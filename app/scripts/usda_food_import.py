"""
usda_food_import.py — USDA FoodData Central → app/ontology/nutrition/food_NN.ak

Converts the USDA FoodData Central SR Legacy dataset to Akasha .ak atoms
for the optional 'nutrition' ontology pack.

SR Legacy has ~8,800 foods (natural and prepared) with full nutrient profiles.
Each atom includes: food name, category, and key nutrients per 100g.

Atom IDs:    food:{category_slug}:{normalized_name}
             e.g. food:fruit:apple_raw_with_skin
Aliases:     food:fdc:{fdcId}
Links:       sys:part_of → food:category:{slug}

Attribution:
    USDA FoodData Central — https://fdc.nal.usda.gov/
    U.S. Department of Agriculture, Agricultural Research Service
    Public domain

Download:
    1. Visit: https://fdc.nal.usda.gov/download-foods.html
    2. Download "SR Legacy" → JSON (zip, ~90 MB)
    3. Unzip: you get a folder with FoodData_Central_sr_legacy_food_json_*.json
       OR a zip with individual food JSON files
    4. Run: python app/scripts/usda_food_import.py --food-json /path/to/sr_legacy_food.json

    Alternative (Foundation Foods, ~1,100 carefully-tested foods):
    Download "Foundation Foods" JSON and run with --food-json.

Usage:
    python app/scripts/usda_food_import.py --food-json /path/to/sr_legacy_food.json
    python app/scripts/usda_food_import.py --food-json /path/to/foundation_food.json --dry-run

Options:
    --food-json FILE   Path to USDA FDC JSON file (SR Legacy or Foundation Foods)
    --out DIR          Output directory (default: app/ontology/nutrition/)
    --chunk-size N     Foods per .ak file (default: 2000)
    --dry-run          Print stats only, write no files

Note: Direct download is not supported as USDA FDC uses dated filenames.
      Visit https://fdc.nal.usda.gov/download-foods.html to get the current link.
"""

import argparse
import json
import os
import re
import sys

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "nutrition")

# Key nutrient IDs to include in description
NUTRIENT_IDS: dict[int, tuple[str, str]] = {
    1008: ('kcal',    'Energy'),
    1003: ('protein', 'Protein'),
    1004: ('fat',     'Fat'),
    1005: ('carbs',   'Carbohydrate'),
    1079: ('fiber',   'Fiber'),
    1087: ('ca',      'Calcium'),
    1093: ('na',      'Sodium'),
    1162: ('vitC',    'Vitamin C'),
}

# USDA food group code → slug + label
# From SR Legacy food category descriptions
CATEGORY_SLUG: dict[str, str] = {
    'dairy and egg products':          'dairy',
    'spices and herbs':                'spice',
    'baby foods':                      'baby_food',
    'fats and oils':                   'fat_oil',
    'poultry products':                'poultry',
    'soups, sauces, and gravies':      'sauce',
    'sausages and luncheon meats':     'processed_meat',
    'breakfast cereals':               'cereal',
    'fruits and fruit juices':         'fruit',
    'pork products':                   'pork',
    'vegetables and vegetable products': 'vegetable',
    'nut and seed products':           'nut_seed',
    'beef products':                   'beef',
    'beverages':                       'beverage',
    'finfish and shellfish products':  'seafood',
    'legumes and legume products':     'legume',
    'lamb, veal, and game products':   'game_meat',
    'baked products':                  'baked',
    'sweets':                          'sweet',
    'cereal grains and pasta':         'grain',
    'fast foods':                      'fast_food',
    'meals, entrees, and side dishes': 'prepared_meal',
    'snacks':                          'snack',
    'ethnic foods':                    'ethnic',
    'restaurant foods':                'restaurant',
    'american indian/alaska native foods': 'indigenous',
}

FILE_HEADER = """\
# {filename}
# USDA FoodData Central (SR Legacy) — https://fdc.nal.usda.gov/ — Public domain
# Generated by app/scripts/usda_food_import.py
# Foods: {food_range}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def normalize(name: str) -> str:
    s = name.lower()
    s = re.sub(r'[,;:\-/\s]+', '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:70]


def category_slug(cat_desc: str) -> str:
    key = cat_desc.lower().strip()
    return CATEGORY_SLUG.get(key, normalize(cat_desc)[:30])


def extract_nutrients(food_nutrients: list) -> dict[int, float]:
    """Extract key nutrient amounts from food's nutrient list."""
    result: dict[int, float] = {}
    for fn in food_nutrients:
        nid = None
        amt = None
        # Handle both direct dicts and nested structures
        if isinstance(fn, dict):
            nutrient = fn.get('nutrient', fn)
            nid = nutrient.get('id') or fn.get('nutrientId')
            amt = fn.get('amount') or fn.get('value')
        if nid is not None and amt is not None and int(nid) in NUTRIENT_IDS:
            try:
                result[int(nid)] = float(amt)
            except (ValueError, TypeError):
                pass
    return result


def nutrient_str(nutrients: dict[int, float]) -> str:
    """Format key nutrients as compact string."""
    parts = []
    if 1008 in nutrients:
        parts.append(f"{nutrients[1008]:.0f} kcal")
    for nid, (slug, label) in NUTRIENT_IDS.items():
        if nid == 1008:
            continue
        if nid in nutrients:
            val = nutrients[nid]
            unit = 'mg' if nid in (1087, 1093, 1162) else 'g'
            if val > 0:
                parts.append(f"{label} {val:.1f}{unit}")
    return ', '.join(parts[:6])  # cap at 6 fields


def parse_foods(path: str) -> list[dict]:
    """
    Parse USDA FDC JSON. Handles SR Legacy and Foundation Foods formats.
    Returns list of food dicts.
    """
    with open(path, encoding='utf-8') as f:
        data = json.load(f)

    # Detect format
    foods_raw: list = []
    if isinstance(data, list):
        foods_raw = data
    elif isinstance(data, dict):
        # Try known top-level keys
        for key in ('SRLegacyFoods', 'FoundationFoods', 'foods', 'Foods'):
            if key in data:
                foods_raw = data[key]
                break
        if not foods_raw:
            # Might be a single food object
            if 'fdcId' in data or 'description' in data:
                foods_raw = [data]

    foods: list[dict] = []
    for item in foods_raw:
        if not isinstance(item, dict):
            continue
        fdc_id = item.get('fdcId') or item.get('fdcid') or item.get('id')
        desc   = (item.get('description') or item.get('name') or '').strip()
        if not fdc_id or not desc:
            continue

        cat_obj  = item.get('foodCategory') or item.get('wweiaFoodCategory') or {}
        cat_desc = ''
        if isinstance(cat_obj, dict):
            cat_desc = cat_obj.get('description') or cat_obj.get('foodCategoryDescription') or ''
        elif isinstance(cat_obj, str):
            cat_desc = cat_obj
        if not cat_desc:
            cat_desc = item.get('foodCategoryDescription', '') or 'other'

        fn_list  = item.get('foodNutrients') or item.get('nutrients') or []
        nutrients = extract_nutrients(fn_list)

        foods.append({
            'id':       str(fdc_id),
            'name':     desc,
            'cat_desc': cat_desc.strip(),
            'cat_slug': category_slug(cat_desc),
            'nutrients': nutrients,
        })

    return foods


def emit_food(fh, food: dict) -> None:
    norm  = normalize(food['name'])
    slug  = food['cat_slug']
    atom  = f"food:{slug}:{norm}"
    alias = f"food:fdc:{food['id']}"
    cat   = f"food:category:{slug}"

    nutr = nutrient_str(food['nutrients'])
    desc = food['name']
    if nutr:
        desc += f" — per 100g: {nutr}"

    fh.write(f'def "{atom}" "{escape_ak(desc[:280])}"\n')
    fh.write(f'al {atom} {alias}\n')
    fh.write(f'ln {atom} {cat} sys:part_of\n')
    fh.write('\n')


def emit_category_anchors(fh, categories: dict[str, str]) -> None:
    """Write category anchor atoms."""
    fh.write('def "food:category" "USDA food categories used in FoodData Central."\n\n')
    for slug, desc in sorted(categories.items()):
        fh.write(f'def "food:category:{slug}" "{escape_ak(desc)}"\n')
        fh.write(f'ln food:category:{slug} food:category sys:part_of\n\n')


def generate(foods: list[dict], out_dir: str, chunk_size: int, dry_run: bool) -> None:
    total     = len(foods)
    num_files = (total + chunk_size - 1) // chunk_size

    # Category summary
    cats: dict[str, str] = {}
    by_cat: dict[str, int] = {}
    for f in foods:
        cats[f['cat_slug']] = f['cat_desc']
        by_cat[f['cat_slug']] = by_cat.get(f['cat_slug'], 0) + 1
    top = sorted(by_cat.items(), key=lambda x: -x[1])[:10]

    print(f"\n  Foods: {total}")
    print(f"  Categories: {len(cats)}")
    for slug, n in top:
        print(f"    {slug}: {n}")
    print(f"  Files: {num_files} × {chunk_size} → food_{{NN}}.ak")

    if dry_run:
        return

    os.makedirs(out_dir, exist_ok=True)

    # First file: category anchors + first chunk
    for i in range(num_files):
        chunk = foods[i * chunk_size:(i + 1) * chunk_size]
        fname = f"food_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, food_range=f"{start}–{end}"))
            if i == 0:
                emit_category_anchors(fh, cats)
            for food in chunk:
                emit_food(fh, food)
        print(f"  {fname}  {len(chunk):5d} foods", flush=True)

    print(f"\n  Total: {total} foods in {num_files} files → {out_dir}/")
    print("\nNext:")
    print("  git add app/ontology/nutrition/ && git commit")
    print("  onto.pack.enable nutrition")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--food-json',  required=True,
                    help='USDA FDC JSON file (SR Legacy or Foundation Foods)')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=2000,
                    help='Foods per .ak file (default: 2000)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    if not os.path.exists(args.food_json):
        print(f"Error: file not found: {args.food_json}")
        print("\nDownload steps:")
        print("  1. Visit: https://fdc.nal.usda.gov/download-foods.html")
        print("  2. Download 'SR Legacy' or 'Foundation Foods' JSON (zip)")
        print("  3. Unzip and pass the .json file with --food-json")
        sys.exit(1)

    print(f'[usda_food_import] Parsing {os.path.basename(args.food_json)} …')
    foods = parse_foods(args.food_json)
    print(f'  {len(foods)} foods loaded')

    if not foods:
        print("No foods found. Check that the JSON file is a valid USDA FDC download.")
        sys.exit(1)

    generate(foods, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
