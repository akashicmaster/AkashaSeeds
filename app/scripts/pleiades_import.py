"""
pleiades_import.py — Pleiades ancient world gazetteer → app/ontology/archaeology/pleiades_NN.ak

Converts the Pleiades Project dataset to Akasha .ak atoms for the
optional 'archaeology' ontology pack.

Pleiades contains ~38,000 ancient Greek, Roman, and Mediterranean world
places (cities, temples, roads, ports, theatres, aqueducts, etc.)
with coordinates, time period coverage, place types, and connections.

Atom IDs:    archeo:place:{pleiades_id}   e.g. archeo:place:423025   (Rome)
Aliases:     archeo:pleiades:{id}         (canonical alias)
Links:       sys:part_of → archeo:place_type:{type}   (settlement, temple, road, …)
             sys:part_of → era:{period}               (if time periods data available)

Attribution:
    Pleiades Project — https://pleiades.stoa.org/
    Editors: Tom Elliott et al.
    CC BY 3.0 — https://creativecommons.org/licenses/by/3.0/

Usage:
    python app/scripts/pleiades_import.py

    python app/scripts/pleiades_import.py --csv /path/to/pleiades-places-latest.csv

    python app/scripts/pleiades_import.py --dry-run

    python app/scripts/pleiades_import.py --min-connections 1  # filter lesser-known sites

Options:
    --csv FILE           Pre-downloaded Pleiades places CSV (may be .gz)
    --out DIR            Output directory (default: app/ontology/archaeology/)
    --chunk-size N       Places per .ak file (default: 2000)
    --min-connections N  Minimum connection count to include (default: 0 = all)
    --dry-run            Print stats only, write no files

Source:
    https://atlantides.org/downloads/pleiades/dumps/pleiades-places-latest.csv.gz
    (~30 MB compressed)
"""

import argparse
import csv
import gzip
import io
import os
import re
import sys
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "archaeology")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "pleiades_cache")

CSV_URL = "https://atlantides.org/downloads/pleiades/dumps/pleiades-places-latest.csv.gz"

# Pleiades time-period codes → era atom IDs
PERIOD_MAP: dict[str, str] = {
    'A':   'era:archaic_greek',
    'C':   'era:classical_greek',
    'H':   'era:hellenistic',
    'R':   'era:roman',
    'L':   'era:late_antique',
    'B':   'era:byzantine',
    'M':   'era:medieval',
    'N':   'era:modern',
    'G':   'era:geometric_greek',
    'E':   'era:early_bronze_age',
    'LBA': 'era:late_bronze_age',
    'MBA': 'era:middle_bronze_age',
    'EBA': 'era:early_bronze_age',
    'IA':  'era:iron_age',
    'PH':  'era:prehistoric',
}

FILE_HEADER = """\
# {filename}
# Pleiades Project — https://pleiades.stoa.org/ — CC BY 3.0
# Generated by app/scripts/pleiades_import.py
# Places: {place_range}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def normalize_type(ft: str) -> str:
    """Normalise a featureType string to an atom name component."""
    s = ft.lower().strip()
    s = re.sub(r'[\s\-/]+', '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    return s[:40]


def fmt_coord(lat: str, lon: str) -> str:
    try:
        la, lo = float(lat), float(lon)
        ns = 'N' if la >= 0 else 'S'
        ew = 'E' if lo >= 0 else 'W'
        return f"{abs(la):.4f}°{ns} {abs(lo):.4f}°{ew}"
    except ValueError:
        return ''


def parse_places(path: str, min_conn: int) -> list[dict]:
    """Parse Pleiades places CSV. Handles .gz transparently."""
    places = []
    opener = gzip.open if path.endswith('.gz') else open
    with opener(path, 'rt', encoding='utf-8', errors='replace') as f:
        reader = csv.DictReader(f)
        for row in reader:
            pid = (row.get('id') or row.get('@id') or '').strip()
            if not pid:
                continue
            title  = (row.get('title') or '').strip()
            if not title:
                continue
            desc   = (row.get('description') or '').strip()[:200]
            lat    = (row.get('representative_lat') or row.get('reprLat') or '').strip()
            lon    = (row.get('representative_lon') or row.get('reprLon') or '').strip()
            ftypes = (row.get('featureTypes') or row.get('featureType') or '').strip()
            times  = (row.get('timePeriods') or row.get('geoContext') or '').strip()
            modern = (row.get('modern_location') or row.get('modernLocation') or '').strip()
            conns  = (row.get('connectsWith') or '').strip()
            conn_count = len(conns.split(',')) if conns else 0

            if conn_count < min_conn:
                continue

            type_list = [normalize_type(t) for t in re.split(r'[,;]', ftypes) if t.strip()] if ftypes else []
            period_codes = [t.strip() for t in re.split(r'[,;\s]+', times) if t.strip()] if times else []

            places.append({
                'id':      pid,
                'title':   title,
                'desc':    desc,
                'lat':     lat,
                'lon':     lon,
                'types':   type_list[:3],
                'periods': period_codes[:6],
                'modern':  modern,
                'conns':   conn_count,
            })
    return places


def emit_place(fh, p: dict, type_set: set) -> None:
    atom  = f"archeo:place:{p['id']}"
    alias = f"archeo:pleiades:{p['id']}"

    parts = [p['title']]
    if p['modern'] and p['modern'].lower() != p['title'].lower():
        parts.append(f"mod. {p['modern']}")
    if p['types']:
        parts.append(', '.join(p['types'][:2]).replace('_', ' '))
    coord = fmt_coord(p['lat'], p['lon'])
    if coord:
        parts.append(coord)
    desc_head = '; '.join(parts)
    if p['desc'] and p['desc'] != p['title']:
        full_desc = f"{desc_head}. {p['desc']}"[:280]
    else:
        full_desc = desc_head[:280]

    fh.write(f'def "{atom}" "{escape_ak(full_desc)}"\n')
    fh.write(f'al {atom} {alias}\n')

    # Place type links
    for ft in p['types']:
        if ft:
            type_atom = f"archeo:place_type:{ft}"
            type_set.add(ft)
            fh.write(f'ln {atom} {type_atom} sys:part_of\n')

    # Time period links
    seen_eras: set[str] = set()
    for code in p['periods']:
        era = PERIOD_MAP.get(code)
        if era and era not in seen_eras:
            fh.write(f'ln {atom} {era} sys:part_of\n')
            seen_eras.add(era)

    fh.write('\n')


def generate(places: list[dict], out_dir: str, chunk_size: int, dry_run: bool) -> None:
    total     = len(places)
    num_files = (total + chunk_size - 1) // chunk_size

    # Gather type stats
    type_counts: dict[str, int] = {}
    for p in places:
        for t in p['types']:
            type_counts[t] = type_counts.get(t, 0) + 1
    top_types = sorted(type_counts.items(), key=lambda x: -x[1])[:10]

    print(f"\n  Places: {total}")
    print(f"  Files:  {num_files} × {chunk_size} → pleiades_{{NN}}.ak")
    print(f"  Top types: " + ', '.join(f"{t}({n})" for t, n in top_types))

    if dry_run:
        return

    os.makedirs(out_dir, exist_ok=True)
    all_types: set[str] = set()

    for i in range(num_files):
        chunk = places[i * chunk_size:(i + 1) * chunk_size]
        fname = f"pleiades_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, place_range=f"{start}–{end}"))
            for p in chunk:
                emit_place(fh, p, all_types)
        print(f"  {fname}  {len(chunk):5d} places", flush=True)

    # Write type namespace anchors to first file
    if all_types:
        types_path = os.path.join(out_dir, "pleiades_types.ak")
        with open(types_path, 'w', encoding='utf-8') as fh:
            fh.write("# pleiades_types.ak — place type namespace anchors\n")
            fh.write("# Pleiades Project — https://pleiades.stoa.org/ — CC BY 3.0\n\n")
            fh.write('def "archeo:place_type" "Archaeological and geographic feature type classification (Pleiades)."\n\n')
            for ft in sorted(all_types):
                label = ft.replace('_', ' ')
                fh.write(f'def "archeo:place_type:{ft}" "{label.capitalize()} (archaeological feature type, Pleiades)"\n')
                fh.write(f'ln archeo:place_type:{ft} archeo:place_type sys:part_of\n\n')
        print(f"  pleiades_types.ak  {len(all_types):5d} types")

    print(f"\n  Total: {total} places in {num_files} files → {out_dir}/")
    print("\nNext:")
    print("  git add app/ontology/archaeology/ && git commit")
    print("  # then: onto.pack.enable archaeology")


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")
    print("(~30 MB compressed, may take a minute)")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_csv(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, 'pleiades-places-latest.csv.gz')
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    _download(CSV_URL, dest, "pleiades-places-latest.csv.gz")
    return dest


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--csv',             help='Pre-downloaded Pleiades places CSV (.gz ok)')
    ap.add_argument('--out',             default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size',      type=int, default=2000,
                    help='Places per .ak file (default: 2000)')
    ap.add_argument('--min-connections', type=int, default=0,
                    help='Minimum connection count to include (default: 0 = all)')
    ap.add_argument('--dry-run',         action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[pleiades_import] Locating CSV …')
    try:
        csv_path = ensure_csv(args.csv)
    except Exception as e:
        print(f'\nError: {e}')
        print(f'\nManual download: {CSV_URL}')
        print('Re-run with: --csv /path/to/pleiades-places-latest.csv.gz')
        sys.exit(1)

    print(f'[pleiades_import] Parsing {os.path.basename(csv_path)} …')
    places = parse_places(csv_path, args.min_connections)
    print(f'  Parsed {len(places)} places')

    generate(places, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
