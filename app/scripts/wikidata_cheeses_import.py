"""
wikidata_cheeses_import.py — Wikidata cheeses → wikidata_cheeses_NN.ak

Queries Wikidata SPARQL for cheese types by country of origin, producing
cheese:wd:* atoms with type and milk-source links.

Atom IDs:    cheese:wd:{normalized_name}   e.g. cheese:wd:camembert
Alias:       cheese:wd:{QID}               e.g. cheese:wd:Q182527
Links:
    sys:part_of → cheese:type:{type_id}    (soft_ripened, washed_rind, blue, hard, fresh, semi_soft)
    sys:part_of → cheese:milk:{milk_id}    (cow, sheep, goat, buffalo)
Sets:
    cheese:wikidata — all cheese atoms

Note: cheese:type:* and cheese:milk:* atoms are assumed to exist already
(defined in gastronomy_concepts.ak or cheese_world.ak).  This script only
creates links to them; it does not redefine them.

Attribution:
    Wikidata — https://www.wikidata.org/
    CC0 1.0 — https://creativecommons.org/publicdomain/zero/1.0/

Usage:
    # Full run (queries Wikidata):
    python app/scripts/wikidata_cheeses_import.py

    # Dry run (stats only, no files written):
    python app/scripts/wikidata_cheeses_import.py --dry-run

    # Custom output directory:
    python app/scripts/wikidata_cheeses_import.py --out out/cheese

    # Use alternate cache dir:
    python app/scripts/wikidata_cheeses_import.py --cache-dir /tmp/wd_cheese_cache

Options:
    --out DIR          Output directory (default: out/wine)
    --chunk-size N     Atoms per .ak file (default: 500)
    --dry-run          Print stats only, write no files
    --cache-dir DIR    Cache directory for SPARQL results (default: out/wikidata_cheeses_cache)
"""

import argparse
import json
import os
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request

SCRIPT_DIR    = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT  = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT   = os.path.join(PROJECT_ROOT, "out", "wine")
DEFAULT_CACHE = os.path.join(PROJECT_ROOT, "out", "wikidata_cheeses_cache")

SPARQL_ENDPOINT = "https://query.wikidata.org/sparql"
USER_AGENT = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

# Countries tried in fallback mode (name for logging, QID for SPARQL)
CHEESE_COUNTRIES = [
    ("France",        "Q142"),
    ("Italy",         "Q38"),
    ("Spain",         "Q29"),
    ("United Kingdom","Q145"),
    ("Netherlands",   "Q55"),
    ("Switzerland",   "Q39"),
    ("Greece",        "Q41"),
    ("Germany",       "Q183"),
    ("Denmark",       "Q35"),
    ("Portugal",      "Q45"),
    ("Belgium",       "Q31"),
    ("Austria",       "Q40"),
    ("United States", "Q30"),
    ("Australia",     "Q408"),
]

QUERY_CHEESES = """\
SELECT ?item ?itemLabel ?country ?countryLabel ?milk ?milkLabel ?type ?typeLabel WHERE {
  ?item wdt:P31/wdt:P279* wd:Q10943 .
  OPTIONAL { ?item wdt:P495 ?country }
  OPTIONAL { ?item wdt:P17 ?country }
  OPTIONAL { ?item wdt:P186 ?milk }
  OPTIONAL { ?item wdt:P31 ?type }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
LIMIT 2000
"""

QUERY_CHEESES_BY_COUNTRY = """\
SELECT ?item ?itemLabel ?country ?countryLabel ?milk ?milkLabel ?type ?typeLabel WHERE {
  ?item wdt:P31/wdt:P279* wd:Q10943 .
  { ?item wdt:P495 wd:%s } UNION { ?item wdt:P17 wd:%s }
  BIND(wd:%s AS ?country)
  OPTIONAL { ?item wdt:P186 ?milk }
  OPTIONAL { ?item wdt:P31 ?type }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
LIMIT 500
"""

FILE_HEADER = """\
# {filename}
# Wikidata — https://www.wikidata.org/ — CC0 1.0
# Generated by app/scripts/wikidata_cheeses_import.py — chunk {chunk_num}
#
"""

# ---------------------------------------------------------------------------
# Label → atom-id mappings
# ---------------------------------------------------------------------------

# Match against lowercase type label fragments
TYPE_MAP: list[tuple[str, str]] = [
    ("soft-ripened",  "soft_ripened"),
    ("soft ripened",  "soft_ripened"),
    ("washed-rind",   "washed_rind"),
    ("washed rind",   "washed_rind"),
    ("blue cheese",   "blue"),
    ("blue-veined",   "blue"),
    ("gorgonzola",    "blue"),   # specific blue subtype
    ("roquefort",     "blue"),   # specific blue subtype
    ("hard cheese",   "hard"),
    ("extra-hard",    "hard"),
    ("semi-hard",     "semi_soft"),
    ("semi hard",     "semi_soft"),
    ("semi-soft",     "semi_soft"),
    ("semi soft",     "semi_soft"),
    ("fresh cheese",  "fresh"),
    ("unripened",     "fresh"),
    ("cream cheese",  "fresh"),
    ("ricotta",       "fresh"),
]

# Match against lowercase milk label fragments
MILK_MAP: list[tuple[str, str]] = [
    ("cow",           "cow"),
    ("cattle",        "cow"),
    ("bovine",        "cow"),
    ("sheep",         "sheep"),
    ("ewe",           "sheep"),
    ("ovine",         "sheep"),
    ("goat",          "goat"),
    ("caprine",       "goat"),
    ("water buffalo", "buffalo"),
    ("buffalo",       "buffalo"),
]


def map_type(label: str) -> str | None:
    ll = label.lower()
    for fragment, atom_id in TYPE_MAP:
        if fragment in ll:
            return atom_id
    return None


def map_milk(label: str) -> str | None:
    ll = label.lower()
    for fragment, atom_id in MILK_MAP:
        if fragment in ll:
            return atom_id
    return None


# ---------------------------------------------------------------------------
# Normalisation
# ---------------------------------------------------------------------------

def normalize(name: str) -> str:
    """Convert label to atom name component: lowercase, NFD→ASCII, underscores."""
    s = unicodedata.normalize('NFD', name)
    s = s.encode('ascii', 'ignore').decode('ascii')
    s = s.lower()
    s = re.sub(r'[\s\-/,.()\[\]\'\"]+', '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:60]


def escape_ak(s: str) -> str:
    """Escape double-quotes and backslashes for .ak def strings."""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def qid_from_uri(uri: str) -> str:
    """Extract QID from a Wikidata entity URI."""
    return uri.rsplit('/', 1)[-1]


def is_real_label(label: str, qid: str) -> bool:
    """Return False if the label is just the QID (Wikidata fallback for missing English labels)."""
    return bool(label) and label != qid


# ---------------------------------------------------------------------------
# SPARQL fetch
# ---------------------------------------------------------------------------

def sparql_query(query: str, label: str) -> list[dict]:
    """Execute a SPARQL query against Wikidata and return the bindings list."""
    params = urllib.parse.urlencode({'query': query, 'format': 'json'})
    url = f"{SPARQL_ENDPOINT}?{params}"
    req = urllib.request.Request(
        url,
        headers={
            'User-Agent': USER_AGENT,
            'Accept': 'application/sparql-results+json',
        }
    )
    print(f"  Querying Wikidata: {label} …", file=sys.stderr)
    with urllib.request.urlopen(req, timeout=90) as resp:
        data = json.loads(resp.read().decode('utf-8'))
    bindings = data['results']['bindings']
    print(f"  → {len(bindings)} results", file=sys.stderr)
    return bindings


def load_or_fetch_cheeses(cache_dir: str) -> list[dict]:
    """Return SPARQL bindings for cheeses, using cache when available."""
    cache_path = os.path.join(cache_dir, 'cheeses.json')
    if os.path.exists(cache_path):
        print(f"[cheeses] Using cached: {cache_path}", file=sys.stderr)
        with open(cache_path, encoding='utf-8') as f:
            return json.load(f)

    os.makedirs(cache_dir, exist_ok=True)

    # Try the single bulk query first
    bindings: list[dict] | None = None
    try:
        bindings = sparql_query(QUERY_CHEESES, "all cheeses")
    except Exception as e:
        if 'timed out' in str(e).lower() or '429' in str(e) or '500' in str(e):
            print(
                f"  Main query timed out ({e}). Falling back to per-country queries …",
                file=sys.stderr,
            )
            bindings = None
        else:
            raise

    if bindings is None:
        bindings = _fetch_cheeses_by_country(cache_dir)

    with open(cache_path, 'w', encoding='utf-8') as f:
        json.dump(bindings, f)
    print(f"  Cached → {cache_path}", file=sys.stderr)
    return bindings


def _fetch_cheeses_by_country(cache_dir: str) -> list[dict]:
    """Fallback: query Wikidata per country and merge results."""
    all_bindings: list[dict] = []
    seen_items: set[str] = set()

    for country_name, country_qid in CHEESE_COUNTRIES:
        country_cache = os.path.join(cache_dir, f'cheeses_{country_qid}.json')
        if os.path.exists(country_cache):
            print(f"  Using cached: {country_cache}", file=sys.stderr)
            with open(country_cache, encoding='utf-8') as f:
                cb = json.load(f)
        else:
            try:
                q = QUERY_CHEESES_BY_COUNTRY % (country_qid, country_qid, country_qid)
                cb = sparql_query(q, f"cheeses — {country_name}")
                time.sleep(1)
            except Exception as exc:
                print(f"  Warning: {country_name} query failed: {exc}", file=sys.stderr)
                continue
            os.makedirs(cache_dir, exist_ok=True)
            with open(country_cache, 'w', encoding='utf-8') as f:
                json.dump(cb, f)

        for b in cb:
            uri = b.get('item', {}).get('value', '')
            if uri not in seen_items:
                seen_items.add(uri)
                all_bindings.append(b)

    return all_bindings


def _print_manual_instructions():
    print("\nManual download steps:", file=sys.stderr)
    print("  1. Open https://query.wikidata.org/ in your browser", file=sys.stderr)
    print("  2. Run the SPARQL query from the script docstring", file=sys.stderr)
    print("  3. Download results as JSON", file=sys.stderr)
    print("  4. Save to:", file=sys.stderr)
    print(f"       {DEFAULT_CACHE}/cheeses.json", file=sys.stderr)
    print("  5. Re-run this script (cache will be used automatically)", file=sys.stderr)


# ---------------------------------------------------------------------------
# Data parsing
# ---------------------------------------------------------------------------

def parse_cheeses(bindings: list[dict]) -> list[dict]:
    """
    Parse SPARQL bindings for cheeses.

    Each Wikidata item may appear multiple times (one row per milk/type combination).
    We collect all distinct milk and type labels per QID before building entries.
    Returns deduplicated list of dicts with keys:
        qid, label, country, milks (list[str]), types (list[str]),
        milk_ids (list[str]), type_ids (list[str]), slug
    """
    # First pass: aggregate per QID
    by_qid: dict[str, dict] = {}
    for b in bindings:
        uri = b.get('item', {}).get('value', '')
        if not uri:
            continue
        qid   = qid_from_uri(uri)
        label = b.get('itemLabel', {}).get('value', '')
        if not is_real_label(label, qid):
            continue

        if qid not in by_qid:
            by_qid[qid] = {
                'qid':     qid,
                'label':   label,
                'country': '',
                'milks':   set(),
                'types':   set(),
            }

        country = b.get('countryLabel', {}).get('value', '')
        if country and not by_qid[qid]['country']:
            by_qid[qid]['country'] = country

        milk_label = b.get('milkLabel', {}).get('value', '')
        if milk_label and is_real_label(milk_label, qid_from_uri(
                b.get('milk', {}).get('value', 'x'))):
            by_qid[qid]['milks'].add(milk_label)

        type_label = b.get('typeLabel', {}).get('value', '')
        if type_label and is_real_label(type_label, qid_from_uri(
                b.get('type', {}).get('value', 'x'))):
            by_qid[qid]['types'].add(type_label)

    # Second pass: resolve slug and mapped IDs
    seen_slugs: dict[str, int] = {}
    results: list[dict] = []

    for qid, info in by_qid.items():
        base_slug = normalize(info['label'])
        if not base_slug:
            continue

        slug = base_slug
        if slug in seen_slugs:
            seen_slugs[slug] += 1
            suffix = chr(ord('b') + seen_slugs[slug] - 1)
            slug = f"{base_slug}_{suffix}"
        else:
            seen_slugs[base_slug] = 0

        milk_ids = []
        for ml in sorted(info['milks']):
            mid = map_milk(ml)
            if mid and mid not in milk_ids:
                milk_ids.append(mid)

        type_ids = []
        for tl in sorted(info['types']):
            tid = map_type(tl)
            if tid and tid not in type_ids:
                type_ids.append(tid)

        results.append({
            'qid':      qid,
            'label':    info['label'],
            'country':  info['country'],
            'milks':    sorted(info['milks']),
            'types':    sorted(info['types']),
            'milk_ids': milk_ids,
            'type_ids': type_ids,
            'slug':     slug,
        })

    return results


# ---------------------------------------------------------------------------
# Emitter
# ---------------------------------------------------------------------------

def emit_cheese(fh, entry: dict) -> None:
    """Write one cheese atom block to fh."""
    atom  = f"cheese:wd:{entry['slug']}"
    alias = f"cheese:wd:{entry['qid']}"
    wd_url = f"https://www.wikidata.org/wiki/{entry['qid']}"

    # Build description
    type_str = entry['types'][0] if entry['types'] else None
    milk_str = entry['milks'][0] if entry['milks'] else None

    cheese_clause = f"{type_str} cheese" if type_str else "cheese"
    origin_clause = f"from {entry['country']}" if entry['country'] else ""
    milk_clause   = f"Milk: {milk_str}." if milk_str else ""

    desc_parts = [entry['label'], f"{cheese_clause}"]
    if origin_clause:
        desc_parts.append(origin_clause)
    desc = f"{', '.join(desc_parts)}. {milk_clause} {wd_url}".strip()

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} {alias}\n')

    for type_id in entry['type_ids']:
        fh.write(f'ln {atom} cheese:type:{type_id} sys:part_of\n')

    for milk_id in entry['milk_ids']:
        fh.write(f'ln {atom} cheese:milk:{milk_id} sys:part_of\n')

    fh.write(f'set.add name="cheese:wikidata" id="{atom}"\n')
    fh.write('\n')


# ---------------------------------------------------------------------------
# Generator
# ---------------------------------------------------------------------------

def generate(
    cheeses: list[dict],
    out_dir: str,
    chunk_size: int,
    dry_run: bool,
) -> None:
    total     = len(cheeses)
    num_files = (total + chunk_size - 1) // chunk_size

    # Count link stats for reporting
    with_type = sum(1 for c in cheeses if c['type_ids'])
    with_milk = sum(1 for c in cheeses if c['milk_ids'])

    print(f"\n  Cheeses:          {total}", file=sys.stderr)
    print(f"  With type links:  {with_type}", file=sys.stderr)
    print(f"  With milk links:  {with_milk}", file=sys.stderr)
    print(f"  Files:            {num_files} × {chunk_size} → wikidata_cheeses_{{NN}}.ak",
          file=sys.stderr)

    if dry_run:
        print("  [dry-run] No files written.", file=sys.stderr)
        return

    os.makedirs(out_dir, exist_ok=True)

    for i in range(num_files):
        chunk = cheeses[i * chunk_size:(i + 1) * chunk_size]
        fname = f"wikidata_cheeses_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, chunk_num=i + 1))
            for entry in chunk:
                emit_cheese(fh, entry)
        print(f"  {fname}  {len(chunk):5d} atoms", file=sys.stderr, flush=True)

    print(f"\n  Total: {total} atoms in {num_files} files → {out_dir}/", file=sys.stderr)
    print(f"\nNext: load the files via akasha.py onto.load dir={out_dir}/", file=sys.stderr)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print stats only, write no files')
    ap.add_argument('--cache-dir',  default=DEFAULT_CACHE,
                    help=f'Cache directory (default: {DEFAULT_CACHE})')
    args = ap.parse_args()

    print('[wikidata_cheeses] Fetching cheeses …', file=sys.stderr)
    try:
        bindings = load_or_fetch_cheeses(args.cache_dir)
    except (urllib.error.URLError, OSError) as e:
        print(f'\nNetwork error: {e}', file=sys.stderr)
        _print_manual_instructions()
        sys.exit(1)

    print('[wikidata_cheeses] Parsing …', file=sys.stderr)
    cheeses = parse_cheeses(bindings)
    print(f'  {len(cheeses)} cheeses after dedup/filter', file=sys.stderr)

    generate(cheeses, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
