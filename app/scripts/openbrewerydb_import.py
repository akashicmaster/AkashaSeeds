#!/usr/bin/env python3
"""
openbrewerydb_import.py — Open Brewery DB → breweries_NN.ak (C-tier drinks pack).

Open Brewery DB is an open dataset of breweries, cideries, brewpubs and bottleshops.
This turns it into an Akasha `.ak` brewery catalogue: one atom per brewery, a small
type taxonomy, and per-country / global sets so the graph is navigable (dive a type,
or list a country set).

Atom IDs:
    brewery:brewery                 root concept
    brewery:type:{type}             micro / brewpub / regional / large / …  (sys:is_a root)
    brewery:{slug}                  one per brewery (name, disambiguated by city/state)
                                    → sys:is_a brewery:type:{type}
Sets:
    breweries                       every brewery
    brewery:in:{country_slug}       breweries by country

Source & license:
    Open Brewery DB — https://www.openbrewerydb.org/  (repo: openbrewerydb/openbrewerydb)
    MIT License — free to redistribute (same license as Akasha). Attribution retained.

Usage:
    python app/scripts/openbrewerydb_import.py                       # fetch + write
    python app/scripts/openbrewerydb_import.py --input breweries.csv # use a local CSV
    python app/scripts/openbrewerydb_import.py --dry-run             # stats only
    python app/scripts/openbrewerydb_import.py --out app/ontology/drinks_c
    python app/scripts/openbrewerydb_import.py --exclude-types planning,closed --limit 3000
"""
import argparse
import csv
import io
import os
import re
import sys
import urllib.request

CSV_URL = ("https://raw.githubusercontent.com/openbrewerydb/openbrewerydb/"
           "master/breweries.csv")

TYPE_GLOSS = {
    "micro":      "Microbrewery — small independent brewery, most beer sold off-site.",
    "nano":       "Nanobrewery — very small-batch brewery.",
    "regional":   "Regional brewery — mid-size, distributes across a region.",
    "brewpub":    "Brewpub — a restaurant/pub that brews its own beer on-site.",
    "large":      "Large brewery — high-volume, national/international distribution.",
    "planning":   "Planning — a brewery in planning, not yet operating.",
    "bar":        "Bar — a bar that serves beer (not primarily a producer).",
    "contract":   "Contract brewery — a business that hires another brewery to make its beer.",
    "proprietor": "Proprietor — a contract-brewing arrangement where the brand owns the recipe.",
    "closed":     "Closed — a brewery that has ceased operations.",
    "taproom":    "Taproom — a producer's on-site tasting room / bar.",
    "cidery":     "Cidery — a producer of cider.",
    "beergarden": "Beer garden — an outdoor venue serving beer.",
    "location":   "Location — a brewery location record.",
}


def slug(s: str) -> str:
    s = (s or "").lower()
    s = re.sub(r"[&/]", " and ", s)
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or "x"


def esc(s: str) -> str:
    """Description body lives inside a double-quoted .ak arg — strip stray quotes."""
    return (s or "").replace('"', "'").replace("\n", " ").strip()


def load_rows(input_path):
    if input_path:
        with open(input_path, encoding="utf-8", errors="replace") as f:
            return list(csv.DictReader(f))
    req = urllib.request.Request(CSV_URL, headers={"User-Agent": "akasha-import"})
    with urllib.request.urlopen(req, timeout=120) as r:
        text = r.read().decode("utf-8", errors="replace")
    return list(csv.DictReader(io.StringIO(text)))


def build(rows, exclude_types, limit):
    lines = [
        "# Open Brewery DB — brewery catalogue (C-tier). Generated by "
        "scripts/openbrewerydb_import.py.",
        "# Source: Open Brewery DB (openbrewerydb/openbrewerydb) — MIT License.",
        "",
        'def "brewery:brewery" "A brewery — a facility that makes beer (醸造所)."',
        "",
    ]
    # type taxonomy (only the types actually present)
    types_present = []
    seen_t = set()
    for r in rows:
        t = (r.get("brewery_type") or "").strip().lower()
        if t and t not in seen_t:
            seen_t.add(t)
            types_present.append(t)
    for t in sorted(types_present):
        if t in exclude_types:
            continue
        lines.append(f'def "brewery:type:{t}" "{esc(TYPE_GLOSS.get(t, t + " brewery."))}"')
        lines.append(f"ln brewery:type:{t} brewery:brewery sys:is_a")
    lines.append("")

    used = {}          # slug -> count, for disambiguation
    n = 0
    countries = set()
    for r in rows:
        t = (r.get("brewery_type") or "").strip().lower()
        if not t or t in exclude_types:
            continue
        name = (r.get("name") or "").strip()
        if not name:
            continue
        city = (r.get("city") or "").strip()
        state = (r.get("state_province") or "").strip()
        country = (r.get("country") or "").strip()
        base = slug(name)
        key = base
        if key in used:                       # disambiguate by city, then state, then counter
            key = f"{base}__{slug(city)}" if city else base
        if key in used:
            key = f"{base}__{slug(city)}_{slug(state)}"
        while key in used:
            used[key] += 1
            key = f"{base}__{used[key]}"
        used[key] = 1

        aid = f"brewery:{key}"
        where = ", ".join(x for x in (city, state, country) if x)
        web = (r.get("website_url") or "").strip()
        desc = f"{name} — {t} brewery" + (f" in {where}" if where else "") + "."
        if web:
            desc += f" {web}"
        lines.append(f'def "{aid}" "{esc(desc)}"')
        lines.append(f"ln {aid} brewery:type:{t} sys:is_a")
        lines.append(f'set.add name="breweries" id="{aid}"')
        if country:
            cs = slug(country)
            countries.add((cs, country))
            lines.append(f'set.add name="brewery:in:{cs}" id="{aid}"')
        n += 1
        if limit and n >= limit:
            break
    return lines, n, sorted(countries)


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", help="local breweries.csv (else fetch from GitHub)")
    ap.add_argument("--out", default="app/ontology/drinks_c")
    ap.add_argument("--exclude-types", default="planning",
                    help="comma-separated brewery types to skip (default: planning)")
    ap.add_argument("--limit", type=int, default=0, help="cap number of breweries (0 = all)")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv[1:])

    exclude = {t.strip().lower() for t in args.exclude_types.split(",") if t.strip()}
    rows = load_rows(args.input)
    lines, n, countries = build(rows, exclude, args.limit)
    print(f"breweries: {n}  |  countries: {len(countries)}  |  excluded types: "
          f"{sorted(exclude) or 'none'}")
    if args.dry_run:
        print("\n".join(lines[:24]))
        return 0
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "breweries.ak")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}  ({os.path.getsize(path)//1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
