"""
worldstats_import.py — flow real country statistics into the fact:* axis.

Reads a CSV of (iso3, dimension, value, unit, year, source) and emits an .ak that
links each geo:country:<ISO3> to a value atom via its fact:<dimension> relation:

    def "geostat:JPN:population" "124,516,650 people (2023) — World Bank SP.POP.TOTL"
    ln geo:country:JPN geostat:JPN:population fact:population

Values are stored as atoms (not bare numbers) so they carry provenance in the
description and are queryable through the graph — content-addressed, idempotent,
re-runnable as new data arrives. The fact:* dimensions themselves live in
app/ontology/world/facts_products.ak.

Data sources (public, ISO3-keyed — fetch the full set and drop into a CSV):
  - World Bank Open Data   https://data.worldbank.org  (indicators: SP.POP.TOTL
    population, NY.GDP.MKTP.CD GDP, AG.LND.TOTL.K2 area, SP.DYN.LE00.IN life exp.)
  - UN Data                https://data.un.org
  - Our World in Data      https://ourworldindata.org

Usage:
    python app/scripts/worldstats_import.py app/scripts/data/worldstats_sample.csv \
           app/ontology/world/geostats.ak
"""
import csv, sys, os

KNOWN_DIMS = {"population","area","gdp","gdp_per_capita","hdi","life_expectancy",
              "literacy_rate","currency","official_language","major_export","climate_zone"}

def group(num):
    try:
        return f"{int(float(num)):,}"
    except ValueError:
        return num

def main(csv_path, out_path):
    rows = list(csv.DictReader(open(csv_path, newline="")))
    lines = ["# Akasha ontology (world pack) — country statistics (fact:* values).",
             f"# Generated by app/scripts/worldstats_import.py from {os.path.basename(csv_path)}.",
             "# Each value links geo:country:<ISO3> → geostat:<ISO3>:<dim> via fact:<dim>.",
             "# Regenerate to refresh; content-addressed atoms make it idempotent.", ""]
    seen, skipped = set(), []
    for r in rows:
        iso, dim = r["iso3"].strip().upper(), r["dimension"].strip().lower()
        if dim not in KNOWN_DIMS:
            skipped.append((iso, dim)); continue
        val, unit = group(r["value"].strip()), r.get("unit","").strip()
        year, src = r.get("year","").strip(), r.get("source","").strip()
        desc = f"{val}{(' '+unit) if unit else ''}"
        if year: desc += f" ({year})"
        if src:  desc += f" — {src}"
        key = f"geostat:{iso}:{dim}"
        if key in seen: continue
        seen.add(key)
        lines.append(f'def "{key}" "{desc.replace(chr(34), chr(39))}"')
        lines.append(f"ln geo:country:{iso} {key} fact:{dim}")
    open(out_path, "w").write("\n".join(lines) + "\n")
    print(f"[worldstats] wrote {len(seen)} values → {out_path}")
    if skipped:
        print(f"[worldstats] skipped {len(skipped)} rows with unknown dimensions "
              f"(add to KNOWN_DIMS / facts_products.ak): {sorted(set(d for _,d in skipped))}")

if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("usage: worldstats_import.py <in.csv> <out.ak>"); sys.exit(1)
    main(sys.argv[1], sys.argv[2])
