"""
avalon_codes_import.py — Avalon Project (Yale Law) → app/ontology/law/avalon_NN.ak

Fetches the index page of the Avalon Project at Yale Law School
(https://avalon.law.yale.edu/) and extracts links to historical legal documents
grouped by time period (Ancient, Medieval, 18th Century, etc.).

Each document becomes an Akasha .ak atom in app/ontology/law/.

Atom IDs:    law:doc:{norm_title}        e.g. law:doc:magna_carta
Aliases:     law:avalon:{url_slug}       e.g. law:avalon:magna_carta
Links:       ln law:doc:{norm_title} law:code sys:part_of
Sets:        ontology.law_documents

Attribution:
    The Avalon Project — Yale Law School
    https://avalon.law.yale.edu/

Usage:
    # Fetch index from avalon.law.yale.edu automatically:
    python app/scripts/avalon_codes_import.py

    # Use pre-downloaded HTML:
    python app/scripts/avalon_codes_import.py --html out/avalon_cache/index.html

    # Dry run (print first 20 lines, no files written):
    python app/scripts/avalon_codes_import.py --dry-run

    # Override output directory:
    python app/scripts/avalon_codes_import.py --out app/ontology/law/

Options:
    --html FILE       Pre-downloaded Avalon index HTML
    --out DIR         Output directory (default: app/ontology/law/)
    --chunk-size N    Atoms per .ak file (default: 500)
    --dry-run         Print first 20 lines, write no files

Source:
    https://avalon.law.yale.edu/
    User-Agent: AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)
"""

import argparse
import html as html_module
import os
import re
import sys
import unicodedata
import urllib.error
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "law")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "avalon_cache")
CACHE_FILE   = os.path.join(CACHE_DIR, "index.html")

AVALON_BASE = "https://avalon.law.yale.edu/"

USER_AGENT = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

FILE_HEADER = """\
# {filename}
# The Avalon Project — Yale Law School — https://avalon.law.yale.edu/
# Historical legal documents
# Generated by app/scripts/avalon_codes_import.py
# Entries: {entry_range}
#
"""

NAMESPACE_ANCHOR = """\
# Namespace anchor — historical legal codes and documents
def "law:code" "Namespace anchor for historical legal codes and documents"

"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n - 1].rsplit(' ', 1)[0].rstrip(' ,;') + '…'


def normalize_title(title: str, max_chars: int = 70) -> str:
    """Convert document title to atom ID component (lowercase, ASCII, underscored)."""
    s = unicodedata.normalize('NFKD', title)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = s.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def url_slug(path: str) -> str:
    """Extract a slug from the last path component of a URL, stripping extension."""
    part = path.rstrip('/').rsplit('/', 1)[-1]
    part = re.sub(r'\.[a-z]{2,5}$', '', part, flags=re.IGNORECASE)
    part = re.sub(r'[^a-zA-Z0-9_\-]', '_', part)
    part = re.sub(r'_+', '_', part).strip('_')
    return part.lower()[:80]


def fetch_html() -> str:
    """Fetch the Avalon index page; cache it locally."""
    os.makedirs(CACHE_DIR, exist_ok=True)

    if os.path.exists(CACHE_FILE):
        eprint(f'[avalon_codes_import] Using cached: {CACHE_FILE}')
        with open(CACHE_FILE, encoding='utf-8', errors='replace') as f:
            return f.read()

    eprint('[avalon_codes_import] Fetching Avalon Project index …')
    eprint(f'  URL: {AVALON_BASE}')

    req = urllib.request.Request(
        AVALON_BASE,
        headers={'User-Agent': USER_AGENT},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            raw = resp.read()
        # Try UTF-8, fallback to latin-1
        try:
            content = raw.decode('utf-8')
        except UnicodeDecodeError:
            content = raw.decode('latin-1')
        with open(CACHE_FILE, 'w', encoding='utf-8') as f:
            f.write(content)
        eprint(f'  Cached to {CACHE_FILE}')
        return content
    except urllib.error.URLError as e:
        raise


def strip_tags(s: str) -> str:
    """Remove HTML tags from a string."""
    return re.sub(r'<[^>]+>', '', s)


def clean_text(s: str) -> str:
    """Decode HTML entities, strip tags, collapse whitespace."""
    s = html_module.unescape(s)
    s = strip_tags(s)
    s = re.sub(r'\s+', ' ', s).strip()
    return s


def parse_documents(html: str) -> list[dict]:
    """
    Parse the Avalon index page to extract document links and their time-period
    headings. Returns a list of dicts with keys: title, path, period.

    Strategy: scan for headings (h2/h3/h4) to detect period names, then collect
    anchor tags whose href points to Avalon document paths.
    """
    documents: list[dict] = []
    seen_paths: set[str] = set()

    # Split into lines for sequential processing
    # We parse with a simple state machine to avoid needing BeautifulSoup.

    current_period = 'General'

    # Detect headings: <h2>…</h2>, <h3>…</h3>, <h4>…</h4>
    heading_re = re.compile(
        r'<h[234][^>]*>(.*?)</h[234]>',
        re.IGNORECASE | re.DOTALL,
    )
    # Detect anchor links
    anchor_re = re.compile(
        r'<a\s[^>]*href=["\']([^"\']+)["\'][^>]*>(.*?)</a>',
        re.IGNORECASE | re.DOTALL,
    )

    # We process the HTML in order, updating current_period at headings
    # and collecting links between them.
    # Use re.split to tokenize into heading and non-heading segments.
    segments = re.split(r'(<h[234][^>]*>.*?</h[234]>)', html,
                        flags=re.IGNORECASE | re.DOTALL)

    for seg in segments:
        # Check if this segment is a heading
        hm = heading_re.match(seg)
        if hm:
            period_text = clean_text(hm.group(1))
            if period_text and len(period_text) < 120:
                current_period = period_text
            continue

        # Otherwise, look for document links in this segment
        for am in anchor_re.finditer(seg):
            href  = am.group(1).strip()
            label = clean_text(am.group(2))

            if not label or not href:
                continue

            # Skip navigation, empty anchors, external links, mailto
            if href.startswith('#') or href.startswith('mailto:'):
                continue
            if href.startswith('http') and not href.startswith(AVALON_BASE):
                continue

            # Normalise to a relative path under avalon.law.yale.edu
            if href.startswith(AVALON_BASE):
                rel_path = href[len(AVALON_BASE):].lstrip('/')
            elif href.startswith('http'):
                continue
            else:
                rel_path = href.lstrip('/')

            # Must look like a document path (contains a slash or extension)
            if not rel_path:
                continue

            # Skip purely navigational targets (e.g. js:, /)
            if rel_path in ('/', '') or re.match(r'^javascript:', rel_path, re.I):
                continue

            # Require the path to look like a document or directory
            # (has a '/' or ends with .htm/.html/.asp/.pdf or similar)
            if not (
                '/' in rel_path
                or re.search(r'\.(html?|asp|pdf|txt|xml)$', rel_path, re.I)
            ):
                continue

            # Deduplicate by path
            if rel_path in seen_paths:
                continue
            seen_paths.add(rel_path)

            # Skip very short labels that are likely navigation artefacts
            if len(label) < 4:
                continue

            full_url = AVALON_BASE + rel_path

            documents.append({
                'title':    label,
                'path':     rel_path,
                'full_url': full_url,
                'period':   current_period,
            })

    eprint(f'  {len(documents):,} document links found')
    return documents


def build_description(doc: dict) -> str:
    """Build ≤280-char description string for a document atom."""
    title  = doc['title']
    period = doc['period']
    url    = doc['full_url']

    parts = [title]
    if period and period.lower() not in ('general', 'home', 'main', 'navigation'):
        parts.append(period)
    parts.append('historical legal document')
    body = '; '.join(parts)
    desc = f"{body}. {url}"
    return truncate(desc, 280)


def emit_doc_block(doc: dict, norm: str, slug: str) -> list[str]:
    """Return list of .ak lines for one Avalon document."""
    atom  = f"law:doc:{norm}"
    alias = f"law:avalon:{slug}"
    desc  = build_description(doc)
    return [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
        f'ln {atom} law:code sys:part_of',
        f'set.add name="ontology.law_documents" id="{atom}"',
        '',
    ]


def assign_keys(documents: list[dict]) -> list[dict]:
    """
    Assign unique atom_key and slug to each document.
    Resolves collisions by appending _2, _3, etc.
    """
    seen_norms: dict[str, int] = {}
    seen_slugs: dict[str, int] = {}

    for doc in documents:
        base_norm = normalize_title(doc['title'])
        base_slug = url_slug(doc['path'])

        # Resolve norm collision
        if base_norm in seen_norms:
            seen_norms[base_norm] += 1
            norm = f"{base_norm}_{seen_norms[base_norm]}"
        else:
            seen_norms[base_norm] = 1
            norm = base_norm

        # Resolve slug collision
        if base_slug in seen_slugs:
            seen_slugs[base_slug] += 1
            slug = f"{base_slug}_{seen_slugs[base_slug]}"
        else:
            seen_slugs[base_slug] = 1
            slug = base_slug

        doc['atom_key'] = norm
        doc['slug']     = slug

    return documents


def generate(documents: list[dict], out_dir: str, chunk_size: int,
             dry_run: bool) -> None:
    total   = len(documents)
    n_files = (total + chunk_size - 1) // chunk_size if total else 0

    eprint(f'\n  Documents:  {total:,}')
    eprint(f'  Files:      {n_files} × {chunk_size} → avalon_{{NN}}.ak')
    eprint(f'  Output:     {out_dir}/')

    # Build all output lines
    all_lines: list[str] = []
    for doc in documents:
        all_lines.extend(emit_doc_block(doc, doc['atom_key'], doc['slug']))

    if dry_run:
        print('# --- DRY RUN: first 20 output lines ---')
        count = 0
        for line in NAMESPACE_ANCHOR.splitlines():
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        for line in all_lines:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    if total == 0:
        eprint('[avalon_codes_import] No documents to write.')
        return

    os.makedirs(out_dir, exist_ok=True)

    # Split into per-document blocks (each terminated by a blank line)
    blocks: list[list[str]] = []
    current: list[str] = []
    for line in all_lines:
        current.append(line)
        if line == '':
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    n_chunks = (len(blocks) + chunk_size - 1) // chunk_size
    for i in range(n_chunks):
        chunk_blocks = blocks[i * chunk_size:(i + 1) * chunk_size]
        fname  = f"avalon_{i + 1:02d}.ak"
        fpath  = os.path.join(out_dir, fname)
        start  = i * chunk_size + 1
        end    = start + len(chunk_blocks) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, entry_range=f"{start}–{end}"))
            if i == 0:
                fh.write(NAMESPACE_ANCHOR)
            for block in chunk_blocks:
                fh.write('\n'.join(block) + '\n')
        eprint(f'  {fname}  {len(chunk_blocks):5d} entries', flush=True)

    eprint(f'\n  Total: {total:,} documents in {n_chunks} files → {out_dir}/')
    eprint('\nNext: git add app/ontology/law/avalon_*.ak && git commit')


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--html',       help='Pre-downloaded Avalon index HTML')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print first 20 lines, write no files')
    args = ap.parse_args()

    if args.html:
        eprint(f'[avalon_codes_import] Loading --html {args.html} …')
        with open(args.html, encoding='utf-8', errors='replace') as f:
            html = f.read()
    else:
        try:
            html = fetch_html()
        except urllib.error.URLError as e:
            eprint(f'\nError: Could not fetch Avalon index — {e}')
            eprint('\nManual download:')
            eprint('  Visit https://avalon.law.yale.edu/')
            eprint(f'  Save the page as: {CACHE_FILE}')
            eprint('  Then run: python app/scripts/avalon_codes_import.py --html out/avalon_cache/index.html')
            sys.exit(1)
        except Exception as e:
            eprint(f'\nError: {e}')
            eprint('\nManual download:')
            eprint('  Visit https://avalon.law.yale.edu/')
            eprint(f'  Save the page as: {CACHE_FILE}')
            eprint('  Then run: python app/scripts/avalon_codes_import.py --html out/avalon_cache/index.html')
            sys.exit(1)

    eprint('[avalon_codes_import] Parsing document links …')
    documents = parse_documents(html)

    if not documents:
        eprint('No document links found. The page structure may have changed.')
        eprint('Try: python app/scripts/avalon_codes_import.py --html out/avalon_cache/index.html')
        sys.exit(0)

    documents = assign_keys(documents)
    generate(documents, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
