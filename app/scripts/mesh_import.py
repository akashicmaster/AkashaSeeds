"""
mesh_import.py — NLM MeSH descriptor XML → app/ontology/medicine/*.ak

Converts NLM Medical Subject Headings (MeSH) descriptors to Akasha .ak
ontology files for the medicine/ optional pack.

Atom IDs:    med:{cat}:{normalized_name}   e.g. med:dis:diabetes_mellitus
UI alias:    med:mesh:{DescriptorUI}       e.g. med:mesh:D003924
Links:       sys:part_of to parent in MeSH tree hierarchy

Categories included by default (--categories):
    A  anat  Anatomy
    B  org   Organisms
    C  dis   Diseases and Conditions
    E  tech  Analytical, Diagnostic and Therapeutic Techniques
    F  psy   Psychiatry and Psychology
    G  phys  Phenomena and Processes
    H  occ   Disciplines and Occupations
    I  soc   Anthropology, Education, Sociology
    J  ind   Technology, Industry, Agriculture
    K  hum   Humanities
    L  info  Information Science
    M  grp   Named Groups
    N  care  Health Care

Excluded by default:
    D  chem  Chemicals and Drugs  (overlaps chem: namespace; ~15K bulk entries)
    V        Publication Characteristics  (not useful for knowledge graph)
    Z        Geographicals  (use geo: namespace instead)

Usage:
    # Download and convert (requires nlmpubs.nlm.nih.gov in network allowlist):
    python app/scripts/mesh_import.py

    # Use a pre-downloaded file:
    python app/scripts/mesh_import.py --xml /path/to/desc2024.xml

    # Dry run (stats only, no files written):
    python app/scripts/mesh_import.py --xml /path/to/desc2024.xml --dry-run

    # Also include Chemicals (D category):
    python app/scripts/mesh_import.py --categories A,B,C,D,E,F,G,H,I,J,K,L,M,N

    # Custom output directory:
    python app/scripts/mesh_import.py --out /tmp/mesh_out/

Options:
    --xml FILE          Pre-downloaded MeSH descriptor XML file
    --year N            MeSH year for download (default: 2024)
    --out DIR           Output directory (default: app/ontology/medicine/)
    --chunk-size N      Atoms per .ak file (default: 2000)
    --categories LIST   Comma-separated category letters (default: A-N excl. D,V,Z)
    --dry-run           Print stats only, write no files

Attribution:
    Medical Subject Headings (MeSH), National Library of Medicine (NLM)
    https://www.nlm.nih.gov/mesh/
    Public Domain — no restrictions on use
"""

import argparse
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "medicine")

DOWNLOAD_URL = "https://nlmpubs.nlm.nih.gov/projects/mesh/MESH_FILES/xmlmesh/desc{year}.xml"

# Category letter → namespace short code + label
CATEGORY_INFO = {
    'A': ('anat',  'Anatomy'),
    'B': ('org',   'Organisms'),
    'C': ('dis',   'Diseases and Conditions'),
    'D': ('chem',  'Chemicals and Drugs'),
    'E': ('tech',  'Analytical, Diagnostic and Therapeutic Techniques'),
    'F': ('psy',   'Psychiatry and Psychology'),
    'G': ('phys',  'Phenomena and Processes'),
    'H': ('occ',   'Disciplines and Occupations'),
    'I': ('soc',   'Anthropology, Education, Sociology'),
    'J': ('ind',   'Technology, Industry, Agriculture'),
    'K': ('hum',   'Humanities'),
    'L': ('info',  'Information Science'),
    'M': ('grp',   'Named Groups'),
    'N': ('care',  'Health Care'),
    'V': ('pub',   'Publication Characteristics'),
    'Z': ('geo',   'Geographicals'),
}

DEFAULT_CATEGORIES = set('ABCEFGHIJKLMN')  # exclude D, V, Z

FILE_HEADER = """\
# {filename}
# Medical Subject Headings (MeSH), National Library of Medicine (NLM)
# https://www.nlm.nih.gov/mesh/ — Public Domain
# Generated by app/scripts/mesh_import.py
# Atoms: {atom_range}
#
"""


def normalize(name: str) -> str:
    """Convert MeSH descriptor name to atom name component."""
    s = name.lower()
    s = re.sub(r'[,\s]+', '_', s)         # comma/space → underscore
    s = re.sub(r'[^a-z0-9_]', '', s)      # strip other chars
    s = re.sub(r'_+', '_', s).strip('_')  # collapse underscores
    return s[:64]


def primary_category(tree_numbers: list[str]) -> str | None:
    """Return the single-letter category of the first tree number."""
    for tn in tree_numbers:
        cat = tn[0] if tn else ''
        if cat in CATEGORY_INFO:
            return cat
    return None


def parent_tree_number(tn: str) -> str | None:
    """Return the parent tree number (strip last .segment), or None for roots."""
    idx = tn.rfind('.')
    return tn[:idx] if idx > 0 else None


def truncate(text: str, maxlen: int = 280) -> str:
    """Truncate to maxlen chars, breaking at a word boundary."""
    if len(text) <= maxlen:
        return text
    cut = text[:maxlen].rsplit(' ', 1)[0]
    return cut + '…'


def escape_ak(s: str) -> str:
    """Escape double-quotes and backslashes for .ak def strings."""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def parse_mesh_xml(xml_path: str, categories: set[str]) -> list[dict]:
    """
    Parse MeSH descriptor XML using iterparse (memory-efficient for large files).
    Returns list of descriptor dicts with keys:
        ui, name, tree_numbers, scope_note, entry_terms
    filtered to the given category set.
    """
    descriptors = []
    count_total = 0
    count_included = 0

    context = ET.iterparse(xml_path, events=("start", "end"))
    _, root = next(context)

    current: dict | None = None

    for event, elem in context:
        tag = elem.tag

        if event == "start" and tag == "DescriptorRecord":
            current = {
                "ui": "",
                "name": "",
                "tree_numbers": [],
                "scope_note": "",
                "entry_terms": [],
            }

        elif event == "end" and current is not None:
            if tag == "DescriptorUI":
                current["ui"] = (elem.text or "").strip()
            elif tag == "DescriptorName":
                s = elem.find("String")
                if s is not None:
                    current["name"] = (s.text or "").strip()
            elif tag == "TreeNumber":
                tn = (elem.text or "").strip()
                if tn:
                    current["tree_numbers"].append(tn)
            elif tag == "ScopeNote":
                current["scope_note"] = truncate((elem.text or "").strip())
            elif tag == "Term":
                s = elem.find("String")
                pref = elem.get("ConceptPreferredTermYN", "N")
                if s is not None and pref != "Y":
                    t = (s.text or "").strip()
                    if t and t != current["name"]:
                        current["entry_terms"].append(t)

            elif tag == "DescriptorRecord":
                count_total += 1
                cat = primary_category(current["tree_numbers"])
                if cat and cat in categories:
                    count_included += 1
                    descriptors.append(current)
                current = None
                root.clear()  # free memory

    print(f"  Total descriptors in XML: {count_total}")
    print(f"  Included ({','.join(sorted(categories))}): {count_included}")
    return descriptors


def build_tree_map(descriptors: list[dict]) -> dict[str, str]:
    """Build tree_number → atom_id mapping for link resolution."""
    tree_map: dict[str, str] = {}
    for d in descriptors:
        cat = primary_category(d["tree_numbers"])
        if not cat:
            continue
        ns, _ = CATEGORY_INFO[cat]
        atom_id = f"med:{ns}:{normalize(d['name'])}"
        for tn in d["tree_numbers"]:
            tree_map[tn] = atom_id
    return tree_map


def emit_descriptor(fh, d: dict, tree_map: dict[str, str]) -> int:
    """Write one descriptor to fh. Returns number of lines written."""
    cat = primary_category(d["tree_numbers"])
    if not cat:
        return 0
    ns, _ = CATEGORY_INFO[cat]
    name_part = normalize(d["name"])
    atom_id   = f"med:{ns}:{name_part}"
    ui_alias  = f"med:mesh:{d['ui']}"

    desc = d["scope_note"] or d["name"]

    lines = 0
    fh.write(f'def "{atom_id}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom_id} {ui_alias}\n')
    lines += 2

    # Parent link (sys:part_of) for each tree number that has a parent
    seen_parents: set[str] = set()
    for tn in d["tree_numbers"]:
        ptn = parent_tree_number(tn)
        if ptn and ptn in tree_map:
            parent_id = tree_map[ptn]
            if parent_id != atom_id and parent_id not in seen_parents:
                fh.write(f'ln {atom_id} {parent_id} sys:part_of\n')
                seen_parents.add(parent_id)
                lines += 1

    fh.write('\n')
    return lines + 1


def generate(descriptors: list[dict], out_dir: str, chunk_size: int, dry_run: bool):
    tree_map = build_tree_map(descriptors)

    total = len(descriptors)
    num_files = (total + chunk_size - 1) // chunk_size
    print(f"\n  Atoms to write: {total}")
    print(f"  Files: {num_files} × {chunk_size} → mesh_{{NN}}.ak")

    if dry_run:
        # Count links
        link_count = 0
        for d in descriptors:
            for tn in d["tree_numbers"]:
                ptn = parent_tree_number(tn)
                if ptn and ptn in tree_map:
                    link_count += 1
        print(f"  sys:part_of links: {link_count}")
        return

    os.makedirs(out_dir, exist_ok=True)
    written_files = []

    for file_idx in range(num_files):
        chunk = descriptors[file_idx * chunk_size:(file_idx + 1) * chunk_size]
        fname = f"mesh_{file_idx + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = file_idx * chunk_size + 1
        end   = start + len(chunk) - 1

        with open(fpath, "w", encoding="utf-8") as fh:
            fh.write(FILE_HEADER.format(filename=fname, atom_range=f"{start}–{end}"))
            for d in chunk:
                emit_descriptor(fh, d, tree_map)

        written_files.append((fname, len(chunk)))
        print(f"  {fname}  {len(chunk):5d} atoms", flush=True)

    total_written = sum(c for _, c in written_files)
    print(f"\n  Total: {total_written} atoms in {len(written_files)} files → {out_dir}/")
    print("\nNext: commit files and run: onto.pack.enable medicine")


def download_xml(year: int, dest: str) -> str:
    url = DOWNLOAD_URL.format(year=year)
    print(f"Downloading {url} …")
    print("(This is a large file ~300MB — may take several minutes)")
    dest_path = os.path.join(dest, f"desc{year}.xml")
    os.makedirs(dest, exist_ok=True)

    def _progress(block_num, block_size, total_size):
        if total_size > 0:
            pct = min(100, block_num * block_size * 100 // total_size)
            print(f"\r  {pct}%", end="", flush=True)

    urllib.request.urlretrieve(url, dest_path, _progress)
    print(f"\nSaved to {dest_path}")
    return dest_path


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--xml",        help="Pre-downloaded MeSH descriptor XML file")
    ap.add_argument("--year",       type=int, default=2024,
                    help="MeSH year for download (default: 2024)")
    ap.add_argument("--out",        default=DEFAULT_OUT,
                    help=f"Output directory (default: {DEFAULT_OUT})")
    ap.add_argument("--chunk-size", type=int, default=2000,
                    help="Atoms per .ak file (default: 2000)")
    ap.add_argument("--categories", default=",".join(sorted(DEFAULT_CATEGORIES)),
                    help="Category letters to include (default: A,B,C,E,F,G,H,I,J,K,L,M,N)")
    ap.add_argument("--dry-run",    action="store_true",
                    help="Print stats only, write no files")
    args = ap.parse_args()

    categories = set(c.strip().upper() for c in args.categories.split(',') if c.strip())
    unknown = categories - set(CATEGORY_INFO)
    if unknown:
        print(f"Unknown categories: {unknown}")
        sys.exit(1)

    print("[mesh_import] Category plan:")
    for cat in sorted(categories):
        ns, label = CATEGORY_INFO[cat]
        print(f"  {cat}  med:{ns}:*  {label}")

    # Locate or download XML
    xml_path = args.xml
    if not xml_path:
        cache_dir = os.path.join(PROJECT_ROOT, "out", "mesh_cache")
        cached = os.path.join(cache_dir, f"desc{args.year}.xml")
        if os.path.exists(cached):
            print(f"\nUsing cached file: {cached}")
            xml_path = cached
        else:
            try:
                xml_path = download_xml(args.year, cache_dir)
            except Exception as e:
                print(f"\nDownload failed: {e}")
                print("\nTo use a pre-downloaded file:")
                print(f"  1. Download from: {DOWNLOAD_URL.format(year=args.year)}")
                print(f"  2. Re-run with: --xml /path/to/desc{args.year}.xml")
                sys.exit(1)

    print(f"\n[mesh_import] Parsing {os.path.basename(xml_path)} …")
    descriptors = parse_mesh_xml(xml_path, categories)

    print("\n[mesh_import] Category breakdown:")
    by_cat: dict[str, int] = {}
    for d in descriptors:
        cat = primary_category(d["tree_numbers"]) or '?'
        by_cat[cat] = by_cat.get(cat, 0) + 1
    for cat in sorted(by_cat):
        ns, label = CATEGORY_INFO.get(cat, ('?', '?'))
        print(f"  {cat}  med:{ns}:*  {by_cat[cat]:5d}  {label}")

    generate(descriptors, args.out, args.chunk_size, args.dry_run)


if __name__ == "__main__":
    main()
