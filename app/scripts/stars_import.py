FILE_HEADER = """\
# {filename}
# Yale Bright Star Catalogue 5th ed. — Hoffleit & Warren (1991) — Public domain
# https://heasarc.gsfc.nasa.gov/W3Browse/star-catalog/bsc5p.html
# Generated by app/scripts/stars_import.py
# Stars: {star_range}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def parse_bsc5(path: str) -> list[dict]:
    """
    Parse BSC5 fixed-width catalog. Returns list of star dicts.
    BSC5 record format (key fields):
        cols 1-4    HR number
        cols 5-14   HD number
        cols 26-31  Constellation abbreviation + number (e.g. "Ori  ")
        cols 76-77  RA hours (J2000)
        cols 78-79  RA minutes
        cols 80-83  RA seconds
        cols 84     Dec sign
        cols 85-86  Dec degrees
        cols 87-88  Dec arcmin
        cols 89-90  Dec arcsec
        cols 103-107 Visual magnitude (V, 5 chars, may include decimal)
        cols 130-147 Spectral type
    All columns are 1-indexed in the BSC5 docs; Python slices are 0-indexed.
    """
    stars = []

    opener = gzip.open if path.endswith('.gz') else open
    with opener(path, 'rt', encoding='ascii', errors='replace') as f:
        for line in f:
            if len(line) < 100:
                continue
            hr_str = line[0:4].strip()
            if not hr_str or not hr_str.isdigit():
                continue
            hr = int(hr_str)

            hd_str = line[4:14].strip()
            hd = int(hd_str) if hd_str.isdigit() else None

            # Constellation from Bayer/Flamsteed field (cols 11-14 approx)
            # Actually the constellation is embedded in cols 11-14 as 3-letter abbrev
            con_raw = line[11:14].strip().lower() if len(line) > 14 else ''

            # RA: cols 75-82 (0-indexed), Dec: cols 83-89
            try:
                ra_h  = int(line[75:77])
                ra_m  = int(line[77:79])
                ra_s  = float(line[79:83])
                dec_s = line[83]
                dec_d = int(line[84:86])
                dec_m = int(line[86:88])
                dec_sa = int(line[88:90])
                ra_deg  = ra_h * 15 + ra_m * 0.25 + ra_s * (15 / 3600)
                dec_deg = (dec_d + dec_m / 60 + dec_sa / 3600) * (-1 if dec_s == '-' else 1)
            except (ValueError, IndexError):
                ra_deg, dec_deg = None, None

            # Visual magnitude (cols 102-106, 0-indexed)
            try:
                vmag = float(line[102:107].strip())
            except (ValueError, IndexError):
                vmag = None

            # Spectral type (cols 129-146)
            spec = line[129:147].strip() if len(line) > 147 else ''

            common = IAU_STAR_NAMES.get(hr)

            stars.append({
                'hr':      hr,
                'hd':      hd,
                'con':     con_raw,
                'ra':      ra_deg,
                'dec':     dec_deg,
                'vmag':    vmag,
                'spec':    spec,
                'common':  common,
            })

    return stars


def fmt_coord_eq(ra: float | None, dec: float | None) -> str:
    if ra is None or dec is None:
        return ''
    dec_s = '+' if dec >= 0 else '-'
    return f"RA {ra:.4f}° Dec {dec_s}{abs(dec):.4f}°"


def emit_star(fh, s: dict) -> None:
    """Write one star atom to fh."""
    hr     = s['hr']
    atom   = f"astro:star:hr{hr}"
    vmag   = f"mag {s['vmag']:+.2f}" if s['vmag'] is not None else ''
    coord  = fmt_coord_eq(s['ra'], s['dec'])
    spec   = s['spec'][:10].strip() if s['spec'] else ''
    parts  = [p for p in [vmag, spec, coord] if p]
    desc   = f"HR {hr}" + (f", {', '.join(parts)}" if parts else '')

    if s['common']:
        desc = s['common'].replace('_', ' ').title() + f" (HR {hr}" + (f", {vmag}" if vmag else '') + ")"

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} astro:bsc:{hr}\n')
    if s['hd']:
        fh.write(f'al {atom} astro:hd:{s["hd"]}\n')
    if s['common']:
        fh.write(f'al {atom} astro:star:{s["common"]}\n')
    if s['con']:
        fh.write(f'ln {atom} astro:constellation:{s["con"]} sys:part_of\n')
    fh.write('\n')


def generate(stars: list[dict], out_dir: str, chunk_size: int, dry_run: bool):
    total     = len(stars)
    named     = sum(1 for s in stars if s['common'])
    num_files = (total + chunk_size - 1) // chunk_size

    print(f"\n  Stars: {total}  ({named} with common names)")
    print(f"  Files: {num_files} × {chunk_size} → bsc5_{{NN}}.ak")

    if dry_run:
        return

    os.makedirs(out_dir, exist_ok=True)
    for i in range(num_files):
        chunk = stars[i * chunk_size:(i + 1) * chunk_size]
        fname = f"bsc5_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, star_range=f"{start}–{end}"))
            for s in chunk:
                emit_star(fh, s)
        print(f"  {fname}  {len(chunk):5d} stars", flush=True)

    print(f"\n  Total: {total} stars in {num_files} files → {out_dir}/")
    print("\nNext: git add ontology/common/bsc5_*.ak && git commit")


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_catalog(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    gz   = os.path.join(CACHE_DIR, 'catalog.gz')
    dat  = os.path.join(CACHE_DIR, 'catalog')
    if os.path.exists(dat):
        print(f"Using cached: {dat}")
        return dat
    if os.path.exists(gz):
        print(f"Using cached: {gz}")
        return gz
    _download(BSC5_URL, gz, "BSC5 catalog.gz (~750 KB)")
    return gz


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--bsc-file',   help='Pre-downloaded BSC5 catalog file')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=2000,
                    help='Stars per .ak file (default: 2000; all stars fit in ~5 files)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[stars_import] Locating BSC5 catalog …')
    try:
        cat_path = ensure_catalog(args.bsc_file)
    except Exception as e:
        print(f'\nError: {e}')
        print(f'\nManual download: {BSC5_URL}')
        print('Re-run with: --bsc-file /path/to/catalog')
        sys.exit(1)

    print(f'[stars_import] Parsing {os.path.basename(cat_path)} …')
    stars = parse_bsc5(cat_path)
    print(f'  Parsed {len(stars)} records')

    generate(stars, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
