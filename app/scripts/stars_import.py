"""
stars_import.py — Yale Bright Star Catalogue (BSC5) → ontology/common/stars.ak

Converts the Yale Bright Star Catalogue 5th edition to Akasha .ak atoms
for ontology/common/.

Includes:
    - All ~9,000 catalogue entries (stars with visual magnitude < ~7.5)
    - Common name atoms for the ~300 named stars
    - IAU constellation links via sys:part_of

Atom IDs:    astro:star:hr{HR}               e.g. astro:star:hr1234
             astro:star:{common_name}         e.g. astro:star:sirius  (named stars)
Aliases:     astro:bsc:{HR}                  (HR catalogue number)
             astro:hd:{HD}                   (Henry Draper number, if present)
             astro:hip:{HIP}                 (Hipparcos, if present)
Links:       sys:part_of → astro:constellation:{iau3}  e.g. astro:constellation:ori

Attribution:
    Yale Bright Star Catalogue, 5th Revised Edition
    Hoffleit & Warren (1991), ADC Selected Astronomical Catalogs Vol. 1
    https://heasarc.gsfc.nasa.gov/W3Browse/star-catalog/bsc5p.html
    Public domain

Usage:
    python app/scripts/stars_import.py

    python app/scripts/stars_import.py --bsc-file /path/to/catalog

    python app/scripts/stars_import.py --dry-run

Options:
    --bsc-file FILE   Pre-downloaded BSC5 catalog file (bsc5.dat or catalog)
    --out DIR         Output directory (default: ontology/common/)
    --dry-run         Print stats only, write no files

Source:
    https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz   (primary, CDS Strasbourg)
    Fallback via NASA HEASARC — see --bsc-file option for manual download.

IAU Constellation abbreviations used for sys:part_of links.
Constellation atoms should exist in ontology/common/ (see iau_constellations.ak).
"""

