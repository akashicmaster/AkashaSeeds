"""
wikidata_stage_import.py — Wikidata SPARQL → app/ontology/film/stage_works_NN.ak

Queries the Wikidata SPARQL endpoint for theatrical works (stage plays and musicals)
and emits Akasha .ak atoms. Full plot text is NOT stored — only title, year, genre,
writer, and a URL pointing back to wikidata.org.

Atom IDs:
    stage:work:{norm_title}      e.g. stage:work:hamlet_1603
    (appends _{year} if title collision)
Aliases:
    stage:wd:{qid}               → wikidata.org/wiki/{qid}
    stage:imdb:{imdbId}          (if IMDb ID is available on the item)
Sets:
    ontology.stage_works

Attribution:
    Wikidata — https://www.wikidata.org/ — CC0 1.0
    SPARQL endpoint — https://query.wikidata.org/

Usage:
    # Auto-query SPARQL (result cached locally):
    python app/scripts/wikidata_stage_import.py

    # Use pre-downloaded SPARQL result JSON:
    python app/scripts/wikidata_stage_import.py --json /path/to/stage_works.json

    # Dry run — preview first 20 lines, write no files:
    python app/scripts/wikidata_stage_import.py --dry-run

    # Override output directory:
    python app/scripts/wikidata_stage_import.py --out app/ontology/film/

Options:
    --json FILE       Pre-downloaded SPARQL result JSON
    --out DIR         Output directory (default: app/ontology/film/)
    --chunk-size N    Atoms per .ak file (default: 500)
    --dry-run         Print first 20 lines to stdout, write no files

Source:
    https://query.wikidata.org/sparql
    Items: stage plays (Q25379) and musicals (Q2743)
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "film")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "wikidata_stage_cache")
CACHE_FILE   = os.path.join(CACHE_DIR, "stage_works.json")

SPARQL_ENDPOINT = "https://query.wikidata.org/sparql"
USER_AGENT      = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

# Single UNION query covering both stage plays (Q25379) and musicals (Q2743)
SPARQL_QUERY = """\
SELECT DISTINCT ?work ?workLabel ?writerLabel ?year ?genreLabel ?imdbId WHERE {
  {
    ?work wdt:P31/wdt:P279* wd:Q25379 .
  } UNION {
    ?work wdt:P31/wdt:P279* wd:Q2743 .
  }
  OPTIONAL { ?work wdt:P50 ?writer }
  OPTIONAL { ?work wdt:P577|wdt:P571 ?date . BIND(YEAR(?date) AS ?year) }
  OPTIONAL { ?work wdt:P136 ?genre }
  OPTIONAL { ?work wdt:P345 ?imdbId }
  FILTER(LANG(?workLabel) = "en" || !BOUND(?workLabel))
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?year ?workLabel
LIMIT 8000"""

# Split queries used as fallback if the UNION times out
SPARQL_PLAYS_QUERY = """\
SELECT DISTINCT ?work ?workLabel ?writerLabel ?year ?genreLabel ?imdbId WHERE {
  ?work wdt:P31/wdt:P279* wd:Q25379 .
  OPTIONAL { ?work wdt:P50 ?writer }
  OPTIONAL { ?work wdt:P577|wdt:P571 ?date . BIND(YEAR(?date) AS ?year) }
  OPTIONAL { ?work wdt:P136 ?genre }
  OPTIONAL { ?work wdt:P345 ?imdbId }
  FILTER(LANG(?workLabel) = "en" || !BOUND(?workLabel))
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?year ?workLabel
LIMIT 8000"""

SPARQL_MUSICALS_QUERY = """\
SELECT DISTINCT ?work ?workLabel ?writerLabel ?year ?genreLabel ?imdbId WHERE {
  ?work wdt:P31/wdt:P279* wd:Q2743 .
  OPTIONAL { ?work wdt:P50 ?writer }
  OPTIONAL { ?work wdt:P577|wdt:P571 ?date . BIND(YEAR(?date) AS ?year) }
  OPTIONAL { ?work wdt:P136 ?genre }
  OPTIONAL { ?work wdt:P345 ?imdbId }
  FILTER(LANG(?workLabel) = "en" || !BOUND(?workLabel))
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?year ?workLabel
LIMIT 8000"""

FILE_HEADER = """\
# {filename}
# Wikidata — https://www.wikidata.org/ — CC0 1.0
# Generated by app/scripts/wikidata_stage_import.py
# Entries: {entry_range}
#
"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def norm_title(title: str, max_chars: int = 60) -> str:
    s = title.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip('.,;') + '…'


def extract_qid(uri: str) -> str:
    """Extract Q-number from Wikidata entity URI like http://www.wikidata.org/entity/Q12345."""
    m = re.search(r'(Q\d+)$', uri)
    return m.group(1) if m else uri


def sparql_get(query: str) -> dict:
    """Execute a SPARQL query; return parsed JSON. Retry once on timeout."""
    params = urllib.parse.urlencode({'query': query, 'format': 'application/sparql-results+json'})
    url = SPARQL_ENDPOINT + '?' + params
    req = urllib.request.Request(url, headers={
        'Accept':     'application/sparql-results+json',
        'User-Agent': USER_AGENT,
    })
    for attempt in range(2):
        try:
            eprint(f"  SPARQL request (attempt {attempt + 1}) …")
            with urllib.request.urlopen(req, timeout=60) as resp:
                return json.loads(resp.read().decode('utf-8'))
        except Exception as e:
            if attempt == 0:
                eprint(f"  Timeout/error: {e} — retrying in 5s …")
                time.sleep(5)
            else:
                raise
    raise RuntimeError("SPARQL query failed after 2 attempts")


def fetch_sparql_results() -> list[dict]:
    """Fetch SPARQL results; fall back to split queries if UNION times out."""
    os.makedirs(CACHE_DIR, exist_ok=True)
    if os.path.exists(CACHE_FILE):
        eprint(f"Using cached: {CACHE_FILE}")
        with open(CACHE_FILE, encoding='utf-8') as f:
            data = json.load(f)
        return data.get('results', {}).get('bindings', [])

    eprint("[wikidata_stage_import] Querying Wikidata SPARQL endpoint …")
    try:
        data = sparql_get(SPARQL_QUERY)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f"  UNION query returned {len(bindings):,} rows")
    except Exception as e:
        eprint(f"  UNION query failed: {e}")
        eprint("  Falling back to split queries …")
        plays_data    = sparql_get(SPARQL_PLAYS_QUERY)
        musicals_data = sparql_get(SPARQL_MUSICALS_QUERY)
        plays_b    = plays_data.get('results', {}).get('bindings', [])
        musicals_b = musicals_data.get('results', {}).get('bindings', [])
        eprint(f"  Plays: {len(plays_b):,}, Musicals: {len(musicals_b):,}")
        bindings = plays_b + musicals_b
        data = {'results': {'bindings': bindings}}

    with open(CACHE_FILE, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    eprint(f"  Cached to: {CACHE_FILE}")
    return bindings


def val(row: dict, field: str) -> str | None:
    """Safely extract string value from a SPARQL result binding row."""
    entry = row.get(field)
    if not entry:
        return None
    v = entry.get('value', '').strip()
    return v if v else None


def parse_bindings(bindings: list[dict]) -> list[dict]:
    """
    Collapse multi-row results (multiple writers/genres per work) into one record
    per work. Dedup by norm_title; keep earliest year on collision.
    """
    # Group by work URI
    by_work: dict[str, dict] = {}
    for row in bindings:
        work_uri = val(row, 'work')
        if not work_uri:
            continue
        qid   = extract_qid(work_uri)
        label = val(row, 'workLabel') or qid
        year  = val(row, 'year')
        writer = val(row, 'writerLabel')
        genre  = val(row, 'genreLabel')
        imdb   = val(row, 'imdbId')

        if qid not in by_work:
            by_work[qid] = {
                'qid':     qid,
                'label':   label,
                'year':    year,
                'writers': set(),
                'genres':  set(),
                'imdb':    imdb,
            }
        rec = by_work[qid]
        # Keep earliest year
        if year and (rec['year'] is None or int(year) < int(rec['year'])):
            rec['year'] = year
        if writer:
            rec['writers'].add(writer)
        if genre:
            rec['genres'].add(genre)
        if imdb and not rec['imdb']:
            rec['imdb'] = imdb

    eprint(f"  {len(by_work):,} unique works after collapsing multi-row results")

    # Convert sets to sorted strings
    records = []
    for qid, rec in by_work.items():
        rec['writers'] = ', '.join(sorted(rec['writers']))
        rec['genres']  = ', '.join(sorted(rec['genres']))
        records.append(rec)

    # Sort: by year ascending, then label
    records.sort(key=lambda r: (int(r['year']) if r['year'] else 9999, r['label'].lower()))

    # Dedup by norm_title: keep earliest-year version
    seen_norm: dict[str, dict] = {}
    for rec in records:
        nt = norm_title(rec['label'])
        if nt not in seen_norm:
            seen_norm[nt] = rec
        # else: already have an entry; since sorted by year asc, current entry is later → skip

    deduped = list(seen_norm.values())
    eprint(f"  {len(deduped):,} works after title deduplication")

    # Resolve collisions in the normalised slug space (same norm_title after dedup pass
    # shouldn't happen, but compute final keys with year suffix for any remaining)
    seen_keys: dict[str, int] = {}
    for rec in deduped:
        nt = norm_title(rec['label'])
        yr = rec['year'] or ''
        key = f"{nt}_{yr}" if yr else nt
        if key in seen_keys:
            # Shouldn't happen after dedup, but handle gracefully
            seen_keys[key] += 1
            key = f"{key}_{seen_keys[key]}"
        else:
            seen_keys[key] = 1
        rec['atom_key'] = key

    return deduped


def build_description(rec: dict) -> str:
    """Build ≤280-char description omitting absent fields."""
    label = rec['label']
    year  = rec['year']
    genre = rec['genres']
    writer = rec['writers']
    url   = f"https://www.wikidata.org/wiki/{rec['qid']}"

    parts = [label]
    if year:
        parts[0] = f"{label} ({year})"
    if genre:
        parts.append(genre)
    if writer:
        parts.append(f"by {writer}")
    desc = '; '.join(parts) + f'. {url}'
    return truncate(desc, 280)


def emit_work_block(rec: dict) -> list[str]:
    """Return list of .ak lines for one stage work."""
    atom  = f"stage:work:{rec['atom_key']}"
    alias = f"stage:wd:{rec['qid']}"
    desc  = build_description(rec)
    lines = [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
    ]
    if rec.get('imdb'):
        lines.append(f'al {atom} stage:imdb:{rec["imdb"]}')
    lines.append(f'set.add name="ontology.stage_works" id="{atom}"')
    lines.append('')
    return lines


def generate(records: list[dict], out_dir: str, chunk_size: int, dry_run: bool) -> None:
    # Build all lines
    all_lines: list[str] = []
    for rec in records:
        all_lines.extend(emit_work_block(rec))

    n_total = len(records)
    n_files = (n_total + chunk_size - 1) // chunk_size
    eprint(f"\n  Works:  {n_total:,}")
    eprint(f"  Files:  {n_files} × {chunk_size} → stage_works_{{NN}}.ak")
    eprint(f"  Output: {out_dir}/")

    if dry_run:
        print("# --- DRY RUN: first 20 output lines ---")
        count = 0
        for line in all_lines:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    os.makedirs(out_dir, exist_ok=True)

    # Split into blocks (blank-line terminated)
    blocks: list[list[str]] = []
    current: list[str] = []
    for line in all_lines:
        current.append(line)
        if line == '':
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    n_chunks = (len(blocks) + chunk_size - 1) // chunk_size
    for i in range(n_chunks):
        chunk_blocks = blocks[i * chunk_size:(i + 1) * chunk_size]
        fname = f"stage_works_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk_blocks) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, entry_range=f"{start}–{end}"))
            for block in chunk_blocks:
                fh.write('\n'.join(block) + '\n')
        eprint(f"  {fname}  {len(chunk_blocks):5d} entries", flush=True)

    eprint(f"\n  Done → {out_dir}/")
    eprint("\nNext: git add app/ontology/film/stage_works_*.ak && git commit")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json',       help='Pre-downloaded SPARQL result JSON')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print first 20 lines to stdout, write no files')
    args = ap.parse_args()

    if args.json:
        eprint(f'[wikidata_stage_import] Loading {args.json} …')
        with open(args.json, encoding='utf-8') as f:
            data = json.load(f)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f'  {len(bindings):,} rows in JSON file')
    else:
        try:
            bindings = fetch_sparql_results()
        except Exception as e:
            eprint(f'\nError: {e}')
            eprint(f"""
Manual download:
  Visit https://query.wikidata.org/
  Paste the SPARQL_QUERY constant from this script
  Download result as JSON
  Pass with: --json /path/to/stage_works.json
""")
            sys.exit(1)

    if not bindings:
        eprint('No results returned. Try --json with a pre-downloaded file.')
        sys.exit(0)

    eprint('[wikidata_stage_import] Parsing results …')
    records = parse_bindings(bindings)

    if not records:
        eprint('No valid records after parsing.')
        sys.exit(0)

    generate(records, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
