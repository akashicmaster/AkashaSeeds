"""
wikidata_wines_import.py — Wikidata wine appellations + châteaux → wikidata_wines_NN.ak

Queries Wikidata SPARQL for:
  - Wine appellations (AOC, DOC, DOCG, DO, AVA, etc.) → wine:appellation:* atoms
  - Wine châteaux / estates                            → wine:chateau:* atoms

Atom IDs:
    wine:appellation:{normalized_name}   e.g. wine:appellation:pomerol
    wine:chateau:{normalized_name}       e.g. wine:chateau:petrus
    wine:wd:{QID}                        (alias for both)

Sets:
    wine:appellations   — all appellations
    wine:chateaux       — all châteaux

Attribution:
    Wikidata — https://www.wikidata.org/
    CC0 1.0 — https://creativecommons.org/publicdomain/zero/1.0/

Usage:
    # Full run (queries Wikidata):
    python app/scripts/wikidata_wines_import.py

    # Dry run (stats only, no files written):
    python app/scripts/wikidata_wines_import.py --dry-run

    # Custom output directory:
    python app/scripts/wikidata_wines_import.py --out out/wine

    # Use alternate cache dir:
    python app/scripts/wikidata_wines_import.py --cache-dir /tmp/wd_wine_cache

Options:
    --out DIR          Output directory (default: out/wine)
    --chunk-size N     Atoms per .ak file (default: 500)
    --dry-run          Print stats only, write no files
    --cache-dir DIR    Cache directory for SPARQL results (default: out/wikidata_wines_cache)
"""

import argparse
import json
import os
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "out", "wine")
DEFAULT_CACHE = os.path.join(PROJECT_ROOT, "out", "wikidata_wines_cache")

SPARQL_ENDPOINT = "https://query.wikidata.org/sparql"
USER_AGENT = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

# Wikidata QIDs for country fallback queries
WINE_COUNTRIES = [
    ("France",        "Q142"),
    ("Italy",         "Q38"),
    ("Spain",         "Q29"),
    ("Portugal",      "Q45"),
    ("Germany",       "Q183"),
    ("United States", "Q30"),
    ("Australia",     "Q408"),
    ("Argentina",     "Q414"),
    ("Chile",         "Q298"),
    ("South Africa",  "Q258"),
    ("New Zealand",   "Q664"),
    ("Austria",       "Q40"),
    ("Hungary",       "Q28"),
    ("Greece",        "Q41"),
]

QUERY_APPELLATIONS = """\
SELECT ?item ?itemLabel ?country ?countryLabel ?appType ?appTypeLabel WHERE {
  ?item wdt:P31/wdt:P279* wd:Q1756733 .
  OPTIONAL { ?item wdt:P17 ?country }
  OPTIONAL { ?item wdt:P31 ?appType }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
LIMIT 3000
"""

QUERY_APPELLATIONS_BY_COUNTRY = """\
SELECT ?item ?itemLabel ?country ?countryLabel ?appType ?appTypeLabel WHERE {
  ?item wdt:P31/wdt:P279* wd:Q1756733 .
  ?item wdt:P17 wd:%s .
  BIND(wd:%s AS ?country)
  OPTIONAL { ?item wdt:P31 ?appType }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
LIMIT 1000
"""

QUERY_CHATEAUX = """\
SELECT ?item ?itemLabel ?region ?regionLabel ?country ?countryLabel WHERE {
  ?item wdt:P31/wdt:P279* wd:Q785550 .
  ?item wdt:P17 ?country .
  OPTIONAL { ?item wdt:P131 ?region }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
LIMIT 2000
"""

FILE_HEADER = """\
# {filename}
# Wikidata — https://www.wikidata.org/ — CC0 1.0
# Generated by app/scripts/wikidata_wines_import.py — chunk {chunk_num}
#
"""


# ---------------------------------------------------------------------------
# Normalisation
# ---------------------------------------------------------------------------

def normalize(name: str) -> str:
    """Convert label to atom name component: lowercase, NFD→ASCII, underscores."""
    s = unicodedata.normalize('NFD', name)
    s = s.encode('ascii', 'ignore').decode('ascii')
    s = s.lower()
    s = re.sub(r'[\s\-/,.()\[\]\'\"]+', '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:60]


def escape_ak(s: str) -> str:
    """Escape double-quotes and backslashes for .ak def strings."""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def qid_from_uri(uri: str) -> str:
    """Extract QID from Wikidata entity URI like http://www.wikidata.org/entity/Q142."""
    return uri.rsplit('/', 1)[-1]


def is_real_label(label: str, qid: str) -> bool:
    """Return False if the label is just the QID (Wikidata fallback when no English label)."""
    return bool(label) and label != qid


# ---------------------------------------------------------------------------
# SPARQL fetch
# ---------------------------------------------------------------------------

def sparql_query(query: str, label: str) -> list[dict]:
    """
    Execute a SPARQL query against Wikidata and return the bindings list.
    Raises urllib.error.URLError on network failure.
    """
    params = urllib.parse.urlencode({'query': query, 'format': 'json'})
    url = f"{SPARQL_ENDPOINT}?{params}"
    req = urllib.request.Request(
        url,
        headers={
            'User-Agent': USER_AGENT,
            'Accept': 'application/sparql-results+json',
        }
    )
    print(f"  Querying Wikidata: {label} …", file=sys.stderr)
    with urllib.request.urlopen(req, timeout=90) as resp:
        data = json.loads(resp.read().decode('utf-8'))
    bindings = data['results']['bindings']
    print(f"  → {len(bindings)} results", file=sys.stderr)
    return bindings


def sparql_query_with_fallback(
    main_query: str,
    main_label: str,
    country_query_tpl: str,
    cache_path: str,
) -> list[dict]:
    """
    Try main_query first.  On timeout, fall back to per-country queries.
    Results are merged and returned.
    """
    try:
        return sparql_query(main_query, main_label)
    except Exception as e:
        if 'timed out' in str(e).lower() or '429' in str(e) or '500' in str(e):
            print(
                f"  Main query timed out ({e}). Falling back to per-country queries …",
                file=sys.stderr,
            )
        else:
            raise

    all_bindings: list[dict] = []
    seen_items: set[str] = set()
    for country_name, country_qid in WINE_COUNTRIES:
        country_cache = cache_path.replace('.json', f'_{country_qid}.json')
        if os.path.exists(country_cache):
            print(f"  Using cached: {country_cache}", file=sys.stderr)
            with open(country_cache, encoding='utf-8') as f:
                bindings = json.load(f)
        else:
            try:
                q = country_query_tpl % (country_qid, country_qid)
                bindings = sparql_query(q, f"{main_label} — {country_name}")
                time.sleep(1)  # be polite
            except Exception as exc:
                print(f"  Warning: {country_name} query failed: {exc}", file=sys.stderr)
                continue
            os.makedirs(os.path.dirname(country_cache), exist_ok=True)
            with open(country_cache, 'w', encoding='utf-8') as f:
                json.dump(bindings, f)

        for b in bindings:
            uri = b.get('item', {}).get('value', '')
            if uri not in seen_items:
                seen_items.add(uri)
                all_bindings.append(b)

    return all_bindings


# ---------------------------------------------------------------------------
# Cache helpers
# ---------------------------------------------------------------------------

def load_or_fetch_appellations(cache_dir: str) -> list[dict]:
    cache_path = os.path.join(cache_dir, 'appellations.json')
    if os.path.exists(cache_path):
        print(f"[wines] Using cached appellations: {cache_path}", file=sys.stderr)
        with open(cache_path, encoding='utf-8') as f:
            return json.load(f)

    os.makedirs(cache_dir, exist_ok=True)
    bindings = sparql_query_with_fallback(
        QUERY_APPELLATIONS,
        "wine appellations",
        QUERY_APPELLATIONS_BY_COUNTRY,
        cache_path,
    )
    with open(cache_path, 'w', encoding='utf-8') as f:
        json.dump(bindings, f)
    print(f"  Cached → {cache_path}", file=sys.stderr)
    return bindings


def load_or_fetch_chateaux(cache_dir: str) -> list[dict]:
    cache_path = os.path.join(cache_dir, 'chateaux.json')
    if os.path.exists(cache_path):
        print(f"[wines] Using cached chateaux: {cache_path}", file=sys.stderr)
        with open(cache_path, encoding='utf-8') as f:
            return json.load(f)

    os.makedirs(cache_dir, exist_ok=True)
    try:
        bindings = sparql_query(QUERY_CHATEAUX, "wine châteaux/estates")
    except Exception as e:
        print(f"\nError fetching châteaux: {e}", file=sys.stderr)
        _print_manual_instructions()
        sys.exit(1)
    with open(cache_path, 'w', encoding='utf-8') as f:
        json.dump(bindings, f)
    print(f"  Cached → {cache_path}", file=sys.stderr)
    return bindings


def _print_manual_instructions():
    print("\nManual download steps:", file=sys.stderr)
    print("  1. Open https://query.wikidata.org/ in your browser", file=sys.stderr)
    print("  2. Run the SPARQL queries from the script docstring", file=sys.stderr)
    print("  3. Download results as JSON", file=sys.stderr)
    print("  4. Save to:", file=sys.stderr)
    print(f"       {DEFAULT_CACHE}/appellations.json", file=sys.stderr)
    print(f"       {DEFAULT_CACHE}/chateaux.json", file=sys.stderr)
    print("  5. Re-run this script (cache will be used automatically)", file=sys.stderr)


# ---------------------------------------------------------------------------
# Data parsing
# ---------------------------------------------------------------------------

def parse_appellations(bindings: list[dict]) -> list[dict]:
    """
    Parse SPARQL bindings for appellations.
    Returns deduplicated list of dicts with keys: qid, label, country, app_type, slug.
    """
    seen_uris: set[str] = set()
    seen_slugs: dict[str, int] = {}
    results: list[dict] = []

    for b in bindings:
        uri = b.get('item', {}).get('value', '')
        if not uri or uri in seen_uris:
            continue
        seen_uris.add(uri)

        qid = qid_from_uri(uri)
        label = b.get('itemLabel', {}).get('value', '')
        if not is_real_label(label, qid):
            continue

        country = b.get('countryLabel', {}).get('value', '')
        app_type = b.get('appTypeLabel', {}).get('value', '')

        base_slug = normalize(label)
        if not base_slug:
            continue

        slug = base_slug
        if slug in seen_slugs:
            seen_slugs[slug] += 1
            suffix = chr(ord('b') + seen_slugs[slug] - 1)
            slug = f"{base_slug}_{suffix}"
        else:
            seen_slugs[base_slug] = 0

        results.append({
            'qid':      qid,
            'label':    label,
            'country':  country,
            'app_type': app_type,
            'slug':     slug,
        })

    return results


def parse_chateaux(bindings: list[dict]) -> list[dict]:
    """
    Parse SPARQL bindings for châteaux.
    Returns deduplicated list of dicts with keys: qid, label, region, country, slug.
    """
    seen_uris: set[str] = set()
    seen_slugs: dict[str, int] = {}
    results: list[dict] = []

    for b in bindings:
        uri = b.get('item', {}).get('value', '')
        if not uri or uri in seen_uris:
            continue
        seen_uris.add(uri)

        qid = qid_from_uri(uri)
        label = b.get('itemLabel', {}).get('value', '')
        if not is_real_label(label, qid):
            continue

        country = b.get('countryLabel', {}).get('value', '')
        region  = b.get('regionLabel',  {}).get('value', '')

        base_slug = normalize(label)
        if not base_slug:
            continue

        slug = base_slug
        if slug in seen_slugs:
            seen_slugs[slug] += 1
            suffix = chr(ord('b') + seen_slugs[slug] - 1)
            slug = f"{base_slug}_{suffix}"
        else:
            seen_slugs[base_slug] = 0

        results.append({
            'qid':     qid,
            'label':   label,
            'country': country,
            'region':  region,
            'slug':    slug,
        })

    return results


# ---------------------------------------------------------------------------
# Emitters
# ---------------------------------------------------------------------------

def emit_appellation(fh, entry: dict) -> None:
    """Write one appellation atom block to fh."""
    atom  = f"wine:appellation:{entry['slug']}"
    alias = f"wine:wd:{entry['qid']}"
    wd_url = f"https://www.wikidata.org/wiki/{entry['qid']}"

    parts = [entry['label'], "wine appellation"]
    if entry['country']:
        parts.append(entry['country'])
    desc = f"{', '.join(parts)}. {wd_url}"

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} {alias}\n')
    fh.write(f'set.add name="wine:appellations" id="{atom}"\n')
    fh.write('\n')


def emit_chateau(fh, entry: dict) -> None:
    """Write one château atom block to fh."""
    atom  = f"wine:chateau:{entry['slug']}"
    alias = f"wine:wd:{entry['qid']}"
    wd_url = f"https://www.wikidata.org/wiki/{entry['qid']}"

    location_parts = []
    if entry['region']:
        location_parts.append(entry['region'])
    if entry['country']:
        location_parts.append(entry['country'])
    location = ', '.join(location_parts) if location_parts else 'unknown location'
    desc = f"{entry['label']}, wine estate in {location}. {wd_url}"

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} {alias}\n')
    fh.write(f'set.add name="wine:chateaux" id="{atom}"\n')
    fh.write('\n')


# ---------------------------------------------------------------------------
# Generator
# ---------------------------------------------------------------------------

def generate(
    appellations: list[dict],
    chateaux: list[dict],
    out_dir: str,
    chunk_size: int,
    dry_run: bool,
) -> None:
    all_entries = (
        [('appellation', e) for e in appellations]
        + [('chateau',     e) for e in chateaux]
    )
    total     = len(all_entries)
    num_files = (total + chunk_size - 1) // chunk_size

    print(f"\n  Appellations: {len(appellations)}", file=sys.stderr)
    print(f"  Châteaux:     {len(chateaux)}", file=sys.stderr)
    print(f"  Total atoms:  {total}", file=sys.stderr)
    print(f"  Files:        {num_files} × {chunk_size} → wikidata_wines_{{NN}}.ak", file=sys.stderr)

    if dry_run:
        print("  [dry-run] No files written.", file=sys.stderr)
        return

    os.makedirs(out_dir, exist_ok=True)

    for i in range(num_files):
        chunk = all_entries[i * chunk_size:(i + 1) * chunk_size]
        fname = f"wikidata_wines_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, chunk_num=i + 1))
            for kind, entry in chunk:
                if kind == 'appellation':
                    emit_appellation(fh, entry)
                else:
                    emit_chateau(fh, entry)
        print(f"  {fname}  {len(chunk):5d} atoms", file=sys.stderr, flush=True)

    print(f"\n  Total: {total} atoms in {num_files} files → {out_dir}/", file=sys.stderr)
    print(f"\nNext: load the files via akasha.py onto.load dir={out_dir}/", file=sys.stderr)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print stats only, write no files')
    ap.add_argument('--cache-dir',  default=DEFAULT_CACHE,
                    help=f'Cache directory (default: {DEFAULT_CACHE})')
    args = ap.parse_args()

    print('[wikidata_wines] Fetching appellations …', file=sys.stderr)
    try:
        app_bindings = load_or_fetch_appellations(args.cache_dir)
    except (urllib.error.URLError, OSError) as e:
        print(f'\nNetwork error fetching appellations: {e}', file=sys.stderr)
        _print_manual_instructions()
        sys.exit(1)

    print('[wikidata_wines] Fetching châteaux …', file=sys.stderr)
    try:
        ch_bindings = load_or_fetch_chateaux(args.cache_dir)
    except (urllib.error.URLError, OSError) as e:
        print(f'\nNetwork error fetching châteaux: {e}', file=sys.stderr)
        _print_manual_instructions()
        sys.exit(1)

    print('[wikidata_wines] Parsing …', file=sys.stderr)
    appellations = parse_appellations(app_bindings)
    chateaux     = parse_chateaux(ch_bindings)
    print(f'  {len(appellations)} appellations, {len(chateaux)} châteaux after dedup/filter',
          file=sys.stderr)

    generate(appellations, chateaux, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
