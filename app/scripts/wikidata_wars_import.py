"""
wikidata_wars_import.py — Wikidata SPARQL → app/ontology/war/wars_NN.ak

Queries the Wikidata SPARQL endpoint for major wars and armed conflicts
(items with ≥5 sitelinks) and emits Akasha .ak atoms.

Atom IDs:
    war:conflict:{norm_name}    e.g. war:conflict:world_war_ii_1939
    (appends _{startYear} if name collision)
Aliases:
    war:wd:{qid}                → wikidata.org/wiki/{qid}
Sets:
    ontology.wars

Attribution:
    Wikidata — https://www.wikidata.org/ — CC0 1.0
    SPARQL endpoint — https://query.wikidata.org/

Usage:
    # Auto-query SPARQL (result cached locally):
    python app/scripts/wikidata_wars_import.py

    # Use pre-downloaded SPARQL result JSON:
    python app/scripts/wikidata_wars_import.py --json /path/to/wars.json

    # Dry run — preview first 20 lines, write no files:
    python app/scripts/wikidata_wars_import.py --dry-run

    # Override output directory:
    python app/scripts/wikidata_wars_import.py --out app/ontology/war/

    # Raise sitelinks threshold:
    python app/scripts/wikidata_wars_import.py --min-sitelinks 10

Options:
    --json FILE           Pre-downloaded SPARQL result JSON
    --out DIR             Output directory (default: app/ontology/war/)
    --chunk-size N        Atoms per .ak file (default: 500)
    --min-sitelinks N     Minimum Wikipedia sitelinks (default: 5)
    --dry-run             Print first 20 lines to stdout, write no files

Source:
    https://query.wikidata.org/sparql
    Items: wars (Q198) and armed conflicts (Q180684)
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "war")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "wikidata_wars_cache")
CACHE_FILE   = os.path.join(CACHE_DIR, "wars.json")

SPARQL_ENDPOINT = "https://query.wikidata.org/sparql"
USER_AGENT      = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

# Primary UNION query: wars (Q198) and armed conflicts (Q180684)
SPARQL_QUERY = """\
SELECT DISTINCT ?conflict ?conflictLabel ?startYear ?endYear ?locationLabel ?resultLabel WHERE {
  {
    ?conflict wdt:P31/wdt:P279* wd:Q198 .
  } UNION {
    ?conflict wdt:P31/wdt:P279* wd:Q180684 .
  }
  ?conflict wikibase:sitelinks ?links .
  FILTER(?links >= 5)
  OPTIONAL {
    ?conflict wdt:P580 ?start .
    BIND(YEAR(?start) AS ?startYear)
  }
  OPTIONAL {
    ?conflict wdt:P582 ?end .
    BIND(YEAR(?end) AS ?endYear)
  }
  OPTIONAL { ?conflict wdt:P276|wdt:P17 ?location }
  OPTIONAL { ?conflict wdt:P793 ?result }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?startYear ?conflictLabel
LIMIT 5000"""

# Fallback split queries if UNION times out
SPARQL_WAR_QUERY = """\
SELECT DISTINCT ?conflict ?conflictLabel ?startYear ?endYear ?locationLabel ?resultLabel WHERE {
  ?conflict wdt:P31/wdt:P279* wd:Q198 .
  ?conflict wikibase:sitelinks ?links .
  FILTER(?links >= 5)
  OPTIONAL {
    ?conflict wdt:P580 ?start .
    BIND(YEAR(?start) AS ?startYear)
  }
  OPTIONAL {
    ?conflict wdt:P582 ?end .
    BIND(YEAR(?end) AS ?endYear)
  }
  OPTIONAL { ?conflict wdt:P276|wdt:P17 ?location }
  OPTIONAL { ?conflict wdt:P793 ?result }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?startYear ?conflictLabel
LIMIT 5000"""

SPARQL_CONFLICT_QUERY = """\
SELECT DISTINCT ?conflict ?conflictLabel ?startYear ?endYear ?locationLabel ?resultLabel WHERE {
  ?conflict wdt:P31/wdt:P279* wd:Q180684 .
  ?conflict wikibase:sitelinks ?links .
  FILTER(?links >= 5)
  OPTIONAL {
    ?conflict wdt:P580 ?start .
    BIND(YEAR(?start) AS ?startYear)
  }
  OPTIONAL {
    ?conflict wdt:P582 ?end .
    BIND(YEAR(?end) AS ?endYear)
  }
  OPTIONAL { ?conflict wdt:P276|wdt:P17 ?location }
  OPTIONAL { ?conflict wdt:P793 ?result }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?startYear ?conflictLabel
LIMIT 5000"""

FILE_HEADER = """\
# {filename}
# Wikidata — https://www.wikidata.org/ — CC0 1.0
# Generated by app/scripts/wikidata_wars_import.py
# Entries: {entry_range}
#
"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def norm_name(name: str, max_chars: int = 70) -> str:
    """Normalise conflict name to atom ID component."""
    s = name.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip('.,;') + '…'


def extract_qid(uri: str) -> str:
    """Extract Q-number from Wikidata entity URI."""
    m = re.search(r'(Q\d+)$', uri)
    return m.group(1) if m else uri


def sparql_get(query: str) -> dict:
    """Execute a SPARQL query; return parsed JSON. Retry once on timeout."""
    params = urllib.parse.urlencode({'query': query, 'format': 'application/sparql-results+json'})
    url = SPARQL_ENDPOINT + '?' + params
    req = urllib.request.Request(url, headers={
        'Accept':     'application/sparql-results+json',
        'User-Agent': USER_AGENT,
    })
    for attempt in range(2):
        try:
            eprint(f"  SPARQL request (attempt {attempt + 1}) …")
            with urllib.request.urlopen(req, timeout=90) as resp:
                return json.loads(resp.read().decode('utf-8'))
        except Exception as e:
            if attempt == 0:
                eprint(f"  Timeout/error: {e} — retrying in 5s …")
                time.sleep(5)
            else:
                raise
    raise RuntimeError("SPARQL query failed after 2 attempts")


def fetch_sparql_results() -> list[dict]:
    """Fetch SPARQL results from cache or network; fall back to split queries on timeout."""
    os.makedirs(CACHE_DIR, exist_ok=True)
    if os.path.exists(CACHE_FILE):
        eprint(f"Using cached: {CACHE_FILE}")
        with open(CACHE_FILE, encoding='utf-8') as f:
            data = json.load(f)
        return data.get('results', {}).get('bindings', [])

    eprint("[wikidata_wars_import] Querying Wikidata SPARQL endpoint …")
    try:
        data = sparql_get(SPARQL_QUERY)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f"  UNION query returned {len(bindings):,} rows")
    except Exception as e:
        eprint(f"  UNION query failed: {e}")
        eprint("  Falling back to split queries (Q198 and Q180684) …")
        war_data      = sparql_get(SPARQL_WAR_QUERY)
        conflict_data = sparql_get(SPARQL_CONFLICT_QUERY)
        war_b      = war_data.get('results', {}).get('bindings', [])
        conflict_b = conflict_data.get('results', {}).get('bindings', [])
        eprint(f"  Wars (Q198): {len(war_b):,}, Armed conflicts (Q180684): {len(conflict_b):,}")
        bindings = war_b + conflict_b
        data = {'results': {'bindings': bindings}}

    with open(CACHE_FILE, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    eprint(f"  Cached to: {CACHE_FILE}")
    return bindings


def val(row: dict, field: str) -> str | None:
    """Safely extract string value from a SPARQL result binding row."""
    entry = row.get(field)
    if not entry:
        return None
    v = entry.get('value', '').strip()
    return v if v else None


def parse_bindings(bindings: list[dict], min_sitelinks: int = 5) -> list[dict]:
    """
    Collapse multi-row results (multiple locations/results per conflict) into one
    record per QID. Keep earliest start year; collect up to 2 locations; collect results.
    """
    by_qid: dict[str, dict] = {}
    for row in bindings:
        conflict_uri = val(row, 'conflict')
        if not conflict_uri:
            continue
        qid       = extract_qid(conflict_uri)
        label     = val(row, 'conflictLabel') or qid
        # Skip rows where label is just the QID (unlabelled item)
        if label == qid:
            continue
        start_yr  = val(row, 'startYear')
        end_yr    = val(row, 'endYear')
        location  = val(row, 'locationLabel')
        result    = val(row, 'resultLabel')

        if qid not in by_qid:
            by_qid[qid] = {
                'qid':       qid,
                'label':     label,
                'startYear': start_yr,
                'endYear':   end_yr,
                'locations': [],
                'results':   [],
            }
        rec = by_qid[qid]

        # Keep earliest start year
        if start_yr:
            if rec['startYear'] is None or int(start_yr) < int(rec['startYear']):
                rec['startYear'] = start_yr
        # Keep latest end year (or None if still ongoing)
        if end_yr:
            if rec['endYear'] is None or int(end_yr) > int(rec['endYear']):
                rec['endYear'] = end_yr

        # Collect up to 2 unique locations
        if location and location not in rec['locations'] and len(rec['locations']) < 2:
            rec['locations'].append(location)

        # Collect first result label
        if result and result not in rec['results'] and len(rec['results']) < 1:
            rec['results'].append(result)

    eprint(f"  {len(by_qid):,} unique conflicts after collapsing multi-row results")

    records = list(by_qid.values())

    # Sort: by start year ascending, then label
    records.sort(key=lambda r: (int(r['startYear']) if r['startYear'] else 9999,
                                r['label'].lower()))

    # Assign atom keys with collision-safe year suffix
    seen_keys: dict[str, int] = {}
    for rec in records:
        base = norm_name(rec['label'])
        yr   = rec['startYear'] or ''
        key  = base
        if key in seen_keys:
            # First collision: add year suffix
            key = f"{base}_{yr}" if yr else f"{base}_2"
        if key in seen_keys:
            # Still colliding: add counter
            seen_keys_count = seen_keys.get(key, 0) + 1
            key = f"{key}_{seen_keys_count}"
        seen_keys[key] = seen_keys.get(key, 0) + 1
        rec['atom_key'] = key

    eprint(f"  {len(records):,} conflict records ready for output")
    return records


def build_description(rec: dict) -> str:
    """Build ≤280-char description; omit absent fields."""
    label    = rec['label']
    start_yr = rec['startYear']
    end_yr   = rec['endYear']
    locs     = rec['locations']
    url      = f"https://www.wikidata.org/wiki/{rec['qid']}"

    # Date range
    if start_yr and end_yr and end_yr != start_yr:
        dates = f"({start_yr}–{end_yr})"
    elif start_yr:
        dates = f"({start_yr})"
    else:
        dates = ''

    parts = [f"{label} {dates}".strip() if dates else label]
    if locs:
        parts.append(', '.join(locs))
    parts.append(url)

    desc = '; '.join(parts)
    return truncate(desc, 280)


def emit_conflict_block(rec: dict) -> list[str]:
    """Return list of .ak lines for one conflict."""
    atom  = f"war:conflict:{rec['atom_key']}"
    alias = f"war:wd:{rec['qid']}"
    desc  = build_description(rec)
    lines = [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
        f'ln {atom} war:conflict sys:part_of',
        f'set.add name="ontology.wars" id="{atom}"',
        '',
    ]
    return lines


def generate(records: list[dict], out_dir: str, chunk_size: int, dry_run: bool) -> None:
    # Build all lines, prepending namespace anchor in chunk 01
    anchor_lines = [
        'def "war:conflict" "Namespace anchor for wars and armed conflicts"',
        '',
    ]
    all_lines: list[str] = anchor_lines[:]
    for rec in records:
        all_lines.extend(emit_conflict_block(rec))

    n_total = len(records)
    n_files = (n_total + chunk_size - 1) // chunk_size if n_total else 1
    eprint(f"\n  Conflicts: {n_total:,}")
    eprint(f"  Files:     {n_files} × {chunk_size} → wars_{{NN}}.ak")
    eprint(f"  Output:    {out_dir}/")

    if dry_run:
        print("# --- DRY RUN: first 20 output lines ---")
        count = 0
        for line in all_lines:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    os.makedirs(out_dir, exist_ok=True)

    # Split into per-record blocks (blank-line terminated)
    blocks: list[list[str]] = []
    current: list[str] = []
    for line in all_lines:
        current.append(line)
        if line == '':
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    n_chunks = (len(blocks) + chunk_size - 1) // chunk_size
    for i in range(n_chunks):
        chunk_blocks = blocks[i * chunk_size:(i + 1) * chunk_size]
        fname  = f"wars_{i + 1:02d}.ak"
        fpath  = os.path.join(out_dir, fname)
        start  = i * chunk_size + 1
        end    = start + len(chunk_blocks) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, entry_range=f"{start}–{end}"))
            for block in chunk_blocks:
                fh.write('\n'.join(block) + '\n')
        eprint(f"  {fname}  {len(chunk_blocks):5d} entries", flush=True)

    eprint(f"\n  Done → {out_dir}/")
    eprint("\nNext: git add app/ontology/war/wars_*.ak && git commit")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json',          help='Pre-downloaded SPARQL result JSON')
    ap.add_argument('--out',           default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size',    type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--min-sitelinks', type=int, default=5,
                    help='Minimum Wikipedia sitelinks to include (default: 5)')
    ap.add_argument('--dry-run',       action='store_true',
                    help='Print first 20 lines to stdout, write no files')
    args = ap.parse_args()

    if args.json:
        eprint(f'[wikidata_wars_import] Loading {args.json} …')
        with open(args.json, encoding='utf-8') as f:
            data = json.load(f)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f'  {len(bindings):,} rows in JSON file')
    else:
        try:
            bindings = fetch_sparql_results()
        except Exception as e:
            eprint(f'\nError: {e}')
            eprint("""
Manual download:
  Visit https://query.wikidata.org/
  Paste the SPARQL_QUERY from this script
  Download as JSON
  Run: python app/scripts/wikidata_wars_import.py --json /path/to/wars.json
""")
            sys.exit(1)

    if not bindings:
        eprint('No results returned. Try --json with a pre-downloaded file.')
        sys.exit(0)

    eprint('[wikidata_wars_import] Parsing results …')
    records = parse_bindings(bindings, min_sitelinks=args.min_sitelinks)

    if not records:
        eprint('No valid records after parsing.')
        sys.exit(0)

    generate(records, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
