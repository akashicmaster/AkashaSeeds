"""
wikidata_buildings_import.py — Wikidata SPARQL → app/ontology/art/buildings_NN.ak

Queries the Wikidata SPARQL endpoint for notable historic buildings and monuments
and emits Akasha .ak atoms. Full encyclopaedic text is NOT stored — only name,
year, architect, style, country, and a URL pointing back to wikidata.org.

Atom IDs:
    arch:building:{norm_name}       e.g. arch:building:notre_dame_de_paris_1345
    (appends _{year} on collision)
Aliases:
    arch:wd:{qid}                   → wikidata.org/wiki/{qid}
Sets:
    ontology.buildings

Attribution:
    Wikidata — https://www.wikidata.org/ — CC0 1.0
    SPARQL endpoint — https://query.wikidata.org/

Usage:
    # Auto-query SPARQL (result cached locally):
    python app/scripts/wikidata_buildings_import.py

    # Use pre-downloaded SPARQL result JSON:
    python app/scripts/wikidata_buildings_import.py --json /path/to/buildings.json

    # Dry run — preview first 20 lines, write no files:
    python app/scripts/wikidata_buildings_import.py --dry-run

    # Override output directory:
    python app/scripts/wikidata_buildings_import.py --out app/ontology/art/

    # Raise year cap:
    python app/scripts/wikidata_buildings_import.py --max-year 1970

Options:
    --json FILE       Pre-downloaded SPARQL result JSON
    --out DIR         Output directory (default: app/ontology/art/)
    --chunk-size N    Atoms per .ak file (default: 500)
    --max-year INT    Latest construction year to include (default: 1950)
    --dry-run         Print first 20 lines to stdout, write no files

Source:
    https://query.wikidata.org/sparql
    Items: buildings (Q41176) and monuments (Q4989906)
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "art")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "wikidata_buildings_cache")
CACHE_FILE   = os.path.join(CACHE_DIR, "buildings.json")

SPARQL_ENDPOINT = "https://query.wikidata.org/sparql"
USER_AGENT      = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

# Combined UNION query for buildings (Q41176) and monuments (Q4989906)
SPARQL_QUERY = """\
SELECT DISTINCT ?building ?buildingLabel ?architectLabel ?styleLabel ?year ?countryLabel WHERE {
  {
    ?building wdt:P31/wdt:P279* wd:Q41176 .
  } UNION {
    ?building wdt:P31/wdt:P279* wd:Q4989906 .
  }
  ?building wikibase:sitelinks ?links .
  FILTER(?links >= 10)
  OPTIONAL { ?building wdt:P84 ?architect }
  OPTIONAL { ?building wdt:P149 ?style }
  OPTIONAL { ?building wdt:P17 ?country }
  OPTIONAL {
    ?building wdt:P571 ?date .
    BIND(YEAR(?date) AS ?year)
  }
  FILTER(!BOUND(?year) || ?year <= 1950)
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?year ?buildingLabel
LIMIT 5000"""

# Split queries used as fallback if the UNION times out
SPARQL_BUILDINGS_QUERY = """\
SELECT DISTINCT ?building ?buildingLabel ?architectLabel ?styleLabel ?year ?countryLabel WHERE {
  ?building wdt:P31/wdt:P279* wd:Q41176 .
  ?building wikibase:sitelinks ?links .
  FILTER(?links >= 10)
  OPTIONAL { ?building wdt:P84 ?architect }
  OPTIONAL { ?building wdt:P149 ?style }
  OPTIONAL { ?building wdt:P17 ?country }
  OPTIONAL {
    ?building wdt:P571 ?date .
    BIND(YEAR(?date) AS ?year)
  }
  FILTER(!BOUND(?year) || ?year <= 1950)
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?year ?buildingLabel
LIMIT 5000"""

SPARQL_MONUMENTS_QUERY = """\
SELECT DISTINCT ?building ?buildingLabel ?architectLabel ?styleLabel ?year ?countryLabel WHERE {
  ?building wdt:P31/wdt:P279* wd:Q4989906 .
  ?building wikibase:sitelinks ?links .
  FILTER(?links >= 10)
  OPTIONAL { ?building wdt:P84 ?architect }
  OPTIONAL { ?building wdt:P149 ?style }
  OPTIONAL { ?building wdt:P17 ?country }
  OPTIONAL {
    ?building wdt:P571 ?date .
    BIND(YEAR(?date) AS ?year)
  }
  FILTER(!BOUND(?year) || ?year <= 1950)
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?year ?buildingLabel
LIMIT 5000"""

FILE_HEADER = """\
# {filename}
# Wikidata — https://www.wikidata.org/ — CC0 1.0
# Generated by app/scripts/wikidata_buildings_import.py
# Entries: {entry_range}
#
"""

NAMESPACE_ANCHOR = """\
def "arch:building" "Namespace anchor for notable historic buildings and monuments"

"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def norm_name(name: str, max_chars: int = 60) -> str:
    s = name.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip('.,;') + '…'


def extract_qid(uri: str) -> str:
    """Extract Q-number from Wikidata entity URI like http://www.wikidata.org/entity/Q12345."""
    m = re.search(r'(Q\d+)$', uri)
    return m.group(1) if m else uri


def sparql_get(query: str) -> dict:
    """Execute a SPARQL query; return parsed JSON. Retry once on timeout."""
    params = urllib.parse.urlencode({'query': query, 'format': 'application/sparql-results+json'})
    url = SPARQL_ENDPOINT + '?' + params
    req = urllib.request.Request(url, headers={
        'Accept':     'application/sparql-results+json',
        'User-Agent': USER_AGENT,
    })
    for attempt in range(2):
        try:
            eprint(f"  SPARQL request (attempt {attempt + 1}) …")
            with urllib.request.urlopen(req, timeout=90) as resp:
                return json.loads(resp.read().decode('utf-8'))
        except Exception as e:
            if attempt == 0:
                eprint(f"  Timeout/error: {e} — retrying in 5s …")
                time.sleep(5)
            else:
                raise
    raise RuntimeError("SPARQL query failed after 2 attempts")


def fetch_sparql_results() -> list[dict]:
    """Fetch SPARQL results; fall back to split queries if UNION times out."""
    os.makedirs(CACHE_DIR, exist_ok=True)
    if os.path.exists(CACHE_FILE):
        eprint(f"Using cached: {CACHE_FILE}")
        with open(CACHE_FILE, encoding='utf-8') as f:
            data = json.load(f)
        return data.get('results', {}).get('bindings', [])

    eprint("[wikidata_buildings_import] Querying Wikidata SPARQL endpoint …")
    try:
        data = sparql_get(SPARQL_QUERY)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f"  UNION query returned {len(bindings):,} rows")
    except Exception as e:
        eprint(f"  UNION query failed: {e}")
        eprint("  Falling back to split queries …")
        buildings_data = sparql_get(SPARQL_BUILDINGS_QUERY)
        monuments_data = sparql_get(SPARQL_MONUMENTS_QUERY)
        buildings_b = buildings_data.get('results', {}).get('bindings', [])
        monuments_b = monuments_data.get('results', {}).get('bindings', [])
        eprint(f"  Buildings: {len(buildings_b):,}, Monuments: {len(monuments_b):,}")
        bindings = buildings_b + monuments_b
        data = {'results': {'bindings': bindings}}

    with open(CACHE_FILE, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    eprint(f"  Cached to: {CACHE_FILE}")
    return bindings


def val(row: dict, field: str) -> str | None:
    """Safely extract string value from a SPARQL result binding row."""
    entry = row.get(field)
    if not entry:
        return None
    v = entry.get('value', '').strip()
    return v if v else None


def parse_bindings(bindings: list[dict], max_year: int) -> list[dict]:
    """
    Collapse multi-row results (multiple architects/styles per building) into one
    record per building. Dedup by norm_name; append _{year} on collision.
    """
    # Group by building URI
    by_building: dict[str, dict] = {}
    for row in bindings:
        building_uri = val(row, 'building')
        if not building_uri:
            continue
        qid       = extract_qid(building_uri)
        label     = val(row, 'buildingLabel') or qid
        architect = val(row, 'architectLabel')
        style     = val(row, 'styleLabel')
        country   = val(row, 'countryLabel')
        year      = val(row, 'year')

        # Apply max_year filter (redundant with SPARQL but covers post-fetch use of --max-year)
        if year:
            try:
                if int(year) > max_year:
                    continue
            except ValueError:
                pass

        if qid not in by_building:
            by_building[qid] = {
                'qid':       qid,
                'label':     label,
                'year':      year,
                'architects': set(),
                'styles':    set(),
                'country':   country,
            }
        rec = by_building[qid]
        # Keep earliest year
        if year and (rec['year'] is None or int(year) < int(rec['year'])):
            rec['year'] = year
        if architect:
            rec['architects'].add(architect)
        if style:
            rec['styles'].add(style)
        if country and not rec['country']:
            rec['country'] = country

    eprint(f"  {len(by_building):,} unique buildings after collapsing multi-row results")

    # Convert sets to sorted strings (take first value for description brevity)
    records = []
    for qid, rec in by_building.items():
        architects_sorted = sorted(rec['architects'])
        styles_sorted     = sorted(rec['styles'])
        rec['architect'] = architects_sorted[0] if architects_sorted else ''
        rec['style']     = styles_sorted[0] if styles_sorted else ''
        del rec['architects']
        del rec['styles']
        records.append(rec)

    # Sort: by year ascending, then label
    records.sort(key=lambda r: (int(r['year']) if r['year'] else 9999, r['label'].lower()))

    # Assign unique atom keys — append _{year} on norm_name collision
    seen_keys: dict[str, int] = {}
    for rec in records:
        nn   = norm_name(rec['label'])
        year = rec['year'] or ''
        base = nn
        key  = base
        if key in seen_keys:
            key = f"{base}_{year}" if year else f"{base}_2"
            if key in seen_keys:
                seen_keys[key] = seen_keys.get(key, 0) + 1
                key = f"{key}_{seen_keys[key] + 1}"
        seen_keys[key] = 1
        rec['atom_key'] = key

    eprint(f"  {len(records):,} buildings after parsing")
    return records


def build_description(rec: dict) -> str:
    """Build ≤280-char description omitting absent fields."""
    parts = [rec['label']]
    if rec['year']:
        parts[0] = f"{rec['label']} ({rec['year']})"
    if rec['style']:
        parts.append(rec['style'])
    if rec['architect']:
        parts.append(f"arch. {rec['architect']}")
    if rec['country']:
        parts.append(rec['country'])
    url = f"https://www.wikidata.org/wiki/{rec['qid']}"
    desc = '; '.join(parts) + f'. {url}'
    return truncate(desc, 280)


def emit_building_block(rec: dict) -> list[str]:
    """Return list of .ak lines for one building."""
    atom  = f"arch:building:{rec['atom_key']}"
    alias = f"arch:wd:{rec['qid']}"
    desc  = build_description(rec)
    lines = [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
        f'ln {atom} arch:building sys:part_of',
        f'set.add name="ontology.buildings" id="{atom}"',
        '',
    ]
    return lines


def generate(records: list[dict], out_dir: str, chunk_size: int,
             dry_run: bool) -> None:
    """Build .ak output and write chunk files."""
    all_lines: list[str] = []
    for rec in records:
        all_lines.extend(emit_building_block(rec))

    n_total = len(records)
    n_files = (n_total + chunk_size - 1) // chunk_size
    eprint(f"\n  Buildings: {n_total:,}")
    eprint(f"  Files:     {n_files} × {chunk_size} → buildings_{{NN}}.ak")
    eprint(f"  Output:    {out_dir}/")

    if dry_run:
        print("# --- DRY RUN: first 20 output lines ---")
        print(NAMESPACE_ANCHOR.rstrip())
        count = 0
        for line in all_lines:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    os.makedirs(out_dir, exist_ok=True)

    # Split into per-building blocks (blank-line terminated)
    blocks: list[list[str]] = []
    current: list[str] = []
    for line in all_lines:
        current.append(line)
        if line == '':
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    n_chunks = (len(blocks) + chunk_size - 1) // chunk_size
    for i in range(n_chunks):
        chunk_blocks = blocks[i * chunk_size:(i + 1) * chunk_size]
        fname = f"buildings_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk_blocks) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, entry_range=f"{start}–{end}"))
            if i == 0:
                fh.write(NAMESPACE_ANCHOR)
            for block in chunk_blocks:
                fh.write('\n'.join(block) + '\n')
        eprint(f"  {fname}  {len(chunk_blocks):5d} entries", flush=True)

    eprint(f"\n  Done → {out_dir}/")
    eprint("\nNext: git add app/ontology/art/buildings_*.ak && git commit")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json', help='Pre-downloaded SPARQL result JSON')
    ap.add_argument('--out', default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--max-year', type=int, default=1950,
                    help='Latest construction year to include (default: 1950)')
    ap.add_argument('--dry-run', action='store_true',
                    help='Print first 20 lines to stdout, write no files')
    args = ap.parse_args()

    if args.json:
        eprint(f'[wikidata_buildings_import] Loading {args.json} …')
        with open(args.json, encoding='utf-8') as f:
            data = json.load(f)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f'  {len(bindings):,} rows in JSON file')
    else:
        try:
            bindings = fetch_sparql_results()
        except Exception as e:
            eprint(f'\nError: {e}')
            eprint(f"""
Manual download:
  Visit https://query.wikidata.org/
  Paste the SPARQL_QUERY from this script
  Download as JSON
  Run: python app/scripts/wikidata_buildings_import.py --json /path/to/buildings.json
""")
            sys.exit(1)

    if not bindings:
        eprint('No results returned. Try --json with a pre-downloaded file.')
        sys.exit(0)

    eprint(f'[wikidata_buildings_import] Parsing results (max year: {args.max_year}) …')
    records = parse_bindings(bindings, args.max_year)

    if not records:
        eprint('No valid records after parsing.')
        sys.exit(0)

    generate(records, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
