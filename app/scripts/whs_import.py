"""
whs_import.py — UNESCO World Heritage Sites → ontology/common/geo_whs.ak

Converts the UNESCO World Heritage List to Akasha .ak atoms for ontology/common/.

~1,200 sites as of 2024. Includes cultural, natural, and mixed sites.

Atom IDs:    archeo:whs:{id}           e.g. archeo:whs:206   (Angkor)
UNESCO URL:  archeo:whs:url:{id}       (alias)
Links:       sys:part_of → geo:country:{iso3lower}
             sys:part_of → archeo:whs:cultural / archeo:whs:natural / archeo:whs:mixed

Attribution:
    UNESCO World Heritage Centre — https://whc.unesco.org/
    Terms of use: https://whc.unesco.org/en/syndication/

Usage:
    python app/scripts/whs_import.py

    python app/scripts/whs_import.py --xml /path/to/whc-sites.xml

    python app/scripts/whs_import.py --dry-run
"""

import argparse
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

SCRIPT_DIR  = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "ontology", "common", "geo_whs.ak")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "whs_cache")

WHS_XML_URL = "https://whc.unesco.org/en/list/xml/"

FILE_HEADER = """\
# geo_whs.ak
# UNESCO World Heritage List — https://whc.unesco.org/
# Generated by app/scripts/whs_import.py
# Sites: {count}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def truncate(s: str, n: int = 200) -> str:
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0] + '…'


def text(elem, tag: str) -> str:
    child = elem.find(tag)
    return (child.text or '').strip() if child is not None else ''


def parse_whs(path: str) -> list[dict]:
    tree = ET.parse(path)
    root = tree.getroot()
    # Handle both <query> and direct <row> roots
    rows = root.findall('.//row')
    sites = []
    for row in rows:
        uid  = text(row, 'unique_number') or text(row, 'id_number')
        name = text(row, 'site')
        if not uid or not name:
            continue
        desc_raw  = text(row, 'short_description') or text(row, 'justification') or name
        desc      = truncate(re.sub(r'<[^>]+>', '', desc_raw))
        year      = text(row, 'date_inscribed')
        category  = text(row, 'category') or text(row, 'category_short')
        iso2      = text(row, 'iso_code').lower()
        iso3      = text(row, 'udnp_code').lower() or iso2
        country   = text(row, 'states_name_en')
        criteria  = text(row, 'criteria_txt')
        try:
            lat = float(text(row, 'latitude'))
            lon = float(text(row, 'longitude'))
            coord = f"{abs(lat):.4f}°{'N' if lat>=0 else 'S'} {abs(lon):.4f}°{'E' if lon>=0 else 'W'}"
        except ValueError:
            coord = ''
        sites.append({
            'id':       uid,
            'name':     name,
            'desc':     desc,
            'year':     year,
            'category': category,
            'iso3':     iso3 or iso2,
            'country':  country,
            'coord':    coord,
            'criteria': criteria,
        })
    sites.sort(key=lambda s: int(s['id']) if s['id'].isdigit() else 0)
    return sites


def emit_site(fh, s: dict) -> None:
    atom    = f"archeo:whs:{s['id']}"
    country = f"geo:country:{s['iso3']}" if s['iso3'] else None

    cat_lc  = s['category'].lower() if s['category'] else ''
    if 'natural' in cat_lc:
        cat_atom = 'archeo:whs:natural'
    elif 'mixed' in cat_lc:
        cat_atom = 'archeo:whs:mixed'
    else:
        cat_atom = 'archeo:whs:cultural'

    parts = [s['name']]
    if s['country']:
        parts.append(s['country'])
    if s['year']:
        parts.append(f"inscribed {s['year']}")
    if s['criteria']:
        parts.append(s['criteria'])
    if s['coord']:
        parts.append(s['coord'])
    desc = '; '.join(parts)
    if s['desc'] and s['desc'] != s['name']:
        desc += f". {s['desc']}"

    fh.write(f'def "{atom}" "{escape_ak(desc[:280])}"\n')
    fh.write(f'al {atom} archeo:whs:url:{s["id"]}\n')
    if country:
        fh.write(f'ln {atom} {country} sys:part_of\n')
    fh.write(f'ln {atom} {cat_atom} sys:part_of\n')
    fh.write('\n')


def generate(sites: list[dict], out_path: str, dry_run: bool) -> None:
    cats: dict[str, int] = {}
    for s in sites:
        c = (s['category'] or 'Unknown').lower()
        k = 'Natural' if 'natural' in c else 'Mixed' if 'mixed' in c else 'Cultural'
        cats[k] = cats.get(k, 0) + 1

    print(f"\n  Sites: {len(sites)}")
    for k, v in sorted(cats.items()):
        print(f"    {k}: {v}")
    print(f"  Output: {out_path}")

    if dry_run:
        return

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as fh:
        fh.write(FILE_HEADER.format(count=len(sites)))
        # Category namespace anchors
        fh.write('def "archeo:whs:cultural" "UNESCO World Heritage Sites — cultural properties (monuments, groups of buildings, sites)."\n')
        fh.write('ln archeo:whs:cultural archeo:whs sys:part_of\n\n')
        fh.write('def "archeo:whs:natural" "UNESCO World Heritage Sites — natural properties (geological, ecological, biological, scenic)."\n')
        fh.write('ln archeo:whs:natural archeo:whs sys:part_of\n\n')
        fh.write('def "archeo:whs:mixed" "UNESCO World Heritage Sites — mixed properties meeting both cultural and natural criteria."\n')
        fh.write('ln archeo:whs:mixed archeo:whs sys:part_of\n\n')
        fh.write('def "archeo:whs" "UNESCO World Heritage Sites — places of outstanding universal value inscribed under the 1972 World Heritage Convention."\n\n')
        for s in sites:
            emit_site(fh, s)
    print(f"\n  Written: {len(sites)} sites → {out_path}")
    print("\nNext: git add ontology/common/geo_whs.ak && git commit")


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_xml(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, 'whc-sites.xml')
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    _download(WHS_XML_URL, dest, "UNESCO WHS XML (~2 MB)")
    return dest


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--xml',      help='Pre-downloaded UNESCO WHS XML file')
    ap.add_argument('--out',      default=DEFAULT_OUT,
                    help=f'Output path (default: {DEFAULT_OUT})')
    ap.add_argument('--dry-run',  action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[whs_import] Locating source file …')
    try:
        xml_path = ensure_xml(args.xml)
    except Exception as e:
        print(f'\nError: {e}')
        print(f'\nManual download: {WHS_XML_URL}')
        print('Re-run with: --xml /path/to/whc-sites.xml')
        sys.exit(1)

    print(f'[whs_import] Parsing {os.path.basename(xml_path)} …')
    sites = parse_whs(xml_path)
    generate(sites, args.out, args.dry_run)


if __name__ == '__main__':
    main()
