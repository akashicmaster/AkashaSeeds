"""
periodo_import.py — PeriodO historical periods → ontology/common/eras_periodo.ak

Converts the PeriodO dataset (SIL/University of Oregon) to Akasha .ak atoms.

PeriodO is a linked open data vocabulary of historical periods used in
archaeology and history (~1,500 named period definitions from ~200 scholarly
authorities).

Because the same period (e.g. "Bronze Age") appears under multiple authorities
with slightly different date ranges, this script deduplicates by normalised
label and picks the definition with the most precise temporal coverage.

Atom IDs:    era:{normalized_label}    e.g. era:bronze_age, era:hellenistic
             era:periodo:{short_id}    (alias for the canonical period record)
Description: period name + date range + spatial coverage

Attribution:
    PeriodO: A Gazetteer of Periods for the Humanities and Social Sciences
    https://perio.do/
    Adam Rabinowitz et al., CC0

Usage:
    python app/scripts/periodo_import.py

    python app/scripts/periodo_import.py --json /path/to/periodo.json

    python app/scripts/periodo_import.py --dry-run
"""

import argparse
import json
import os
import re
import sys
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "ontology", "common", "eras_periodo.ak")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "periodo_cache")

PERIODO_URL  = "https://data.perio.do/graph.json"
PERIODO_ALT  = "https://n2t.net/ark:/99152/p0d.json"

FILE_HEADER = """\
# eras_periodo.ak
# PeriodO: A Gazetteer of Periods for the Humanities and Social Sciences
# https://perio.do/ — CC0 (Adam Rabinowitz et al.)
# Generated by app/scripts/periodo_import.py
# Periods: {count}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def normalize_label(label: str) -> str:
    s = label.lower()
    s = re.sub(r'[\s\-,./()]+', '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:80]


def extract_year(node: dict | None, key: str) -> int | None:
    """Extract year from PeriodO start/stop node."""
    if not node:
        return None
    # Try 'in' → 'year' (exact)
    in_node = node.get('in', {})
    if isinstance(in_node, dict):
        y = in_node.get('year')
        if y is not None:
            try:
                return int(y)
            except (ValueError, TypeError):
                pass
    # Try earliestYear / latestYear
    for k in ('earliestYear', 'latestYear', 'year'):
        y = node.get(k)
        if y is not None:
            try:
                return int(y)
            except (ValueError, TypeError):
                pass
    return None


def year_str(y: int | None) -> str:
    if y is None:
        return '?'
    if y < 0:
        return f"{abs(y)} BCE"
    return f"{y} CE"


def precision(start: int | None, stop: int | None) -> int:
    """Higher precision = both dates known and narrower range."""
    if start is None or stop is None:
        return 0
    return 10000 - abs(stop - start)


def extract_periods(data: dict) -> list[dict]:
    """
    Walk PeriodO JSON structure and collect all period definitions.
    Handles both the 'authorities' key and flat '@graph' array styles.
    """
    periods: list[dict] = []

    # Style 1: nested under 'authorities'
    authorities = data.get('authorities', {})
    if isinstance(authorities, dict):
        for auth_id, auth in authorities.items():
            if not isinstance(auth, dict):
                continue
            for pid, p in auth.get('periods', {}).items():
                if not isinstance(p, dict):
                    continue
                _collect(periods, pid, p)

    # Style 2: flat @graph array
    graph = data.get('@graph', [])
    for item in graph:
        if not isinstance(item, dict):
            continue
        t = item.get('type', '') or item.get('@type', '')
        if 'Concept' in str(t):
            pid = item.get('@id', '') or item.get('id', '')
            _collect(periods, pid, item)

    return periods


def _collect(out: list, pid: str, p: dict) -> None:
    """Extract a single period record into out."""
    # Get English label (or first available)
    label_node = p.get('label', {})
    if isinstance(label_node, dict):
        label = (label_node.get('en') or
                 next(iter(label_node.values()), None) or '')
    elif isinstance(label_node, str):
        label = label_node
    else:
        label = ''
    label = label.strip()
    if not label:
        return

    start = extract_year(p.get('start'))
    stop  = extract_year(p.get('stop'))

    spatial_raw = p.get('spatialCoverageDescription', '')
    if not spatial_raw:
        cov = p.get('spatialCoverage', [])
        if isinstance(cov, list):
            spatial_raw = ', '.join(
                c.get('label', '') if isinstance(c, dict) else str(c)
                for c in cov if c
            )
    spatial = spatial_raw.strip()[:120] if spatial_raw else ''

    # Short ID from ARK URI
    short_id = re.sub(r'.*/|^ark:/\d+/', '', pid).strip() if pid else ''

    out.append({
        'id':       short_id,
        'label':    label,
        'norm':     normalize_label(label),
        'start':    start,
        'stop':     stop,
        'spatial':  spatial,
    })


def deduplicate(periods: list[dict]) -> list[dict]:
    """
    For each unique normalized label, keep the record with the most
    precise temporal coverage (both dates known, narrowest range).
    """
    best: dict[str, dict] = {}
    for p in periods:
        norm = p['norm']
        if not norm:
            continue
        existing = best.get(norm)
        if existing is None:
            best[norm] = p
        else:
            if precision(p['start'], p['stop']) > precision(existing['start'], existing['stop']):
                best[norm] = p
    # Sort: ancient first, then by label
    result = sorted(best.values(), key=lambda p: (p['start'] or 99999, p['label']))
    return result


def emit_period(fh, p: dict) -> None:
    atom = f"era:{p['norm']}"

    # Build description
    date_part = ''
    if p['start'] is not None or p['stop'] is not None:
        date_part = f"{year_str(p['start'])} – {year_str(p['stop'])}"
    spatial = p['spatial']
    parts = [p for p in [date_part, spatial] if p]
    desc_suffix = f" ({'; '.join(parts)})" if parts else ''
    desc = escape_ak(f"{p['label']}{desc_suffix}")

    fh.write(f'def "{atom}" "{desc}"\n')
    if p['id']:
        fh.write(f'al {atom} era:periodo:{p["id"]}\n')
    fh.write(f'ln {atom} era:archaeological sys:part_of\n')
    fh.write('\n')


def generate(periods: list[dict], out_path: str, dry_run: bool) -> None:
    dated = sum(1 for p in periods if p['start'] is not None)
    print(f"\n  Unique periods: {len(periods)}  ({dated} with date range)")
    print(f"  Output: {out_path}")

    if dry_run:
        return

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as fh:
        fh.write(FILE_HEADER.format(count=len(periods)))
        fh.write('def "era:archaeological" "Named historical and archaeological periods used in scholarly literature (PeriodO)."\n\n')
        for p in periods:
            emit_period(fh, p)
    print(f"\n  Written: {len(periods)} periods → {out_path}")
    print("\nNext: git add ontology/common/eras_periodo.ak && git commit")


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_json(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, 'periodo.json')
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    for url in (PERIODO_URL, PERIODO_ALT):
        try:
            _download(url, dest, f"PeriodO JSON (~25 MB) from {url}")
            return dest
        except Exception as e:
            print(f"  Failed ({e}), trying fallback …")
    raise RuntimeError("Could not download PeriodO dataset")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json',    help='Pre-downloaded PeriodO JSON file')
    ap.add_argument('--out',     default=DEFAULT_OUT,
                    help=f'Output path (default: {DEFAULT_OUT})')
    ap.add_argument('--dry-run', action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[periodo_import] Locating source file …')
    try:
        json_path = ensure_json(args.json)
    except Exception as e:
        print(f'\nError: {e}')
        print(f'\nManual download: {PERIODO_URL}')
        print('Re-run with: --json /path/to/periodo.json')
        sys.exit(1)

    print(f'[periodo_import] Parsing {os.path.basename(json_path)} …')
    with open(json_path, encoding='utf-8') as f:
        data = json.load(f)

    raw = extract_periods(data)
    print(f'  Raw records: {len(raw)}')
    periods = deduplicate(raw)
    print(f'  After deduplication: {len(periods)}')

    generate(periods, args.out, args.dry_run)


if __name__ == '__main__':
    main()
