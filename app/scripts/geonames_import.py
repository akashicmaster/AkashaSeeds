"""
geonames_import.py — GeoNames world cities → ontology/common/geo_cities_NN.ak

Converts GeoNames populated places to Akasha .ak ontology files for ontology/common/.

Filters applied:
    - feature_class = 'P'  (populated places only)
    - feature_code in PPLC/PPLG  (national capital / seat of government — always included)
    - OR population >= --min-population  (default: 100,000)

Atom IDs:    geo:city:{cc2}:{normalized_name}   e.g. geo:city:jp:tokyo
GeoNames ID: geo:geonames:{id}                  (alias)
Links:       sys:part_of → geo:country:{iso3lower}  e.g. geo:country:jpn

Attribution:
    GeoNames geographical database — https://www.geonames.org/
    CC BY 4.0 — https://creativecommons.org/licenses/by/4.0/

Usage:
    # Download and convert (requires download.geonames.org in network allowlist):
    python app/scripts/geonames_import.py

    # Use pre-downloaded files:
    python app/scripts/geonames_import.py --cities-file cities5000.txt --country-file countryInfo.txt

    # Dry run (stats only, no files written):
    python app/scripts/geonames_import.py --cities-file cities5000.txt --country-file countryInfo.txt --dry-run

    # Lower population threshold:
    python app/scripts/geonames_import.py --min-population 50000

Options:
    --cities-file FILE    Pre-downloaded cities5000.txt (unzipped)
    --country-file FILE   Pre-downloaded countryInfo.txt
    --out DIR             Output directory (default: ontology/common/)
    --chunk-size N        Places per .ak file (default: 2000)
    --min-population N    Min population for non-capitals (default: 100000)
    --dry-run             Print stats only, write no files

Source files:
    https://download.geonames.org/export/dump/cities5000.zip  (~55 MB, cities with pop > 5000)
    https://download.geonames.org/export/dump/countryInfo.txt  (country ISO codes + names)
"""

import argparse
import os
import re
import sys
import urllib.request
import zipfile

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "ontology", "common")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "geonames_cache")

CITIES_URL  = "https://download.geonames.org/export/dump/cities5000.zip"
COUNTRY_URL = "https://download.geonames.org/export/dump/countryInfo.txt"

# GeoNames TSV column indices (cities* files)
F_ID    = 0   # geonameid
F_NAME  = 1   # name (UTF-8)
F_ASCII = 2   # asciiname
F_LAT   = 4   # latitude
F_LON   = 5   # longitude
F_FCL   = 6   # feature class (P = populated place)
F_FCD   = 7   # feature code
F_CC2   = 8   # ISO-3166 alpha-2 country code
F_POP   = 14  # population

CAPITAL_CODES = frozenset({"PPLC", "PPLG"})  # national capital / seat of government

FILE_HEADER = """\
# {filename}
# GeoNames geographical database — https://www.geonames.org/
# CC BY 4.0 — https://creativecommons.org/licenses/by/4.0/
# Generated by app/scripts/geonames_import.py
# Places: {place_range}
#
"""


def normalize(name: str) -> str:
    """Convert place name to atom name component."""
    s = name.lower()
    s = re.sub(r"[\s\-,.'()]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:60]


def escape_ak(s: str) -> str:
    """Escape double-quotes and backslashes for .ak def strings."""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def fmt_coord(lat: float, lon: float) -> str:
    """Format lat/lon as compact readable string."""
    ns = 'N' if lat >= 0 else 'S'
    ew = 'E' if lon >= 0 else 'W'
    return f"{abs(lat):.4f}°{ns} {abs(lon):.4f}°{ew}"


def load_country_info(path: str) -> dict[str, dict]:
    """
    Parse countryInfo.txt → dict keyed by ISO2 code (uppercase).
    Returns: {ISO2: {'iso3': str, 'name': str}}
    """
    info: dict[str, dict] = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if line.startswith('#') or not line.strip():
                continue
            cols = line.split('\t')
            if len(cols) < 5:
                continue
            iso2 = cols[0].strip().upper()
            iso3 = cols[1].strip().lower()
            name = cols[4].strip()
            if iso2 and iso3:
                info[iso2] = {'iso3': iso3, 'name': name}
    return info


def parse_cities(path: str, country_info: dict, min_pop: int) -> list[dict]:
    """
    Parse GeoNames cities TSV; return filtered, sorted list of place dicts.
    Keys: gid, name, ascii, lat, lon, cc2, iso3, country, pop, capital
    """
    places: list[dict] = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            cols = line.rstrip('\n').split('\t')
            if len(cols) <= F_POP:
                continue
            if cols[F_FCL] != 'P':
                continue
            feat = cols[F_FCD]
            try:
                pop = int(cols[F_POP]) if cols[F_POP] else 0
            except ValueError:
                pop = 0
            is_cap = feat in CAPITAL_CODES
            if not is_cap and pop < min_pop:
                continue
            cc2 = cols[F_CC2].strip().upper()
            country = country_info.get(cc2, {})
            try:
                lat = float(cols[F_LAT])
                lon = float(cols[F_LON])
            except ValueError:
                lat, lon = 0.0, 0.0
            places.append({
                'gid':     cols[F_ID].strip(),
                'name':    cols[F_NAME].strip(),
                'ascii':   cols[F_ASCII].strip(),
                'lat':     lat,
                'lon':     lon,
                'cc2':     cc2.lower(),
                'iso3':    country.get('iso3', cc2.lower()),
                'country': country.get('name', cc2),
                'pop':     pop,
                'capital': is_cap,
            })
    # Sort: largest cities first, alphabetical within ties
    places.sort(key=lambda p: (-p['pop'], p['ascii']))
    return places


def emit_place(fh, p: dict) -> None:
    """Write one place to fh."""
    cc2   = p['cc2']
    norm  = normalize(p['ascii'] or p['name'])
    atom  = f"geo:city:{cc2}:{norm}"
    alias = f"geo:geonames:{p['gid']}"
    cntry = f"geo:country:{p['iso3']}"
    coord = fmt_coord(p['lat'], p['lon'])
    pop   = f", pop {p['pop']:,}" if p['pop'] else ''
    desc  = f"{p['name']}, {p['country']}{pop}, {coord}"
    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} {alias}\n')
    fh.write(f'ln {atom} {cntry} sys:part_of\n')
    fh.write('\n')


def generate(places: list[dict], out_dir: str, chunk_size: int, dry_run: bool):
    total     = len(places)
    num_files = (total + chunk_size - 1) // chunk_size
    caps      = sum(1 for p in places if p['capital'])

    print(f"\n  Places: {total}  ({caps} capitals, {total - caps} by population)")
    print(f"  Files:  {num_files} × {chunk_size} → geo_cities_{{NN}}.ak")

    if dry_run:
        # Country coverage breakdown
        by_country: dict[str, int] = {}
        for p in places:
            by_country[p['country']] = by_country.get(p['country'], 0) + 1
        print(f"  Countries represented: {len(by_country)}")
        return

    os.makedirs(out_dir, exist_ok=True)

    for i in range(num_files):
        chunk = places[i * chunk_size:(i + 1) * chunk_size]
        fname = f"geo_cities_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, place_range=f"{start}–{end}"))
            for p in chunk:
                emit_place(fh, p)
        print(f"  {fname}  {len(chunk):5d} places", flush=True)

    print(f"\n  Total: {total} places in {num_files} files → {out_dir}/")
    print("\nNext: git add ontology/common/geo_cities_*.ak && git commit")


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_cities(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    txt = os.path.join(CACHE_DIR, 'cities5000.txt')
    if os.path.exists(txt):
        print(f"Using cached: {txt}")
        return txt
    zp = os.path.join(CACHE_DIR, 'cities5000.zip')
    _download(CITIES_URL, zp, "cities5000.zip (~55 MB)")
    print("Extracting …")
    with zipfile.ZipFile(zp) as zf:
        zf.extractall(CACHE_DIR)
    if not os.path.exists(txt):
        raise RuntimeError(f"Extraction did not produce {txt}")
    return txt


def ensure_countries(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, 'countryInfo.txt')
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    _download(COUNTRY_URL, dest, "countryInfo.txt")
    return dest


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--cities-file',    help='Pre-downloaded cities5000.txt (unzipped)')
    ap.add_argument('--country-file',   help='Pre-downloaded countryInfo.txt')
    ap.add_argument('--out',            default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size',     type=int, default=2000,
                    help='Places per .ak file (default: 2000)')
    ap.add_argument('--min-population', type=int, default=100_000,
                    help='Min population for non-capitals (default: 100000)')
    ap.add_argument('--dry-run',        action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[geonames_import] Locating source files …')
    try:
        cities_path  = ensure_cities(args.cities_file)
        country_path = ensure_countries(args.country_file)
    except Exception as e:
        print(f'\nError: {e}')
        print('\nManual download steps:')
        print(f'  1. {CITIES_URL}')
        print(f'     → unzip to get cities5000.txt')
        print(f'  2. {COUNTRY_URL}')
        print(f'Re-run with:')
        print(f'  --cities-file /path/to/cities5000.txt --country-file /path/to/countryInfo.txt')
        sys.exit(1)

    print('[geonames_import] Loading country info …')
    countries = load_country_info(country_path)
    print(f'  {len(countries)} countries loaded')

    print(f'[geonames_import] Parsing cities (pop ≥ {args.min_population:,} or capital) …')
    places = parse_cities(cities_path, countries, args.min_population)

    generate(places, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
