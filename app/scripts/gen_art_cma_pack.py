#!/usr/bin/env python3
"""Generate the Art Explorer's works pack — `app/ontology/art_cma/` — from the bundled CMA corpus.

The Art Explorer airs one WORK per turn and shows its image in the gallery room. The works are the
Cleveland Museum of Art open-access records already bundled in `app/assets/cma_visual_curation/`
(100 works, every one CC0, each with the museum's own image URL). Source data enters as ontology,
prepared off-line: this script reads `records.jsonl.gz` and writes a plain `.ak` pack. Nothing in it
is inferred — every sentence is a field of the record, verbatim, and a field the record leaves blank
is left out (40 works have no named maker; none is invented).

Per work (`<acc>` = the accession number with `.` → `_`):

    def "art:work:cma:<acc>"         the record as a sentence — title, maker, date, culture,
                                     type, technique, measurements, collection + accession
    def "art:work:cma:<acc>:image"   the museum's image URL (the image is never stored)
    def "art:work:cma:<acc>:credit"  "The Cleveland Museum of Art · Open Access (CC0) · <page>"
    def "art:work:cma:<acc>:label"   the wall label: "<title> — <maker> · <date>" (fields verbatim)
    set.add name="art:cma:broadcast" id="art:work:cma:<acc>"        (the work only)

Run:  python app/scripts/gen_art_cma_pack.py
"""
import gzip
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "app", "assets", "cma_visual_curation", "records.jsonl.gz")
OUT_DIR = os.path.join(ROOT, "app", "ontology", "art_cma")
SET = "art:cma:broadcast"


def q(s):
    return '"%s"' % str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").strip()


def sentence(r):
    parts = [str(r.get("title") or "").strip()]
    for f in ("creators", "creation_date"):
        v = str(r.get(f) or "").strip()
        if v:
            parts.append(v)
    cult = r.get("culture")
    cult = "; ".join(cult) if isinstance(cult, list) else str(cult or "")
    if cult.strip():
        parts.append(cult.strip())
    kind = "; ".join(x for x in (str(r.get("type") or "").strip(),
                                 str(r.get("technique") or "").strip()) if x)
    if kind:
        parts.append(kind)
    if str(r.get("measurements") or "").strip():
        parts.append(str(r["measurements"]).strip())
    coll = "The Cleveland Museum of Art"
    if str(r.get("department") or "").strip():
        coll += ", " + str(r["department"]).strip()
    parts.append("%s, %s" % (coll, r.get("accession_number")))
    return ". ".join(p.rstrip(".") for p in parts if p) + "."


def label(r):
    """The wall label: title — maker · date, each the record's own field; a blank one is left out."""
    tail = " · ".join(x for x in (str(r.get("creators") or "").strip(),
                                  str(r.get("creation_date") or "").strip()) if x)
    return str(r.get("title") or "").strip() + (" — " + tail if tail else "")


def main():
    rows = [json.loads(l) for l in gzip.open(SRC, "rt", encoding="utf-8") if l.strip()]
    rows = [r for r in rows if r.get("rights") == "CC0" and r.get("image_url")]
    rows.sort(key=lambda r: str(r.get("accession_number")))
    os.makedirs(OUT_DIR, exist_ok=True)
    lines = [
        "# art_cma — the Art Explorer's works: Cleveland Museum of Art Open Access (CC0).",
        "# GENERATED by app/scripts/gen_art_cma_pack.py from app/assets/cma_visual_curation/ — do not",
        "# edit by hand; re-run the generator. Every sentence is the museum record's own fields;",
        "# a blank field is left out, never guessed. Images are referenced, never stored.",
        "",
    ]
    for r in rows:
        acc = str(r["accession_number"]).replace(".", "_")
        a = "art:work:cma:%s" % acc
        lines.append("def %s %s" % (q(a), q(sentence(r))))
        lines.append("def %s %s" % (q(a + ":image"), q(r["image_url"])))
        lines.append("def %s %s" % (q(a + ":credit"), q("The Cleveland Museum of Art · Open Access (CC0) · %s"
                                                          % r.get("canonical_url", ""))))
        lines.append("def %s %s" % (q(a + ":label"), q(label(r))))
        lines.append("")
    for r in rows:
        acc = str(r["accession_number"]).replace(".", "_")
        lines.append('set.add name="%s" id="art:work:cma:%s"' % (SET, acc))
    with open(os.path.join(OUT_DIR, "cma_works.ak"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(os.path.join(OUT_DIR, "PACK.json"), "w", encoding="utf-8") as fh:
        json.dump({
            "label": "Art Explorer — Cleveland Museum of Art Open Access works (Tier C)",
            "description": ("The works the Art Explorer airs, one per turn, each shown in the gallery room by the "
                            "museum's own image. %d works from the bundled CMA open-access corpus "
                            "(app/assets/cma_visual_curation/), every one CC0. Per work: the record as a sentence "
                            "(art:work:cma:<acc>), its image URL (:image — referenced, never stored), credit "
                            "(:credit) and wall label (:label); the works are the Set %s. GENERATED by app/scripts/gen_art_cma_pack.py. "
                            "TIER C — thesaurus (archives) line only." % (len(rows), SET)),
            "license": "CC0 (The Cleveland Museum of Art Open Access)",
            "source": "https://openaccess-api.clevelandart.org/",
            "attribution": "The Cleveland Museum of Art, Open Access",
            "version": "cma-vcl-v1",
        }, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print("wrote %d works → app/ontology/art_cma/cma_works.ak" % len(rows))


if __name__ == "__main__":
    main()
