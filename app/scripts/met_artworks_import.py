"""
met_artworks_import.py — Met Open Access API → app/ontology/art/met_artworks_NN.ak

Downloads notable public-domain artworks (paintings, drawings, etc.) from the
Metropolitan Museum of Art Open Access API and emits Akasha .ak atoms.

Full artwork text is NOT stored — only title, artist, medium summary, year, and a
URL pointing back to metmuseum.org.

Atom IDs:
    art:work:{norm_title}_{year}     e.g. art:work:water_lilies_1906
    (appends _b, _c … on collision within the same year)
Aliases:
    art:met:{objectID}               → metmuseum.org collection page
    art:wd:{qid}                     (if wikidataUrl present on the object)
Sets:
    ontology.artworks

Attribution:
    The Metropolitan Museum of Art — https://www.metmuseum.org/
    Open Access — https://creativecommons.org/publicdomain/zero/1.0/

Usage:
    # Auto-fetch from the Met API (results cached locally):
    python app/scripts/met_artworks_import.py

    # Dry run — preview first 20 lines, write no files:
    python app/scripts/met_artworks_import.py --dry-run

    # Override output directory:
    python app/scripts/met_artworks_import.py --out app/ontology/art/

    # Limit total objects (useful for testing):
    python app/scripts/met_artworks_import.py --max-objects 200

    # Fetch specific departments:
    python app/scripts/met_artworks_import.py --dept-ids 11,3

    # Include post-1900 works:
    python app/scripts/met_artworks_import.py --all

Options:
    --out DIR           Output directory (default: app/ontology/art/)
    --chunk-size N      Atoms per .ak file (default: 1000)
    --dept-ids LIST     Comma-separated department IDs to fetch (default: 11,3,14,19)
    --max-objects N     Limit total objects fetched (useful for testing)
    --all               Include post-1900 works too
    --dry-run           Print first 20 lines to stdout, write no files

Source:
    https://collectionapi.metmuseum.org/public/collection/v1/
    Departments: 11=European Paintings, 3=Ancient Near Eastern Art,
                 14=Islamic Art, 19=Asian Art
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "art")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "met_cache")
OBJECTS_DIR  = os.path.join(CACHE_DIR, "objects")

SEARCH_URL   = "https://collectionapi.metmuseum.org/public/collection/v1/search"
OBJECT_URL   = "https://collectionapi.metmuseum.org/public/collection/v1/objects/{}"
USER_AGENT   = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

DEFAULT_DEPT_IDS = [11, 3, 14, 19]

FILE_HEADER = """\
# {filename}
# The Metropolitan Museum of Art Open Access — https://www.metmuseum.org/
# CC0 1.0 — https://creativecommons.org/publicdomain/zero/1.0/
# Generated by app/scripts/met_artworks_import.py
# Entries: {entry_range}
#
"""

NAMESPACE_ANCHOR = """\
def "art:work" "Namespace anchor for visual artworks"

"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def norm_title(title: str, max_chars: int = 50) -> str:
    s = title.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip('.,;') + '…'


def extract_year(date_str: str) -> str:
    """Extract first 4-digit year from a date string, or return as-is if short."""
    if not date_str:
        return ''
    m = re.search(r'\d{4}', date_str)
    return m.group(0) if m else date_str[:10]


def extract_qid(wikidata_url: str) -> str:
    """Extract Q-number from a Wikidata URL like https://www.wikidata.org/wiki/Q12345."""
    m = re.search(r'(Q\d+)$', wikidata_url)
    return m.group(1) if m else ''


def http_get_json(url: str) -> dict:
    """Fetch JSON from URL with one retry on error."""
    req = urllib.request.Request(url, headers={'User-Agent': USER_AGENT})
    for attempt in range(2):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.loads(resp.read().decode('utf-8'))
        except Exception as e:
            if attempt == 0:
                eprint(f"  Warning: {e} — retrying in 2s …")
                time.sleep(2)
            else:
                raise
    raise RuntimeError(f"HTTP GET failed: {url}")


def fetch_search_ids(dept_id: int) -> list[int]:
    """Fetch objectID list for a department from the Met search endpoint."""
    cache_file = os.path.join(CACHE_DIR, f"search_{dept_id}.json")
    if os.path.exists(cache_file):
        eprint(f"  Using cached search for dept {dept_id}: {cache_file}")
        with open(cache_file, encoding='utf-8') as f:
            data = json.load(f)
        return data.get('objectIDs') or []

    url = (
        f"{SEARCH_URL}?q=&hasImages=true&isPublicDomain=true"
        f"&departmentId={dept_id}"
    )
    eprint(f"  Fetching dept {dept_id} search …")
    try:
        data = http_get_json(url)
    except Exception as e:
        eprint(f"  Failed to fetch dept {dept_id}: {e}")
        return []

    os.makedirs(CACHE_DIR, exist_ok=True)
    with open(cache_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False)
    ids = data.get('objectIDs') or []
    eprint(f"  Dept {dept_id}: {len(ids):,} objects")
    return ids


def fetch_object(object_id: int) -> dict | None:
    """Fetch a single object JSON; use cache if available."""
    cache_file = os.path.join(OBJECTS_DIR, f"{object_id}.json")
    if os.path.exists(cache_file):
        with open(cache_file, encoding='utf-8') as f:
            return json.load(f)
    url = OBJECT_URL.format(object_id)
    try:
        data = http_get_json(url)
    except Exception as e:
        eprint(f"  Warning: failed to fetch object {object_id}: {e}")
        return None
    os.makedirs(OBJECTS_DIR, exist_ok=True)
    with open(cache_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False)
    return data


def passes_filter(obj: dict, include_all: bool) -> bool:
    """Return True if this object should be included."""
    if not obj.get('isPublicDomain'):
        return False
    title  = (obj.get('title') or '').strip()
    artist = (obj.get('artistDisplayName') or '').strip()
    if not title and not artist:
        return False
    if include_all:
        return True
    dept = obj.get('department') or ''
    if 'Modern and Contemporary' in dept:
        return False
    end_date = obj.get('objectEndDate')
    if end_date is not None:
        try:
            return int(end_date) <= 1900
        except (ValueError, TypeError):
            pass
    return True


def build_record(obj: dict) -> dict:
    """Extract fields needed for atom emission."""
    object_id  = obj.get('objectID', 0)
    title      = (obj.get('title') or '').strip()
    artist     = (obj.get('artistDisplayName') or '').strip()
    medium     = (obj.get('medium') or '').strip()
    date_str   = (obj.get('objectDate') or '').strip()
    wikidata_u = (obj.get('wikidataUrl') or '').strip()

    year       = extract_year(date_str) if date_str else ''
    medium_short = medium[:50] if medium else ''
    qid        = extract_qid(wikidata_u) if wikidata_u else ''
    object_url = f"https://www.metmuseum.org/art/collection/search/{object_id}"

    return {
        'object_id':    object_id,
        'title':        title or f"Untitled (Met {object_id})",
        'artist':       artist,
        'medium_short': medium_short,
        'year':         year,
        'date_str':     date_str,
        'qid':          qid,
        'object_url':   object_url,
    }


def assign_atom_keys(records: list[dict]) -> None:
    """Assign unique atom_key to each record in-place."""
    seen: dict[str, int] = {}
    suffixes = ['_b', '_c', '_d', '_e', '_f', '_g', '_h']
    for rec in records:
        nt   = norm_title(rec['title'])
        year = rec['year']
        base = f"{nt}_{year}" if year else nt
        if base not in seen:
            seen[base] = 0
            rec['atom_key'] = base
        else:
            idx = seen[base]
            seen[base] = idx + 1
            suffix = suffixes[idx] if idx < len(suffixes) else f"_{idx + 2}"
            rec['atom_key'] = base + suffix


def build_description(rec: dict) -> str:
    """Build ≤280-char description omitting absent fields."""
    parts = [rec['title']]
    if rec['year']:
        parts[0] = f"{rec['title']} ({rec['year']})"
    if rec['artist']:
        parts.append(rec['artist'])
    if rec['medium_short']:
        parts.append(rec['medium_short'])
    parts.append('Metropolitan Museum of Art')
    desc = '; '.join(parts) + f". {rec['object_url']}"
    return truncate(desc, 280)


def emit_artwork_block(rec: dict) -> list[str]:
    """Return list of .ak lines for one artwork."""
    atom  = f"art:work:{rec['atom_key']}"
    desc  = build_description(rec)
    lines = [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} art:met:{rec["object_id"]}',
    ]
    if rec['qid']:
        lines.append(f'al {atom} art:wd:{rec["qid"]}')
    lines.append(f'ln {atom} art:work sys:part_of')
    lines.append(f'set.add name="ontology.artworks" id="{atom}"')
    lines.append('')
    return lines


def fetch_all_objects(dept_ids: list[int], max_objects: int | None,
                      include_all: bool) -> list[dict]:
    """Fetch object IDs for all departments, then fetch each object JSON."""
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(OBJECTS_DIR, exist_ok=True)

    # Collect all object IDs (deduplicated)
    all_ids: list[int] = []
    seen_ids: set[int] = set()
    for dept_id in dept_ids:
        ids = fetch_search_ids(dept_id)
        for oid in ids:
            if oid not in seen_ids:
                seen_ids.add(oid)
                all_ids.append(oid)

    eprint(f"  Total unique object IDs: {len(all_ids):,}")
    if max_objects:
        all_ids = all_ids[:max_objects]
        eprint(f"  Limited to: {max_objects:,} (--max-objects)")

    # Fetch each object
    records: list[dict] = []
    skipped = 0
    for i, oid in enumerate(all_ids):
        if i > 0 and i % 100 == 0:
            eprint(f"  Fetched {i:,}/{len(all_ids):,} … ({len(records):,} kept, "
                   f"{skipped} skipped)")
        obj = fetch_object(oid)
        if obj is None:
            skipped += 1
            continue
        # Rate-limit only when actually downloading (not from cache)
        cache_file = os.path.join(OBJECTS_DIR, f"{oid}.json")
        # If file was just created (size matches download) we slept inside retry;
        # add polite delay for new downloads based on whether file existed before
        if not os.path.exists(cache_file):
            time.sleep(0.1)
        if not passes_filter(obj, include_all):
            skipped += 1
            continue
        records.append(build_record(obj))

    eprint(f"  Fetched {len(all_ids):,} objects: {len(records):,} kept, "
           f"{skipped} skipped")
    return records


def generate(records: list[dict], out_dir: str, chunk_size: int,
             dry_run: bool) -> None:
    """Build .ak output and write chunk files."""
    assign_atom_keys(records)

    all_lines: list[str] = []
    for rec in records:
        all_lines.extend(emit_artwork_block(rec))

    n_total = len(records)
    n_files = (n_total + chunk_size - 1) // chunk_size
    eprint(f"\n  Artworks: {n_total:,}")
    eprint(f"  Files:    {n_files} × {chunk_size} → met_artworks_{{NN}}.ak")
    eprint(f"  Output:   {out_dir}/")

    if dry_run:
        print("# --- DRY RUN: first 20 output lines ---")
        print(NAMESPACE_ANCHOR.rstrip())
        count = 0
        for line in all_lines:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    os.makedirs(out_dir, exist_ok=True)

    # Split into per-artwork blocks (blank-line terminated)
    blocks: list[list[str]] = []
    current: list[str] = []
    for line in all_lines:
        current.append(line)
        if line == '':
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    n_chunks = (len(blocks) + chunk_size - 1) // chunk_size
    for i in range(n_chunks):
        chunk_blocks = blocks[i * chunk_size:(i + 1) * chunk_size]
        fname = f"met_artworks_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk_blocks) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, entry_range=f"{start}–{end}"))
            if i == 0:
                fh.write(NAMESPACE_ANCHOR)
            for block in chunk_blocks:
                fh.write('\n'.join(block) + '\n')
        eprint(f"  {fname}  {len(chunk_blocks):5d} entries", flush=True)

    eprint(f"\n  Done → {out_dir}/")
    eprint("\nNext: git add app/ontology/art/met_artworks_*.ak && git commit")


def print_network_help():
    eprint("""
The Met API is at: https://collectionapi.metmuseum.org/public/collection/v1/
No authentication required. Run with: python app/scripts/met_artworks_import.py
Network errors will be retried once. Objects already cached in out/met_cache/ are reused.
""")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--out', default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=1000,
                    help='Atoms per .ak file (default: 1000)')
    ap.add_argument('--dept-ids', default=','.join(str(d) for d in DEFAULT_DEPT_IDS),
                    help='Comma-separated department IDs (default: 11,3,14,19)')
    ap.add_argument('--max-objects', type=int, default=None,
                    help='Limit total objects fetched (default: no limit)')
    ap.add_argument('--all', action='store_true',
                    help='Include post-1900 works too')
    ap.add_argument('--dry-run', action='store_true',
                    help='Print first 20 lines to stdout, write no files')
    args = ap.parse_args()

    try:
        dept_ids = [int(d.strip()) for d in args.dept_ids.split(',') if d.strip()]
    except ValueError:
        eprint(f"Error: --dept-ids must be comma-separated integers, got: {args.dept_ids}")
        sys.exit(1)

    eprint('[met_artworks_import] Starting …')
    eprint(f'  Departments: {dept_ids}')
    if args.max_objects:
        eprint(f'  Max objects: {args.max_objects}')
    eprint(f'  Cache dir:   {CACHE_DIR}')
    eprint(f'  Output dir:  {args.out}')

    try:
        records = fetch_all_objects(dept_ids, args.max_objects, args.all)
    except Exception as e:
        eprint(f'\nError: {e}')
        print_network_help()
        sys.exit(1)

    if not records:
        eprint('No records after filtering. Check --dept-ids or try --all.')
        sys.exit(0)

    eprint(f'\n[met_artworks_import] Generating .ak output for {len(records):,} artworks …')
    generate(records, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
