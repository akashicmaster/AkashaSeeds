"""
pantheon_import.py — Pantheon 2.0 dataset → out/people/pantheon_NN.ak

Converts the MIT Media Lab / Harvard Dataverse Pantheon 2.0 dataset of
historically notable people to Akasha .ak ontology files.

Filters applied:
    - HPI >= --min-hpi  (default: 10.0)   Historical Popularity Index
    - L   >= --min-langs (default: 10)    Wikipedia language editions

Atom IDs:    person:{slug}              e.g. person:aristotle
Aliases:     person:pantheon:{id}       (Pantheon numeric ID)
Links:       sys:part_of → person:field:{domain}  e.g. person:field:philosophy
Sets:        person:pantheon

Attribution:
    Pantheon 2.0 — MIT Media Lab / Harvard Dataverse
    https://pantheon.world/
    MIT License — https://opensource.org/licenses/MIT

Usage:
    # Download from Pantheon API and convert:
    python app/scripts/pantheon_import.py

    # Use pre-downloaded CSV:
    python app/scripts/pantheon_import.py --csv /path/to/people.csv

    # Dry run (stats only, no files written):
    python app/scripts/pantheon_import.py --dry-run

    # Lower HPI threshold:
    python app/scripts/pantheon_import.py --min-hpi 5.0

    # Custom output directory:
    python app/scripts/pantheon_import.py --out out/people

Options:
    --csv FILE        Pre-downloaded people CSV (bypass download)
    --out DIR         Output directory (default: out/people)
    --chunk-size N    Atoms per .ak file (default: 500)
    --min-hpi FLOAT   Minimum HPI to include (default: 10.0)
    --min-langs INT   Minimum Wikipedia language editions (default: 10)
    --dry-run         Print stats only, write no files

Source files:
    https://pantheon.world/api/personExport?mode=csv
    Fallback: https://dataverse.harvard.edu/api/access/datafile/2556642
"""

import argparse
import csv
import io
import os
import re
import sys
import unicodedata
import urllib.error
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "out", "people")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "pantheon_cache")
CACHE_FILE   = os.path.join(CACHE_DIR, "people.csv")

PANTHEON_URL_PRIMARY  = "https://pantheon.world/api/personExport?mode=csv"
PANTHEON_URL_FALLBACK = "https://dataverse.harvard.edu/api/access/datafile/2556642"
PANTHEON_PROFILE_BASE = "https://pantheon.world/profile/person/"

USER_AGENT = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

# Mapping from Pantheon domain strings to known person:field: IDs.
# Domain values in the dataset are typically uppercase strings.
DOMAIN_FIELD_MAP: dict[str, str] = {
    "ARTS":                       "visual_arts",
    "VISUAL ARTS":                "visual_arts",
    "MUSIC":                      "music",
    "SCIENCE & TECHNOLOGY":       "science",
    "SCIENCE":                    "science",
    "TECHNOLOGY":                 "engineering_invention",
    "HUMANITIES":                 "linguistics_scholarship",
    "SOCIAL SCIENCES":            "linguistics_scholarship",
    "PHILOSOPHY & RELIGION":      "philosophy",
    "PHILOSOPHY":                 "philosophy",
    "RELIGION":                   "religion",
    "LITERATURE":                 "literature",
    "SPORTS":                     None,   # no matching field atom — skip link
    "INSTITUTIONS":               "politics_statecraft",
    "POLITICS":                   "politics_statecraft",
    "POLITICS & GOVERNMENT":      "politics_statecraft",
    "MILITARY":                   "military",
    "BUSINESS & LAW":             "law",
    "LAW":                        "law",
    "ECONOMICS":                  "economics",
    "EXPLORATION":                "exploration_navigation",
    "MEDICINE":                   "medicine",
    "MATHEMATICS":                "mathematics",
    "ARCHITECTURE":               "architecture",
    "THEATER":                    "theater_performing_arts",
    "PERFORMING ARTS":            "theater_performing_arts",
    "ENGINEERING":                "engineering_invention",
    "LINGUISTICS":                "linguistics_scholarship",
}

# Valid person:field: atom IDs (used to validate mapped values)
KNOWN_FIELDS = frozenset({
    "philosophy", "science", "mathematics", "medicine", "literature",
    "music", "visual_arts", "architecture", "religion", "politics_statecraft",
    "military", "exploration_navigation", "law", "economics",
    "engineering_invention", "theater_performing_arts", "linguistics_scholarship",
})

FILE_HEADER = """\
# {filename}
# Pantheon 2.0 — MIT Media Lab / Harvard Dataverse — MIT License
# https://pantheon.world/
# Generated by app/scripts/pantheon_import.py — chunk {chunk_num}
# People: {person_range}
#
"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    """Escape double-quotes and backslashes for .ak def strings."""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def truncate(s: str, n: int = 320) -> str:
    if len(s) <= n:
        return s
    return s[:n - 1].rsplit(' ', 1)[0].rstrip(' ,;') + '…'


def normalize_slug(s: str) -> str:
    """Convert a name/slug to a safe atom ID component."""
    # Strip accents
    s = unicodedata.normalize('NFD', s)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = s.lower()
    s = re.sub(r"[\s\-,.'()/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:50]


def map_domain_to_field(domain: str) -> str | None:
    """Map a Pantheon domain string to a person:field: atom ID, or None to skip."""
    if not domain:
        return None
    key = domain.strip().upper()
    field = DOMAIN_FIELD_MAP.get(key)
    if field is None:
        return None
    if field not in KNOWN_FIELDS:
        return None
    return field


def build_description(row: dict) -> str:
    """Build atom description from a Pantheon CSV row."""
    name      = row.get('name', '').strip()
    slug      = row.get('slug', '').strip() or normalize_slug(name)
    occupation = row.get('occupation', '').strip()
    birthyear = row.get('birthyear', '').strip()
    deathyear = row.get('deathyear', '').strip()

    try:
        hpi = float(row.get('HPI') or row.get('hpi') or 0)
        hpi_str = f"{hpi:.1f}"
    except (ValueError, TypeError):
        hpi_str = ''

    # Date range
    if birthyear and deathyear:
        dates = f"({birthyear}–{deathyear})"
    elif birthyear:
        dates = f"({birthyear}–)"
    else:
        dates = ''

    url = f"{PANTHEON_PROFILE_BASE}{slug}"

    parts: list[str] = []
    name_part = name
    if dates:
        name_part = f"{name} {dates}"
    parts.append(name_part)
    if occupation:
        parts.append(occupation)
    if hpi_str:
        parts.append(f"HPI:{hpi_str}")
    parts.append(url)

    desc = '. '.join(parts)
    # Use '. ' between segments except the URL segment which uses a space
    # Rebuild more cleanly:
    segments = []
    if name_part:
        segments.append(name_part)
    if occupation:
        segments.append(occupation)
    if hpi_str:
        segments.append(f"HPI:{hpi_str}")

    desc = ', '.join(segments)
    if hpi_str:
        # Reformat: "Name (dates), occupation. HPI:xx.x. URL"
        base = ', '.join(segments[:-1]) if len(segments) > 1 else segments[0]
        desc = f"{base}. HPI:{hpi_str}. {url}"
    else:
        desc = f"{desc}. {url}"

    return truncate(desc, 320)


def emit_person(fh, row: dict) -> None:
    """Write one person atom block to fh."""
    name      = row.get('name', '').strip()
    slug      = (row.get('slug') or '').strip()
    if not slug:
        slug = normalize_slug(name)
    else:
        # Keep existing slug — it's already URL-safe — but normalise to lowercase
        slug = slug.lower().strip()

    person_id = row.get('id', '').strip()
    domain    = row.get('domain', '').strip()

    atom  = f"person:{slug}"
    desc  = build_description(row)
    field = map_domain_to_field(domain)

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    if person_id:
        alias = f"person:pantheon:{person_id}"
        fh.write(f'al {atom} {alias}\n')
    if field:
        fh.write(f'ln {atom} person:field:{field} sys:part_of\n')
    fh.write(f'set.add name="person:pantheon" id="{atom}"\n')
    fh.write('\n')


def download_csv(url: str, dest: str, label: str) -> None:
    """Download a URL to dest with progress output."""
    eprint(f"Downloading {label} …")
    req = urllib.request.Request(url, headers={'User-Agent': USER_AGENT})

    def _prog(b, bs, ts):
        if ts > 0:
            pct = min(100, b * bs * 100 // ts)
            print(f"\r  {pct}%", end='', flush=True, file=sys.stderr)

    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            data = resp.read()
        eprint()   # newline after progress
        with open(dest, 'wb') as f:
            f.write(data)
        eprint(f"  Saved to {dest}")
    except Exception:
        eprint()
        raise


def ensure_csv(csv_arg: str | None) -> str:
    """Return path to the people CSV, downloading if necessary."""
    if csv_arg:
        return csv_arg

    os.makedirs(CACHE_DIR, exist_ok=True)

    if os.path.exists(CACHE_FILE):
        eprint(f"Using cached: {CACHE_FILE}")
        return CACHE_FILE

    # Try primary URL first
    try:
        download_csv(PANTHEON_URL_PRIMARY, CACHE_FILE, "Pantheon people.csv (primary URL)")
        return CACHE_FILE
    except Exception as e:
        eprint(f"  Primary URL failed: {e}")

    # Try fallback URL
    eprint("  Trying fallback URL …")
    try:
        download_csv(PANTHEON_URL_FALLBACK, CACHE_FILE, "Pantheon people.csv (Harvard Dataverse)")
        return CACHE_FILE
    except Exception as e:
        eprint(f"  Fallback URL failed: {e}")

    raise urllib.error.URLError("All download URLs failed")


def load_people(csv_path: str, min_hpi: float, min_langs: int) -> list[dict]:
    """Parse CSV; apply HPI and language edition filters; sort by HPI descending."""
    people: list[dict] = []
    with open(csv_path, encoding='utf-8', newline='') as f:
        # Pantheon CSV may use different encodings; try UTF-8 first
        reader = csv.DictReader(f)
        for row in reader:
            try:
                hpi_val = float(row.get('HPI') or row.get('hpi') or 0)
            except (ValueError, TypeError):
                hpi_val = 0.0
            try:
                l_val = int(float(row.get('L') or row.get('l') or 0))
            except (ValueError, TypeError):
                l_val = 0

            if hpi_val < min_hpi:
                continue
            if l_val < min_langs:
                continue

            people.append(dict(row))

    # Sort by HPI descending
    people.sort(key=lambda r: -float(r.get('HPI') or r.get('hpi') or 0))
    return people


def generate(people: list[dict], out_dir: str, chunk_size: int, dry_run: bool) -> None:
    total     = len(people)
    num_files = (total + chunk_size - 1) // chunk_size if total else 0

    # Domain breakdown
    domain_counts: dict[str, int] = {}
    for p in people:
        d = (p.get('domain') or 'UNKNOWN').strip()
        domain_counts[d] = domain_counts.get(d, 0) + 1

    eprint(f"\n  People: {total:,}")
    eprint(f"  Files:  {num_files} × {chunk_size} → pantheon_{{NN}}.ak")
    eprint(f"  Top domains:")
    for d, cnt in sorted(domain_counts.items(), key=lambda x: -x[1])[:10]:
        eprint(f"    {d:40s} {cnt:5d}")

    if dry_run:
        eprint('\n--- dry-run: first 20 output lines ---')
        import io as _io
        buf = _io.StringIO()
        for p in people[:5]:
            emit_person(buf, p)
        lines = buf.getvalue().splitlines()
        for line in lines[:20]:
            print(line)
        return

    if total == 0:
        eprint('[pantheon_import] No people to write.')
        return

    os.makedirs(out_dir, exist_ok=True)

    for i in range(num_files):
        chunk  = people[i * chunk_size:(i + 1) * chunk_size]
        fname  = f"pantheon_{i + 1:02d}.ak"
        fpath  = os.path.join(out_dir, fname)
        start  = i * chunk_size + 1
        end    = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(
                filename=fname,
                chunk_num=i + 1,
                person_range=f"{start}–{end}",
            ))
            for p in chunk:
                emit_person(fh, p)
        eprint(f"  {fname}  {len(chunk):5d} people", flush=True)

    eprint(f"\n  Total: {total:,} people in {num_files} files → {out_dir}/")
    eprint("\nNext: git add out/people/pantheon_*.ak && git commit")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--csv',        help='Pre-downloaded people CSV (bypass download)')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--min-hpi',    type=float, default=10.0,
                    help='Minimum HPI to include (default: 10.0)')
    ap.add_argument('--min-langs',  type=int, default=10,
                    help='Minimum Wikipedia language editions (default: 10)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    eprint('[pantheon_import] Locating source CSV …')
    try:
        csv_path = ensure_csv(args.csv)
    except Exception as e:
        eprint(f'\nError: {e}')
        eprint('\nManual download steps:')
        eprint(f'  1. Visit https://pantheon.world/data/datasets')
        eprint(f'     or try direct: {PANTHEON_URL_PRIMARY}')
        eprint(f'     or Harvard Dataverse: {PANTHEON_URL_FALLBACK}')
        eprint(f'  2. Save as people.csv')
        eprint(f'Re-run with:')
        eprint(f'  --csv /path/to/people.csv')
        sys.exit(1)

    eprint(f'[pantheon_import] Loading CSV: {csv_path} …')
    try:
        people = load_people(csv_path, args.min_hpi, args.min_langs)
    except Exception as e:
        eprint(f'\nError reading CSV: {e}')
        sys.exit(1)

    eprint(f'[pantheon_import] Loaded {len(people):,} people '
           f'(HPI≥{args.min_hpi}, L≥{args.min_langs})')

    generate(people, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
