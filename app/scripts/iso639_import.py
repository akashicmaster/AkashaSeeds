"""
iso639_import.py — ISO 639-3 language codes → ontology/common/lang.ak

Converts the SIL International ISO 639-3 code table to Akasha .ak atoms
for ontology/common/.

Atom IDs:    lang:{iso639_3}         e.g. lang:eng, lang:jpn, lang:zho
ISO 639-1:   lang:iso1:{iso639_1}    e.g. lang:iso1:en  (alias, where it exists)
Links:       sys:part_of → lang:macrolanguage:{macro}  (for individual dialects)
             sys:part_of → lang:scope:{scope}           (Living / Ancient / etc.)

Scope codes (from SIL):
    I  Individual language
    M  Macrolanguage
    S  Special code (e.g. und, mul, zxx)

Type codes:
    A  Ancient
    C  Constructed
    E  Extinct
    H  Historical
    L  Living
    S  Special

By default, only scope I + M are included; type S excluded.

Attribution:
    ISO 639-3 Registration Authority (SIL International)
    https://iso639-3.sil.org/
    Public domain per SIL terms of use

Usage:
    python app/scripts/iso639_import.py

    python app/scripts/iso639_import.py --lang-file /path/to/iso-639-3.tab

    python app/scripts/iso639_import.py --dry-run

Options:
    --lang-file FILE   Pre-downloaded iso-639-3.tab
    --out DIR          Output file or directory (default: ontology/common/lang_iso639.ak)
    --dry-run          Print stats only, write no files
    --include-extinct  Also include extinct (E) and historical (H) languages
"""

import argparse
import os
import re
import sys
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "ontology", "common", "lang_iso639.ak")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "iso639_cache")

LANG_URL = "https://iso639-3.sil.org/sites/iso639-3/files/downloads/iso-639-3.tab"

# Column indices in iso-639-3.tab
F_ID    = 0   # Id           (ISO 639-3)
F_P2B   = 1   # Part2B       (ISO 639-2/B, bibliographic)
F_P2T   = 2   # Part2T       (ISO 639-2/T, terminology)
F_P1    = 3   # Part1        (ISO 639-1, 2-letter)
F_SCOPE = 4   # Scope        I / M / S
F_TYPE  = 5   # Language_Type A / C / E / H / L / S
F_NAME  = 6   # Ref_Name
F_COMM  = 7   # Comment

SCOPE_LABEL = {
    'I': 'individual language',
    'M': 'macrolanguage',
    'S': 'special code',
}

TYPE_LABEL = {
    'A': 'Ancient',
    'C': 'Constructed',
    'E': 'Extinct',
    'H': 'Historical',
    'L': 'Living',
    'S': 'Special',
}

FILE_HEADER = """\
# lang_iso639.ak
# ISO 639-3 language codes — SIL International — https://iso639-3.sil.org/
# Public domain per SIL terms of use
# Generated by app/scripts/iso639_import.py
# Languages: {count}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def parse_iso639(path: str, include_extinct: bool) -> list[dict]:
    """
    Parse iso-639-3.tab → list of language dicts.
    Keys: id, iso1, scope, ltype, name
    """
    langs: list[dict] = []
    with open(path, encoding='utf-8') as f:
        next(f)  # skip header line
        for line in f:
            cols = line.rstrip('\n').split('\t')
            if len(cols) < 7:
                continue
            lid    = cols[F_ID].strip()
            iso1   = cols[F_P1].strip()
            scope  = cols[F_SCOPE].strip()
            ltype  = cols[F_TYPE].strip()
            name   = cols[F_NAME].strip()
            if not lid or not name:
                continue
            if scope == 'S':   # skip und/mul/zxx etc.
                continue
            if ltype in ('E', 'H') and not include_extinct:
                continue
            langs.append({
                'id':    lid,
                'iso1':  iso1,
                'scope': scope,
                'ltype': ltype,
                'name':  name,
            })
    # Sort: macrolanguages first, then alphabetically by name
    langs.sort(key=lambda l: (0 if l['scope'] == 'M' else 1, l['name']))
    return langs


def emit_lang(fh, lang: dict) -> None:
    """Write one language atom to fh."""
    lid    = lang['id']
    atom   = f"lang:{lid}"
    scope  = SCOPE_LABEL.get(lang['scope'], lang['scope'])
    ltype  = TYPE_LABEL.get(lang['ltype'], lang['ltype'])
    name   = lang['name']

    # Build description
    tags = []
    if lang['ltype'] != 'L':
        tags.append(ltype)
    if lang['scope'] == 'M':
        tags.append('macrolanguage')
    tag_str = f" ({', '.join(tags)})" if tags else ''
    desc = f"{name}{tag_str}"

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')

    # ISO 639-1 alias
    if lang['iso1']:
        fh.write(f'al {atom} lang:iso1:{lang["iso1"]}\n')

    fh.write('\n')


def generate(langs: list[dict], out_path: str, dry_run: bool):
    total   = len(langs)
    living  = sum(1 for l in langs if l['ltype'] == 'L')
    macro   = sum(1 for l in langs if l['scope'] == 'M')
    with_iso1 = sum(1 for l in langs if l['iso1'])

    print(f"\n  Languages: {total}")
    print(f"    Living:          {living}")
    print(f"    Macrolanguages:  {macro}")
    print(f"    With ISO 639-1:  {with_iso1}")
    print(f"  Output: {out_path}")

    if dry_run:
        return

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as fh:
        fh.write(FILE_HEADER.format(count=total))
        for lang in langs:
            emit_lang(fh, lang)

    print(f"\n  Written: {total} atoms → {out_path}")
    print("\nNext: git add ontology/common/lang_iso639.ak && git commit")


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_lang_file(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, 'iso-639-3.tab')
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    _download(LANG_URL, dest, "iso-639-3.tab (~1 MB)")
    return dest


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--lang-file',       help='Pre-downloaded iso-639-3.tab')
    ap.add_argument('--out',             default=DEFAULT_OUT,
                    help=f'Output path (default: {DEFAULT_OUT})')
    ap.add_argument('--dry-run',         action='store_true',
                    help='Print stats only, write no files')
    ap.add_argument('--include-extinct', action='store_true',
                    help='Include extinct (E) and historical (H) languages')
    args = ap.parse_args()

    print('[iso639_import] Locating source file …')
    try:
        lang_path = ensure_lang_file(args.lang_file)
    except Exception as e:
        print(f'\nError: {e}')
        print(f'\nManual download: {LANG_URL}')
        print(f'Re-run with: --lang-file /path/to/iso-639-3.tab')
        sys.exit(1)

    print('[iso639_import] Parsing …')
    langs = parse_iso639(lang_path, args.include_extinct)

    generate(langs, args.out, args.dry_run)


if __name__ == '__main__':
    main()
