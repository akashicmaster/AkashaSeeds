#!/usr/bin/env python3
"""
thecocktaildb_import.py — TheCocktailDB → cocktails_NN.ak (C-tier drinks pack).

TheCocktailDB is the cocktail sibling of TheMealDB (which Akasha already uses for
recipes). This walks its free JSON API and turns every drink into an Akasha atom with
its category, glass, alcoholic class, IBA-official status, method, and ingredient links
— so the graph answers "cocktails that use gin", "IBA official drinks", "served in a
coupe", etc. Reuses the existing wine-pack vocabulary (glassware:, cocktail:method:,
cocktail:served_in).

Atom IDs:
    cocktail:cocktail                 root concept
    cocktail:category:{cat}           Ordinary Drink / Cocktail / Shot / …  (sys:is_a root)
    cocktail:{slug}                   one per drink → sys:is_a its category
    ing:{slug}                        one per distinct ingredient (gin, lime juice, …)
    glassware:{slug}                  reused if present (defined here if new)
Links / sets:
    cocktail:{d} glassware:{g} cocktail:served_in
    cocktail:{d} ing:{i}       cocktail:uses          (dive an ingredient → its drinks)
    cocktail:{d} cocktail:method:{m} cocktail:method  (shaken/stirred/built, if inferable)
    set cocktails · cocktail:iba · cocktail:alcoholic / cocktail:nonalcoholic

Source & attribution (required by TheCocktailDB terms — same provider as our TheMealDB
recipe import): data © TheCocktailDB — https://www.thecocktaildb.com/. The free
development API key is "1".

Usage:
    python app/scripts/thecocktaildb_import.py                     # fetch (a-z,0-9) + write
    python app/scripts/thecocktaildb_import.py --key <API_KEY>     # a paid/patreon key
    python app/scripts/thecocktaildb_import.py --input dump.json   # a local list of drink dicts
    python app/scripts/thecocktaildb_import.py --dry-run
    python app/scripts/thecocktaildb_import.py --out app/ontology/drinks_c
"""
import argparse
import json
import os
import re
import sys
import time
import urllib.request

API = "https://www.thecocktaildb.com/api/json/v1/{key}/search.php?f={ch}"

_METHOD_HINTS = [
    ("shaken", "shake"), ("stirred", "stir"), ("blended", "blend"),
    ("muddled", "muddle"), ("built", "build over"), ("built", "pour"),
]


def slug(s: str) -> str:
    s = (s or "").lower().strip()
    s = re.sub(r"[&/]", " and ", s)
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or "x"


def esc(s: str) -> str:
    # Descriptions live in a double-quoted .ak arg on ONE line: drop quotes and
    # collapse ALL whitespace (incl. \r — TheCocktailDB instructions use \r\n, and a
    # stray \r would split the statement across lines).
    import re as _re
    return _re.sub(r"\s+", " ", (s or "").replace('"', "'")).strip()


def fetch_all(key):
    """Walk search.php?f=<char> over a-z + 0-9; dedup by idDrink."""
    drinks, seen = [], set()
    for ch in "abcdefghijklmnopqrstuvwxyz0123456789":
        url = API.format(key=key, ch=ch)
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "akasha-import"})
            with urllib.request.urlopen(req, timeout=60) as r:
                data = json.loads(r.read().decode("utf-8", errors="replace"))
        except Exception as e:
            print(f"  [!] fetch '{ch}' failed: {e}", file=sys.stderr)
            continue
        for d in (data.get("drinks") or []):
            did = d.get("idDrink")
            if did and did not in seen:
                seen.add(did)
                drinks.append(d)
        time.sleep(0.2)          # be polite to the free API
    return drinks


def _ingredients(d):
    out = []
    for i in range(1, 16):
        ing = (d.get(f"strIngredient{i}") or "").strip()
        meas = (d.get(f"strMeasure{i}") or "").strip()
        if ing:
            out.append((ing, meas))
    return out


def _method(instructions):
    t = (instructions or "").lower()
    for m, kw in _METHOD_HINTS:
        if kw in t:
            return m
    return None


def build(drinks):
    lines = [
        "# TheCocktailDB — cocktail catalogue (C-tier). Generated by "
        "scripts/thecocktaildb_import.py.",
        "# Data © TheCocktailDB — https://www.thecocktaildb.com/ (attribution required).",
        "",
        'def "cocktail:cocktail" "A mixed drink of spirits, mixers and garnish (カクテル)."',
        "",
    ]
    cats, glasses, ings, methods = {}, {}, {}, set()
    body = []
    for d in drinks:
        name = (d.get("strDrink") or "").strip()
        if not name:
            continue
        cid = f"cocktail:{slug(name)}"
        cat = (d.get("strCategory") or "").strip()
        glass = (d.get("strGlass") or "").strip()
        alc = (d.get("strAlcoholic") or "").strip()
        iba = (d.get("strIBA") or "").strip()
        instr = (d.get("strInstructions") or "").strip()
        desc = name + (f" — {cat}" if cat else "") + (f", {alc.lower()}" if alc else "")
        if glass:
            desc += f", served in a {glass.lower()}"
        desc += "."
        if instr:
            desc += " " + instr[:200]
        body.append(f'def "{cid}" "{esc(desc)}"')
        body.append(f'set.add name="cocktails" id="{cid}"')
        if cat:
            cs = slug(cat)
            cats[cs] = cat
            body.append(f"ln {cid} cocktail:category:{cs} sys:is_a")
        if glass:
            gs = slug(glass)
            glasses[gs] = glass
            body.append(f"ln {cid} glassware:{gs} cocktail:served_in")
        m = _method(instr)
        if m:
            methods.add(m)
            body.append(f"ln {cid} cocktail:method:{m} cocktail:method")
        if iba:
            body.append(f'set.add name="cocktail:iba" id="{cid}"')
        if alc:
            setn = "cocktail:alcoholic" if alc.lower().startswith("alcohol") else "cocktail:nonalcoholic"
            body.append(f'set.add name="{setn}" id="{cid}"')
        for ing, meas in _ingredients(d):
            isl = slug(ing)
            ings[isl] = ing
            body.append(f"ln {cid} ing:{isl} cocktail:uses")

    # concept atoms (defined once, before the body that references them)
    for cs, cat in sorted(cats.items()):
        lines.append(f'def "cocktail:category:{cs}" "{esc(cat)} — a cocktail category."')
        lines.append(f"ln cocktail:category:{cs} cocktail:cocktail sys:is_a")
    for gs, g in sorted(glasses.items()):
        lines.append(f'def "glassware:{gs}" "{esc(g)} — a serving glass."')
    for m in sorted(methods):
        lines.append(f'def "cocktail:method:{m}" "Mixed by {m} (technique)."')
    for isl, ing in sorted(ings.items()):
        lines.append(f'def "ing:{isl}" "{esc(ing)} — a cocktail ingredient."')
    lines.append("")
    lines += body
    return lines, len(drinks), len(cats), len(ings)


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--key", default="1", help="TheCocktailDB API key (default: free dev key 1)")
    ap.add_argument("--input", help="local JSON: a list of drink dicts (skip fetching)")
    ap.add_argument("--out", default="app/ontology/drinks_c")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv[1:])

    if args.input:
        raw = json.load(open(args.input, encoding="utf-8"))
        drinks = raw.get("drinks") if isinstance(raw, dict) else raw
    else:
        drinks = fetch_all(args.key)
    lines, nd, nc, ni = build(drinks or [])
    print(f"cocktails: {nd}  |  categories: {nc}  |  distinct ingredients: {ni}")
    if args.dry_run:
        print("\n".join(lines[:20]))
        return 0
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "cocktails.ak")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}  ({os.path.getsize(path)//1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
