"""
jpl_asteroids_import.py — JPL Small-Body Database → app/ontology/space/asteroids_NN.ak

Converts named minor planets from the JPL Small-Body Database Query API to
Akasha .ak ontology files for app/ontology/space/.

Filters:
    - Asteroid class (sb-kind=a), all numbered objects
    - Keep only entries where 'name' field is a non-empty alphabetic word
      (i.e. proper names like "Ceres", "Vesta", "Eros" — not bare numbers)

Atom IDs:    astro:asteroid:{normalized_name}    e.g. astro:asteroid:ceres
Aliases:     astro:asteroid:jpl:{spkid}          (JPL SPK ID)
Links:       sys:part_of → astro:asteroid        (parent collection atom)

Attribution:
    JPL Small-Body Database — https://ssd.jpl.nasa.gov/tools/sbdb_query.html
    NASA Jet Propulsion Laboratory / California Institute of Technology
    Public domain (U.S. Government work)

Usage:
    # Download from JPL SBDB API and convert:
    python app/scripts/jpl_asteroids_import.py

    # Use pre-downloaded JSON:
    python app/scripts/jpl_asteroids_import.py --json-file out/jpl_asteroid_cache/sbdb_named.json

    # Dry run (stats only, no files written):
    python app/scripts/jpl_asteroids_import.py --dry-run

Options:
    --json-file FILE  Pre-downloaded sbdb_named.json from JPL API
    --out DIR         Output directory (default: app/ontology/space/)
    --chunk-size N    Asteroids per .ak file (default: 2000)
    --dry-run         Print stats only, write no files

Source:
    https://ssd-api.jpl.nasa.gov/sbdb_query.api?sb-kind=a&sb-xfrag=1&limit=100000&...
"""

import argparse
import json
import os
import re
import sys
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "space")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "jpl_asteroid_cache")

API_BASE = "https://ssd-api.jpl.nasa.gov/sbdb_query.api"
API_FIELDS = (
    "spkid,full_name,name,prefix,neo,pha,diameter,albedo,"
    "rot_per,GM,orbit_id,e,a,i,om,w,ma,per,moid"
)
API_URL = (
    f"{API_BASE}"
    f"?fields={API_FIELDS}"
    f"&sb-kind=a"
    f"&full-prec=false"
    f"&sb-xfrag=1"
    f"&limit=100000"
)
CACHE_FILE = "sbdb_named.json"

FILE_HEADER = """\
# {filename}
# JPL Small-Body Database — https://ssd.jpl.nasa.gov/
# NASA Jet Propulsion Laboratory / California Institute of Technology
# Public domain (U.S. Government work)
# Generated by app/scripts/jpl_asteroids_import.py
# Asteroids: {asteroid_range}
#
"""

# Regex: a proper name contains at least one letter and no digit-only content
_NAME_RE = re.compile(r'[A-Za-z]')


def normalize(name: str) -> str:
    """Convert asteroid name to atom name component."""
    s = name.lower()
    s = re.sub(r"[\s\-,.'()/]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:60]


def escape_ak(s: str) -> str:
    """Escape double-quotes and backslashes for .ak def strings."""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def fmt_float(val: str | None, digits: int = 3, suffix: str = '') -> str | None:
    """Parse a float string; return formatted string or None if missing/invalid."""
    if val is None:
        return None
    v = str(val).strip()
    if v in ('', 'nan', 'NaN', 'None', 'null'):
        return None
    try:
        result = f"{float(v):.{digits}f}"
        return result + suffix if suffix else result
    except ValueError:
        return None


def extract_number(full_name: str) -> str | None:
    """Extract the leading number from a full_name like '1 Ceres' or '433 Eros'."""
    m = re.match(r'^\s*(\d+)\s+', full_name)
    return m.group(1) if m else None


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_json(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, CACHE_FILE)
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    _download(API_URL, dest, "JPL SBDB asteroid catalog (~20 MB)")
    return dest


def parse_json(path: str) -> list[dict]:
    """
    Parse JPL SBDB JSON response.
    Format: {"fields": [...], "data": [[val, val, ...], ...]}
    Returns filtered, sorted list of asteroid dicts.
    """
    with open(path, encoding='utf-8') as f:
        raw = json.load(f)

    fields = raw.get('fields', [])
    data   = raw.get('data', [])

    if not fields:
        raise ValueError("JSON response has no 'fields' key — unexpected API format")

    # Build index map from field name to column index
    idx = {name: i for i, name in enumerate(fields)}

    def get(row: list, field: str) -> str | None:
        i = idx.get(field)
        if i is None:
            return None
        v = row[i]
        return str(v).strip() if v is not None else None

    asteroids: list[dict] = []
    for row in data:
        name      = get(row, 'name')
        full_name = get(row, 'full_name') or ''
        spkid     = get(row, 'spkid') or ''

        # Keep only entries with a proper alphabetic name
        if not name or not _NAME_RE.search(name):
            continue

        # Numeric-only "names" (asteroid designations like "2021 XY3") — skip
        # The name field should be a proper word name, not a provisional designation
        # Provisional designations contain digits; proper names are purely alpha
        # e.g. "Ceres", "Vesta", "Eros", "Hidalgo", "Hermes"
        if re.match(r'^\d', name):
            continue

        number = extract_number(full_name)

        try:
            spk_int = int(spkid)
        except (ValueError, TypeError):
            spk_int = 999_999_999

        asteroids.append({
            'name':     name,
            'number':   number,
            'full_name': full_name.strip(),
            'spkid':    spkid,
            'spk_int':  spk_int,
            'neo':      get(row, 'neo') or '',
            'pha':      get(row, 'pha') or '',
            'diameter': get(row, 'diameter'),
            'albedo':   get(row, 'albedo'),
            'rot_per':  get(row, 'rot_per'),
            'a':        get(row, 'a'),      # semi-major axis (AU)
            'per':      get(row, 'per'),    # period (days)
            'e':        get(row, 'e'),      # eccentricity
            'i':        get(row, 'i'),      # inclination (deg)
            'moid':     get(row, 'moid'),   # min orbit intersection dist (AU)
        })

    # Sort by SPK ID (roughly order of discovery/numbering)
    asteroids.sort(key=lambda a: a['spk_int'])
    return asteroids


def build_description(a: dict) -> str:
    """Build the human-readable description for an asteroid."""
    parts = []

    number = a['number']
    name   = a['name']
    if number:
        parts.append(f"{name} — asteroid {number}")
    else:
        parts.append(f"{name} — asteroid")

    diam = fmt_float(a['diameter'], 1, ' km')
    if diam:
        parts.append(f"diameter {diam}")

    sma = fmt_float(a['a'], 3, ' AU')
    if sma:
        parts.append(f"semi-major axis {sma}")

    period = fmt_float(a['per'], 1, ' days')
    if period:
        parts.append(f"period {period}")

    indicators = []
    if a['neo'].upper() == 'Y':
        indicators.append("near-Earth object")
    if a['pha'].upper() == 'Y':
        indicators.append("potentially hazardous asteroid")
    if indicators:
        parts.append('; '.join(indicators))

    return '; '.join(parts)


def emit_asteroid(fh, a: dict) -> None:
    """Write one asteroid atom to fh."""
    norm  = normalize(a['name'])
    atom  = f"astro:asteroid:{norm}"
    alias = f"astro:asteroid:jpl:{a['spkid']}"
    desc  = build_description(a)

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} {alias}\n')
    fh.write(f'ln {atom} astro:asteroid sys:part_of\n')
    fh.write('\n')


def generate(asteroids: list[dict], out_dir: str, chunk_size: int, dry_run: bool):
    total     = len(asteroids)
    num_files = (total + chunk_size - 1) // chunk_size
    neos      = sum(1 for a in asteroids if a['neo'].upper() == 'Y')
    phas      = sum(1 for a in asteroids if a['pha'].upper() == 'Y')

    print(f"\n  Named asteroids: {total}")
    print(f"  NEOs:            {neos}")
    print(f"  PHAs:            {phas}")
    print(f"  Files:           {num_files} × {chunk_size} → asteroids_{{NN}}.ak")

    if dry_run:
        return

    os.makedirs(out_dir, exist_ok=True)

    for i in range(num_files):
        chunk = asteroids[i * chunk_size:(i + 1) * chunk_size]
        fname = f"asteroids_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, asteroid_range=f"{start}–{end}"))
            for a in chunk:
                emit_asteroid(fh, a)
        print(f"  {fname}  {len(chunk):5d} asteroids", flush=True)

    print(f"\n  Total: {total} asteroids in {num_files} files → {out_dir}/")
    print("\nNext: git add app/ontology/space/asteroids_*.ak && git commit")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json-file',  help='Pre-downloaded sbdb_named.json from JPL API')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=2000,
                    help='Asteroids per .ak file (default: 2000)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[jpl_asteroids_import] Locating source data …')
    try:
        json_path = ensure_json(args.json_file)
    except Exception as e:
        print(f'\nError: {e}')
        print('\nManual download:')
        print(f'  {API_URL}')
        print(f'  → save as out/jpl_asteroid_cache/sbdb_named.json')
        print('Re-run with: --json-file /path/to/sbdb_named.json')
        sys.exit(1)

    print(f'[jpl_asteroids_import] Parsing {os.path.basename(json_path)} …')
    try:
        asteroids = parse_json(json_path)
    except Exception as e:
        print(f'\nError parsing JSON: {e}')
        sys.exit(1)

    print(f'  Parsed {len(asteroids)} named asteroids (filtered from full catalog)')

    generate(asteroids, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
