#!/usr/bin/env python3
"""
whisky_flavor_import.py — Scotch distillery flavour profiles → whisky_flavor_NN.ak (C-tier).

The classic 86-single-malt taste dataset (David Wishart / Strathclyde "Nessie"): each
distillery scored 0–4 on 12 aromatic axes (Body, Sweetness, Smoky, Medicinal, Tobacco,
Honey, Spicy, Winey, Nutty, Malty, Fruity, Floral). This gives the drinks_c whisky layer
a real flavour graph — "smoky whiskies", "sweet vs dry" — hanging off the distillery atoms
the Wikidata importer creates (whiskey:distillery:*, matched by name).

Atom IDs / links:
    whiskey:flavor:{axis}                      the 12 axes (sys:is_a whiskey:flavor)
    whiskey:distillery:{slug} score:{0-4} whiskey:flavor:{axis}   per non-zero axis
    set whiskey:flavor:{axis}:high             distilleries scoring >=3 on that axis

Source: David Wishart, "Whisky Classified"; the tidy CSV lives at
    https://www.mathstat.strath.ac.uk/outreach/nessie/datasets/whiskies.txt
Widely redistributed for teaching/research. Download it and pass with --input.

Usage:
    python app/scripts/whisky_flavor_import.py --input whiskies.txt
    python app/scripts/whisky_flavor_import.py --input whiskies.txt --out app/ontology/drinks_c --dry-run
"""
import argparse
import csv
import os
import re
import sys

AXES = ["body", "sweetness", "smoky", "medicinal", "tobacco", "honey", "spicy",
        "winey", "nutty", "malty", "fruity", "floral"]


def slug(s):
    s = (s or "").lower()
    s = re.sub(r"[&/]", " and ", s)
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or "x"


def build(rows):
    lines = [
        "# Scotch distillery flavour profiles (C-tier). Generated by "
        "scripts/whisky_flavor_import.py.",
        "# Source: David Wishart, 'Whisky Classified' (Strathclyde/Nessie dataset).",
        "",
        'def "whiskey:flavor" "A whisky aromatic/taste axis (0-4)."',
    ]
    for a in AXES:
        lines.append(f'def "whiskey:flavor:{a}" "{a.capitalize()} — a whisky taste axis (0-4)."')
        lines.append(f"ln whiskey:flavor:{a} whiskey:flavor sys:is_a")
    lines.append("")

    n = 0
    for r in rows:
        name = (r.get("Distillery") or r.get("distillery") or "").strip()
        if not name:
            continue
        d = f"whiskey:distillery:{slug(name)}"
        n += 1
        for a in AXES:
            raw = (r.get(a.capitalize()) or r.get(a) or "").strip()
            try:
                v = int(float(raw))
            except (TypeError, ValueError):
                continue
            if v <= 0:
                continue
            lines.append(f"ln {d} score:{v} whiskey:flavor:{a}")
            if v >= 3:
                lines.append(f'set.add name="whiskey:flavor:{a}:high" id="{d}"')
    return lines, n


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True, help="whiskies.txt (the 12-axis CSV)")
    ap.add_argument("--out", default="app/ontology/drinks_c")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv[1:])

    with open(args.input, encoding="utf-8", errors="replace") as f:
        rows = list(csv.DictReader(f))
    lines, n = build(rows)
    print(f"distilleries scored: {n}  |  axes: {len(AXES)}")
    if args.dry_run:
        print("\n".join(lines[:20]))
        return 0
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "whisky_flavor.ak")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}  ({os.path.getsize(path)//1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
