# Object types to include by default (DEBRIS excluded unless --include-debris)
PAYLOAD_TYPES = frozenset({'PAYLOAD', 'ROCKET BODY'})
ALL_TYPES     = frozenset({'PAYLOAD', 'ROCKET BODY', 'DEBRIS', 'UNKNOWN'})


def normalize(name: str) -> str:
    """Convert satellite name to atom name component."""
    s = name.lower()
    s = re.sub(r"[\s\-,.'()/\[\]]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:80]


def escape_ak(s: str) -> str:
    """Escape double-quotes and backslashes for .ak def strings."""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def fmt_float(val: str | None, digits: int = 1, suffix: str = '') -> str | None:
    """Parse a float string; return formatted string or None if missing/invalid."""
    if val is None:
        return None
    v = str(val).strip()
    if v in ('', 'nan', 'NaN', 'None', 'null', 'N/A'):
        return None
    try:
        result = f"{float(v):.{digits}f}"
        return result + suffix if suffix else result
    except ValueError:
        return None


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_csv(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, CACHE_FILE)
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    _download(SATCAT_URL, dest, "Celestrak SATCAT (~4 MB)")
    return dest


def parse_csv(path: str, include_debris: bool, min_norad: int) -> list[dict]:
    """
    Parse Celestrak SATCAT CSV; return filtered, sorted list of satellite dicts.
    Column names are read from the CSV header row.
    """
    allowed_types = ALL_TYPES if include_debris else PAYLOAD_TYPES

    satellites: list[dict] = []
    with open(path, encoding='utf-8', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Normalise key whitespace (Celestrak headers may have leading/trailing spaces)
            row = {k.strip(): v.strip() for k, v in row.items() if k}

            # NORAD cat ID — required
            norad_str = row.get('NORAD_CAT_ID', row.get('NORADCATID', '')).strip()
            if not norad_str or not norad_str.isdigit():
                continue
            norad = int(norad_str)

            if norad < min_norad:
                continue

            # Current status filter: keep if CURRENT == 'Y' or DECAY is blank
            current = row.get('CURRENT', row.get('OPS_STATUS_CODE', '')).strip().upper()
            decay   = row.get('DECAY', row.get('DECAY_DATE', '')).strip()
            if current != 'Y' and decay:
                continue  # decayed and not flagged current → skip

            # Object type filter
            obj_type = row.get('OBJECT_TYPE', '').strip().upper()
            if obj_type not in allowed_types:
                continue

            # Prefer OBJECT_NAME, fall back to SATNAME
            name = (row.get('OBJECT_NAME') or row.get('SATNAME') or '').strip()
            if not name:
                continue

            intldes  = row.get('INTLDES', row.get('INTL_DES', '')).strip()
            country  = row.get('COUNTRY', '').strip().upper()
            launch   = row.get('LAUNCH', row.get('LAUNCH_DATE', '')).strip()
            period   = row.get('PERIOD', '').strip()
            incl     = row.get('INCLINATION', row.get('INCLINATION_DEG', '')).strip()
            apogee   = row.get('APOGEE', '').strip()
            perigee  = row.get('PERIGEE', '').strip()

            satellites.append({
                'norad':    norad,
                'intldes':  intldes,
                'name':     name,
                'country':  country,
                'obj_type': obj_type,
                'launch':   launch,
                'period':   period,
                'incl':     incl,
                'apogee':   apogee,
                'perigee':  perigee,
            })

    # Sort by NORAD CAT ID
    satellites.sort(key=lambda s: s['norad'])
    return satellites


def build_description(s: dict) -> str:
    """Build the human-readable description for a satellite."""
    parts = [s['name']]

    country = s['country']
    if country:
        parts.append(country)

    launch = s['launch']
    if launch:
        parts.append(f"launched {launch}")

    period = fmt_float(s['period'], 1, ' min')
    if period:
        parts.append(f"period {period}")

    incl = fmt_float(s['incl'], 1, '°')
    if incl:
        parts.append(f"inclination {incl}")

    apogee = fmt_float(s['apogee'], 0, ' km')
    if apogee:
        parts.append(f"apogee {apogee}")

    perigee = fmt_float(s['perigee'], 0, ' km')
    if perigee:
        parts.append(f"perigee {perigee}")

    return '; '.join(parts)


def emit_satellite(fh, s: dict) -> None:
    """Write one satellite atom to fh."""
    norm  = normalize(s['name'])
    atom  = f"astro:satellite:{norm}"
    desc  = build_description(s)

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} astro:satellite:norad:{s["norad"]}\n')
    if s['intldes']:
        fh.write(f'al {atom} astro:satellite:intl:{normalize(s["intldes"])}\n')
    fh.write(f'ln {atom} astro:satellite sys:part_of\n')

    # Country link (only if we have a mapping to ISO3)
    iso3 = COUNTRY_TO_ISO3.get(s['country'])
    if iso3:
        fh.write(f'ln {atom} geo:country:{iso3} sys:part_of\n')

    fh.write('\n')


def generate(
    satellites: list[dict],
    out_dir: str,
    chunk_size: int,
    dry_run: bool,
):
    total     = len(satellites)
    num_files = (total + chunk_size - 1) // chunk_size

    # Breakdown by type
    type_counts: dict[str, int] = {}
    for s in satellites:
        t = s['obj_type']
        type_counts[t] = type_counts.get(t, 0) + 1

    # Country coverage
    countries: set[str] = {s['country'] for s in satellites if s['country']}

    print(f"\n  Satellites: {total}")
    for t, c in sorted(type_counts.items()):
        print(f"    {t}: {c}")
    print(f"  Countries/orgs: {len(countries)}")
    print(f"  Files: {num_files} × {chunk_size} → satellites_{{NN}}.ak")

    if dry_run:
        return

    os.makedirs(out_dir, exist_ok=True)

    for i in range(num_files):
        chunk = satellites[i * chunk_size:(i + 1) * chunk_size]
        fname = f"satellites_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, sat_range=f"{start}–{end}"))
            for s in chunk:
                emit_satellite(fh, s)
        print(f"  {fname}  {len(chunk):5d} satellites", flush=True)

    print(f"\n  Total: {total} satellites in {num_files} files → {out_dir}/")
    print("\nNext: git add app/ontology/space/satellites_*.ak && git commit")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--csv-file',       help='Pre-downloaded satcat.csv from Celestrak')
    ap.add_argument('--out',            default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size',     type=int, default=2000,
                    help='Satellites per .ak file (default: 2000)')
    ap.add_argument('--min-norad',      type=int, default=0,
                    help='Only include objects with NORAD ID >= N (default: 0 = all)')
    ap.add_argument('--include-debris', action='store_true',
                    help='Include DEBRIS object type (excluded by default)')
    ap.add_argument('--dry-run',        action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[satellites_import] Locating source data …')
    try:
        csv_path = ensure_csv(args.csv_file)
    except Exception as e:
        print(f'\nError: {e}')
        print('\nManual download:')
        print(f'  {SATCAT_URL}')
        print(f'  → save as out/satellite_cache/satcat.csv')
        print('Re-run with: --csv-file /path/to/satcat.csv')
        sys.exit(1)

    debris_note = " (including debris)" if args.include_debris else " (payloads + rocket bodies only)"
    print(f'[satellites_import] Parsing {os.path.basename(csv_path)}{debris_note} …')
    satellites = parse_csv(csv_path, args.include_debris, args.min_norad)
    print(f'  Parsed {len(satellites)} satellites')

    generate(satellites, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
