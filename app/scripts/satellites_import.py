"""
satellites_import.py — Celestrak satellite catalog → app/ontology/space/satellites_NN.ak

Converts the Celestrak satellite catalog (SATCAT) to Akasha .ak ontology files
for app/ontology/space/.

Filters applied by default:
    - CURRENT == 'Y'  (active / currently tracked objects)
    - OBJECT_TYPE in ('PAYLOAD', 'ROCKET BODY')  (skip debris)

Atom IDs:    astro:satellite:{normalized_name}        e.g. astro:satellite:iss_zarya
Aliases:     astro:satellite:norad:{NORAD_CAT_ID}
             astro:satellite:intl:{INTLDES}
Links:       sys:part_of → astro:satellite            (parent collection atom)
             sys:part_of → geo:country:{iso3}         (country of origin, where known)

Attribution:
    Celestrak — https://celestrak.org/
    Dr. T.S. Kelso, Celestrak SATCAT
    Public domain / CC0

Usage:
    # Download from Celestrak and convert:
    python app/scripts/satellites_import.py

    # Use pre-downloaded CSV:
    python app/scripts/satellites_import.py --csv-file out/satellite_cache/satcat.csv

    # Include space debris:
    python app/scripts/satellites_import.py --include-debris

    # Only include objects with NORAD ID >= 25000:
    python app/scripts/satellites_import.py --min-norad 25000

    # Dry run (stats only, no files written):
    python app/scripts/satellites_import.py --dry-run

Options:
    --csv-file FILE      Pre-downloaded satcat.csv from Celestrak
    --out DIR            Output directory (default: app/ontology/space/)
    --chunk-size N       Satellites per .ak file (default: 2000)
    --min-norad N        Only include objects with NORAD ID >= N (default: 0)
    --include-debris     Include DEBRIS object type (excluded by default)
    --dry-run            Print stats only, write no files

Source:
    https://celestrak.org/pub/satcat.csv
"""

