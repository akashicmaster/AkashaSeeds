def _download_bytes(url: str, label: str) -> bytes:
    print(f'Downloading {label} …', file=sys.stderr)
    req = urllib.request.Request(
        url,
        headers={'User-Agent': 'AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)'},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def ensure_data(json_arg: str | None) -> list[dict]:
    """
    Return element list.  Priority:
      1. --json FILE (pre-downloaded)
      2. Try API URLs in order
      3. HTML scrape fallback
    """
    if json_arg:
        print(f'[unesco_ich_import] Loading --json {json_arg} …', file=sys.stderr)
        with open(json_arg, encoding='utf-8') as f:
            raw = f.read()
        # Try JSON first; if that fails, treat as HTML
        try:
            data = json.loads(raw)
            return extract_elements_from_json(data)
        except json.JSONDecodeError:
            print('[unesco_ich_import] File is not JSON; trying HTML parse …', file=sys.stderr)
            return scrape_ich_html(raw)

    os.makedirs(CACHE_DIR, exist_ok=True)
    cache_json = os.path.join(CACHE_DIR, 'ich_elements.json')
    cache_html = os.path.join(CACHE_DIR, 'ich_lists_domain02.html')

    # Re-use cache if present
    if os.path.exists(cache_json):
        print(f'[unesco_ich_import] Using cached: {cache_json}', file=sys.stderr)
        with open(cache_json, encoding='utf-8') as f:
            data = json.load(f)
        elems = extract_elements_from_json(data)
        if elems:
            return elems

    if os.path.exists(cache_html):
        print(f'[unesco_ich_import] Using cached: {cache_html}', file=sys.stderr)
        with open(cache_html, encoding='utf-8') as f:
            html = f.read()
        elems = scrape_ich_html(html)
        if elems:
            return elems

    # Try JSON API URLs
    for url in API_URLS:
        try:
            print(f'[unesco_ich_import] Trying {url} …', file=sys.stderr)
            raw_bytes = _download_bytes(url, url)
            data = json.loads(raw_bytes.decode('utf-8'))
            elems = extract_elements_from_json(data)
            if elems:
                with open(cache_json, 'w', encoding='utf-8') as f:
                    json.dump(data, f)
                print(f'  Cached to {cache_json}', file=sys.stderr)
                return elems
            print(f'  No elements found in response from {url}', file=sys.stderr)
        except (urllib.error.URLError, json.JSONDecodeError, OSError) as e:
            print(f'  Failed: {e}', file=sys.stderr)

    # HTML scrape fallback
    try:
        print(f'[unesco_ich_import] Trying HTML scrape: {HTML_URL} …', file=sys.stderr)
        raw_bytes = _download_bytes(HTML_URL, 'UNESCO ICH Performing Arts page')
        html = raw_bytes.decode('utf-8', errors='replace')
        with open(cache_html, 'w', encoding='utf-8') as f:
            f.write(html)
        elems = scrape_ich_html(html)
        if elems:
            return elems
    except (urllib.error.URLError, OSError) as e:
        print(f'  HTML scrape failed: {e}', file=sys.stderr)

    return []


