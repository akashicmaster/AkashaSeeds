def build_ich_url(url_slug: str, ich_id: str) -> str:
    if url_slug:
        return f"{ICH_BASE_URL}{url_slug}"
    if ich_id:
        return f"{ICH_BASE_URL}{ich_id}"
    return ICH_BASE_URL


def emit_element(fh, e: dict) -> None:
    """Write one ICH element atom to fh."""
    norm_id  = normalize_id(e['name'])
    atom     = f"ich:element:{norm_id}"
    ich_id   = e.get('ich_id', '').strip()
    ich_url  = build_ich_url(e.get('url_slug', ''), ich_id)

    parts: list[str] = [e['name']]
    if e.get('country'):
        parts.append(e['country'])
    if e.get('year'):
        parts.append(f"inscribed {e['year']}")
    parts.append('UNESCO ICH Performing Arts')
    parts.append(ich_url)

    desc = '; '.join(p for p in parts if p)
    desc = truncate(desc, 280)

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    if ich_id and ich_id.isdigit():
        fh.write(f'al {atom} ich:ich:{ich_id}\n')
    fh.write(f'ln {atom} perf:arts sys:part_of\n')
    fh.write(f'set.add name="ontology.ich_elements" id="{atom}"\n')
    fh.write('\n')


def generate(elements: list[dict], out_dir: str, chunk_size: int, dry_run: bool) -> None:
    total     = len(elements)
    num_files = (total + chunk_size - 1) // chunk_size if total else 0

    print(f'\n  Elements: {total}', file=sys.stderr)
    print(f'  Files:    {num_files} × {chunk_size} → ich_elements_{{NN}}.ak', file=sys.stderr)

    if dry_run:
        print('\n--- dry-run: first 20 output lines ---', file=sys.stderr)
        import io as _io
        buf = _io.StringIO()
        for e in elements[:5]:
            emit_element(buf, e)
        lines = buf.getvalue().splitlines()
        for line in lines[:20]:
            print(line)
        return

    if total == 0:
        print('[unesco_ich_import] No elements to write.', file=sys.stderr)
        return

    os.makedirs(out_dir, exist_ok=True)
    for i in range(num_files):
        chunk  = elements[i * chunk_size:(i + 1) * chunk_size]
        fname  = f"ich_elements_{i + 1:02d}.ak"
        fpath  = os.path.join(out_dir, fname)
        start  = i * chunk_size + 1
        end    = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, elem_range=f"{start}–{end}"))
            for e in chunk:
                emit_element(fh, e)
        print(f'  {fname}  {len(chunk):5d} elements', file=sys.stderr, flush=True)

    print(f'\n  Total: {total} elements in {num_files} files → {out_dir}/', file=sys.stderr)
    print('\nNext: git add app/ontology/music/ich_elements_*.ak && git commit', file=sys.stderr)


