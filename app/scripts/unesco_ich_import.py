def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json',       help='Pre-downloaded JSON file (or HTML page source)')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print first 20 lines, write no files')
    args = ap.parse_args()

    print('[unesco_ich_import] Fetching UNESCO ICH Performing Arts elements …', file=sys.stderr)
    try:
        elements = ensure_data(args.json)
    except Exception as e:
        print(f'\nError: {e}', file=sys.stderr)
        print('\nManual download:', file=sys.stderr)
        print('  Visit https://ich.unesco.org/en/lists?domain=02', file=sys.stderr)
        print('  Save the page source or use the Export option', file=sys.stderr)
        print('  Pass the file with: --json /path/to/ich_elements.json', file=sys.stderr)
        sys.exit(1)

    if not elements:
        print('\n[unesco_ich_import] No elements were retrieved.', file=sys.stderr)
        print('\nManual download:', file=sys.stderr)
        print('  Visit https://ich.unesco.org/en/lists?domain=02', file=sys.stderr)
        print('  Save the page source or use the Export option', file=sys.stderr)
        print('  Pass the file with: --json /path/to/ich_elements.json', file=sys.stderr)
        sys.exit(1)

    # Filter to Performing Arts; if domain field is absent / ambiguous keep all
    # (we fetched domain=02 already, so HTML path is already filtered)
    filtered = [e for e in elements if not e.get('domain') or is_performing_arts(e['domain'])]
    if not filtered:
        # Domain field was missing for everything; keep all (scrape path returns domain='Performing arts')
        filtered = elements

    print(f'[unesco_ich_import] Performing Arts elements: {len(filtered)} '
          f'(of {len(elements)} total retrieved)', file=sys.stderr)

    generate(filtered, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
