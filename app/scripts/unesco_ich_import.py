class ICHHTMLParser(HTMLParser):
    """
    Minimal scraper for https://ich.unesco.org/en/lists?domain=02

    The UNESCO ICH site renders a list of elements, each typically in a
    <div class="element"> or <article> block containing:
        - A heading or link with the element title
        - Country / state party names
        - Inscription year
    This parser collects raw text from likely containers.
    """

    def __init__(self):
        super().__init__()
        self.elements: list[dict] = []
        self._current: dict | None = None
        self._in_element = False
        self._depth = 0
        self._element_depth = 0
        self._capture_text = False
        self._text_buf: list[str] = []
        # Track all href/title patterns that look like ICH element links
        self._links: list[dict] = []

    def handle_starttag(self, tag, attrs):
        attr_dict = dict(attrs)
        cls = attr_dict.get('class', '')
        href = attr_dict.get('href', '')

        # Detect element container
        if tag in ('div', 'article', 'li') and (
            'element' in cls or 'inscription' in cls or 'item' in cls
        ):
            self._in_element = True
            self._element_depth = self._depth
            self._current = {'name': '', 'country': '', 'year': '', 'ich_id': '', 'url_slug': '', 'domain': 'Performing arts'}
            self._text_buf = []

        # Detect links that look like ICH element pages
        if tag == 'a' and href:
            # Pattern: /en/RL/some-slug-NNNN or similar
            m = re.search(r'/en/RL/([^"?\s]+)', href)
            if m:
                slug = m.group(1)
                num_m = re.search(r'-(\d+)$', slug)
                ich_id = num_m.group(1) if num_m else ''
                title = attr_dict.get('title', '').strip()
                if title or (self._in_element and self._current is not None):
                    self._links.append({
                        'slug':   slug,
                        'ich_id': ich_id,
                        'title':  title,
                    })
                    if self._current is not None and not self._current['url_slug']:
                        self._current['url_slug'] = slug
                        self._current['ich_id']   = ich_id
                        if title and not self._current['name']:
                            self._current['name'] = title

        if tag in ('span', 'p', 'h2', 'h3', 'h4', 'strong', 'em', 'td', 'a'):
            self._capture_text = True

        self._depth += 1

    def handle_endtag(self, tag):
        self._depth -= 1
        if self._in_element and self._depth <= self._element_depth:
            self._in_element = False
            if self._current and self._current.get('name'):
                self.elements.append(self._current)
            self._current = None
        if tag in ('span', 'p', 'h2', 'h3', 'h4', 'strong', 'em', 'td', 'a'):
            self._capture_text = False

    def handle_data(self, data):
        if not self._in_element or self._current is None:
            return
        text = data.strip()
        if not text:
            return
        # Heuristic: first substantial text is the name
        if not self._current['name'] and len(text) > 3:
            self._current['name'] = text
        # Year detection
        if not self._current['year']:
            m = re.search(r'\b(19[89]\d|20[012]\d)\b', text)
            if m:
                self._current['year'] = m.group(1)
        # Country: lines containing country names tend to be short, after name
        if self._current['name'] and not self._current['country'] and 3 < len(text) < 150:
            if not re.match(r'^\d{4}$', text):
                self._current['country'] = text


def scrape_ich_html(html: str) -> list[dict]:
    """Parse UNESCO ICH listing HTML; return element dicts."""
    parser = ICHHTMLParser()
    parser.feed(html)
    elements = parser.elements

    # If parser found no structured elements, try reconstructing from link list
    if not elements and parser._links:
        print('[unesco_ich_import] HTML parser found links but no structured elements; '
              'using link-based extraction.', file=sys.stderr)
        seen: set[str] = set()
        for lnk in parser._links:
            slug = lnk['slug']
            if slug in seen:
                continue
            seen.add(slug)
            # Prettify slug: remove trailing ID, replace hyphens
            title = lnk['title'] or re.sub(r'-\d+$', '', slug).replace('-', ' ').title()
            elements.append({
                'name':     title,
                'country':  '',
                'year':     '',
                'ich_id':   lnk['ich_id'],
                'url_slug': slug,
                'domain':   'Performing arts',
            })

    return elements


