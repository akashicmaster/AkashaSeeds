"""
unesco_ich_import.py — UNESCO Intangible Cultural Heritage → app/ontology/music/ich_elements_NN.ak

Converts UNESCO ICH Performing Arts elements to Akasha .ak atoms for app/ontology/music/.

Filters applied:
    - Domain = "Performing arts" (domain code 02) only
    - Skips "Oral traditions and expressions" and other domains

Atom IDs:    ich:element:{norm_id}          e.g. ich:element:yueju_opera
Aliases:     ich:ich:{numerical_id}         (UNESCO ICH numerical ID, if available)
Links:       sys:part_of → perf:arts

Attribution:
    UNESCO Intangible Cultural Heritage — https://ich.unesco.org/
    Terms of use: https://ich.unesco.org/en/convention

Usage:
    # Auto-fetch via UNESCO ICH API (tries multiple URL patterns):
    python app/scripts/unesco_ich_import.py

    # Use pre-downloaded JSON:
    python app/scripts/unesco_ich_import.py --json /path/to/ich_elements.json

    # Dry run (print first 20 lines, no files written):
    python app/scripts/unesco_ich_import.py --dry-run

    # Override output directory:
    python app/scripts/unesco_ich_import.py --out /path/to/output

Options:
    --json FILE       Pre-downloaded JSON file (UNESCO ICH API or page source)
    --out DIR         Output directory (default: app/ontology/music/)
    --chunk-size N    Atoms per .ak file (default: 500)
    --dry-run         Print first 20 lines, write no files

Sources tried in order:
    1. https://ich.unesco.org/en/lists.json
    2. https://ich.unesco.org/api/elements
    3. https://ich.unesco.org/en/RL/inscriptions?format=json
    4. HTML scrape: https://ich.unesco.org/en/lists?domain=02

Manual download (if auto-fetch fails):
    Visit https://ich.unesco.org/en/lists?domain=02
    Save the page source or use the Export option
    Pass the file with: --json /path/to/ich_elements.json
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
from html.parser import HTMLParser

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "music")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "ich_cache")

# Tried in order until one returns usable data
API_URLS = [
    "https://ich.unesco.org/en/lists.json",
    "https://ich.unesco.org/api/elements",
    "https://ich.unesco.org/en/RL/inscriptions?format=json",
]
HTML_URL = "https://ich.unesco.org/en/lists?domain=02"

ICH_BASE_URL = "https://ich.unesco.org/en/RL/"

# Domain strings that indicate Performing Arts
PERF_ARTS_MARKERS = frozenset({
    "performing arts",
    "02",
    "performing",
})

FILE_HEADER = """\
# {filename}
# UNESCO Intangible Cultural Heritage — https://ich.unesco.org/
# Domain: Performing Arts (domain 02)
# Generated by app/scripts/unesco_ich_import.py
# Elements: {elem_range}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n - 1].rsplit(' ', 1)[0].rstrip(' ,;') + '…'


def normalize_id(name: str) -> str:
    """Normalise element name to atom ID component."""
    s = name.lower()
    # Replace accented chars with ASCII equivalents where possible
    import unicodedata
    s = unicodedata.normalize('NFKD', s)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = re.sub(r"[\s\-,.'()\/]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:60]


def is_performing_arts(domain_val) -> bool:
    """Return True if the domain value indicates Performing Arts."""
    if domain_val is None:
        return False
    if isinstance(domain_val, list):
        return any(is_performing_arts(d) for d in domain_val)
    s = str(domain_val).lower().strip()
    return any(marker in s for marker in PERF_ARTS_MARKERS)


def extract_elements_from_json(data) -> list[dict]:
    """
    Try to extract element records from various JSON shapes the UNESCO ICH API might return.
    Returns list of dicts with keys: name, country, year, ich_id, url_slug, domain.
    """
    elements = []

    # Shape 1: list of objects at top level
    if isinstance(data, list):
        records = data
    # Shape 2: {"results": [...]} or {"elements": [...]} or {"items": [...]}
    elif isinstance(data, dict):
        for key in ('results', 'elements', 'items', 'data', 'inscriptions'):
            if key in data and isinstance(data[key], list):
                records = data[key]
                break
        else:
            # Shape 3: paginated {"count": N, "next": ..., "results": [...]}
            records = []
            for v in data.values():
                if isinstance(v, list) and len(v) > 0:
                    records = v
                    break
    else:
        return elements

    for rec in records:
        if not isinstance(rec, dict):
            continue

        # Name
        name = (
            rec.get('title') or rec.get('name') or rec.get('element_name') or
            rec.get('label') or rec.get('Name') or ''
        ).strip()
        if not name:
            continue

        # Country / countries
        country_raw = (
            rec.get('states') or rec.get('country') or rec.get('countries') or
            rec.get('state_party') or rec.get('states_parties') or ''
        )
        if isinstance(country_raw, list):
            country = ', '.join(str(c) for c in country_raw)
        else:
            country = str(country_raw).strip()

        # Year
        year_raw = (
            rec.get('year') or rec.get('inscription_year') or
            rec.get('date') or rec.get('inscribed') or ''
        )
        year = str(year_raw).strip()[:4] if year_raw else ''

        # ICH numerical ID
        ich_id_raw = rec.get('id') or rec.get('ID') or rec.get('element_id') or ''
        ich_id = str(ich_id_raw).strip() if ich_id_raw else ''

        # URL slug
        url_slug = (
            rec.get('slug') or rec.get('url_slug') or rec.get('link') or
            rec.get('href') or ich_id or ''
        )

        # Domain
        domain = (
            rec.get('domain') or rec.get('domains') or rec.get('field') or
            rec.get('thematic_domain') or ''
        )

        elements.append({
            'name':     name,
            'country':  country,
            'year':     year,
            'ich_id':   ich_id,
            'url_slug': str(url_slug).strip(),
            'domain':   domain,
        })

    return elements


