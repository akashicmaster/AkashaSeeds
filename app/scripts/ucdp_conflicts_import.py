"""
ucdp_conflicts_import.py — UCDP API → app/ontology/war/ucdp_conflicts.ak

Downloads active and recent armed conflicts from the Uppsala Conflict Data
Program (UCDP) REST API and emits Akasha .ak atoms.

Atom IDs:
    war:ucdp:{conflict_id}      e.g. war:ucdp:13793
Aliases:
    war:conflict:{norm_name}    → links to Wikidata wars pack (if present)
Sets:
    ontology.ucdp_conflicts

Attribution:
    Uppsala Conflict Data Program (UCDP) — https://ucdp.uu.se/
    Pettersson, T & Öberg, M (2020) "Organized violence, 1989-2019"
    Journal of Peace Research 57(4) — ISSN 0022-3433

Usage:
    # Auto-download from UCDP API (result cached locally):
    python app/scripts/ucdp_conflicts_import.py

    # Use pre-downloaded conflicts JSON:
    python app/scripts/ucdp_conflicts_import.py --conflicts-file /path/to/conflicts.json

    # Only include conflicts active since 2000:
    python app/scripts/ucdp_conflicts_import.py --min-year 2000

    # Only include wars (intensity ≥ 2):
    python app/scripts/ucdp_conflicts_import.py --intensity 2

    # Dry run — preview first 20 lines, write no files:
    python app/scripts/ucdp_conflicts_import.py --dry-run

Options:
    --conflicts-file FILE   Pre-downloaded conflicts JSON
    --out DIR               Output directory (default: app/ontology/war/)
    --min-year INT          Only conflicts active since this year (default: 1990)
    --intensity INT         Minimum intensity level: 1=minor, 2=war (default: 1)
    --dry-run               Print first 20 lines to stdout, write no files

Source:
    https://ucdpapi.pcr.uu.se/api/conflicts/23.1
    No authentication required.
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "war")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "ucdp_cache")
CACHE_CONFLICTS = os.path.join(CACHE_DIR, "conflicts.json")

UCDP_BASE       = "https://ucdpapi.pcr.uu.se/api/"
UCDP_VERSIONS   = ["23.1", "22.1", "21.1"]
USER_AGENT      = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

CONFLICT_TYPE = {
    1: "extrasystemic (colonial/imperial)",
    2: "interstate",
    3: "intrastate (civil war)",
    4: "internationalised intrastate",
}

INTENSITY = {
    1: "minor conflict",
    2: "war",
}

FILE_HEADER = """\
# ucdp_conflicts.ak
# Uppsala Conflict Data Program — https://ucdp.uu.se/ — CC BY 4.0
# Generated by app/scripts/ucdp_conflicts_import.py
# Entries: {entry_range}
#
"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def norm_name(name: str, max_chars: int = 70) -> str:
    """Normalise conflict name to atom ID component."""
    s = name.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip('.,;') + '…'


def http_get_json(url: str) -> dict | list:
    """Fetch URL and return parsed JSON. Raises on non-200 or non-JSON."""
    req = urllib.request.Request(url, headers={
        'Accept':     'application/json',
        'User-Agent': USER_AGENT,
    })
    with urllib.request.urlopen(req, timeout=60) as resp:
        if resp.status != 200:
            raise RuntimeError(f"HTTP {resp.status} for {url}")
        raw = resp.read()
    return json.loads(raw.decode('utf-8'))


def fetch_all_pages(base_url: str) -> list[dict]:
    """Paginate through UCDP API, collecting all result items."""
    all_items: list[dict] = []
    page = 1
    page_size = 100

    while True:
        url = f"{base_url}?pagesize={page_size}&page={page}"
        eprint(f"  Fetching page {page}: {url}")
        data = http_get_json(url)

        # UCDP response structure: {Result: [...], TotalCount: N, ThisPageEndPosition: N}
        if isinstance(data, dict):
            items = data.get('Result', data.get('result', []))
            total = data.get('TotalCount', data.get('totalCount', 0))
            end_pos = data.get('ThisPageEndPosition', data.get('thisPageEndPosition', 0))
        elif isinstance(data, list):
            items = data
            total = len(data)
            end_pos = len(data)
        else:
            break

        if not items:
            break

        all_items.extend(items)
        eprint(f"    Got {len(items)} items (total so far: {len(all_items)}/{total})")

        if end_pos >= total or len(items) < page_size:
            break
        page += 1
        time.sleep(0.5)  # polite delay

    return all_items


def fetch_ucdp_conflicts() -> list[dict]:
    """Fetch conflicts from UCDP API, trying version fallbacks. Returns raw item list."""
    os.makedirs(CACHE_DIR, exist_ok=True)

    if os.path.exists(CACHE_CONFLICTS):
        eprint(f"Using cached: {CACHE_CONFLICTS}")
        with open(CACHE_CONFLICTS, encoding='utf-8') as f:
            return json.load(f)

    eprint("[ucdp_conflicts_import] Fetching from UCDP API …")
    last_error = None

    for version in UCDP_VERSIONS:
        url = f"{UCDP_BASE}conflicts/{version}"
        eprint(f"  Trying API version {version}: {url}")
        try:
            items = fetch_all_pages(url)
            if items:
                with open(CACHE_CONFLICTS, 'w', encoding='utf-8') as f:
                    json.dump(items, f, ensure_ascii=False, indent=2)
                eprint(f"  Cached {len(items)} conflicts to: {CACHE_CONFLICTS}")
                return items
        except Exception as e:
            eprint(f"  Version {version} failed: {e}")
            last_error = e
            time.sleep(2)

    raise RuntimeError(f"All UCDP API versions failed. Last error: {last_error}")


def parse_conflicts(
    raw: list[dict],
    min_year: int = 1990,
    min_intensity: int = 1,
) -> list[dict]:
    """
    Filter and normalise UCDP conflict records.
    Keeps conflicts active since min_year with intensity >= min_intensity.
    """
    records = []
    for item in raw:
        if not isinstance(item, dict):
            continue

        conflict_id = str(item.get('ConflictId', item.get('conflict_id', ''))).strip()
        if not conflict_id:
            continue

        conflict_name = (
            item.get('Conflict') or item.get('conflict') or
            item.get('Name') or item.get('name') or ''
        ).strip()
        if not conflict_name:
            conflict_name = f"Conflict {conflict_id}"

        location = (
            item.get('Location') or item.get('location') or ''
        ).strip()

        intensity = int(item.get('IntensityLevel', item.get('intensity_level', 0)) or 0)
        conflict_type = int(item.get('TypeOfConflict', item.get('type_of_conflict', 0)) or 0)

        # Start dates: StartDate2 is the earliest (overall conflict start)
        start_date = (
            item.get('StartDate2') or item.get('start_date2') or
            item.get('StartDate') or item.get('start_date') or ''
        ).strip()
        ep_end = (
            item.get('EpEndDate') or item.get('ep_end_date') or ''
        ).strip()

        # Extract year from date string
        start_year = None
        if start_date:
            m = re.match(r'(\d{4})', start_date)
            if m:
                start_year = int(m.group(1))

        ep_end_year = None
        if ep_end:
            m = re.match(r'(\d{4})', ep_end)
            if m:
                ep_end_year = int(m.group(1))

        # Filter by min_year: keep if start_year or end_year >= min_year
        active_year = ep_end_year or start_year or 0
        if active_year < min_year and start_year is not None and start_year < min_year:
            continue

        # Filter by intensity
        if intensity < min_intensity:
            continue

        records.append({
            'conflict_id':   conflict_id,
            'name':          conflict_name,
            'location':      location,
            'intensity':     intensity,
            'conflict_type': conflict_type,
            'start_year':    start_year,
            'ep_end_year':   ep_end_year,
        })

    # Sort: by start_year ascending, then name
    records.sort(key=lambda r: (r['start_year'] or 9999, r['name'].lower()))
    eprint(f"  {len(records):,} conflicts after filtering (min_year={min_year}, min_intensity={min_intensity})")
    return records


def build_description(rec: dict) -> str:
    """Build ≤280-char description; omit absent fields."""
    name         = rec['name']
    location     = rec['location']
    intensity    = INTENSITY.get(rec['intensity'], f"intensity-{rec['intensity']}")
    ctype        = CONFLICT_TYPE.get(rec['conflict_type'], f"type-{rec['conflict_type']}")
    start_year   = rec['start_year']
    conflict_id  = rec['conflict_id']
    url          = f"https://ucdp.uu.se/#/conflict/{conflict_id}"

    parts = [name]
    if location:
        parts.append(location)
    parts.append(ctype)
    parts.append(intensity)
    if start_year:
        parts.append(f"active since {start_year}")
    parts.append(url)

    desc = '; '.join(parts)
    return truncate(desc, 280)


def emit_conflict_block(rec: dict) -> list[str]:
    """Return list of .ak lines for one UCDP conflict."""
    cid      = rec['conflict_id']
    atom     = f"war:ucdp:{cid}"
    n_name   = norm_name(rec['name'])
    alias    = f"war:conflict:{n_name}"
    desc     = build_description(rec)
    lines = [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
        f'ln {atom} war:conflict sys:part_of',
        f'set.add name="ontology.ucdp_conflicts" id="{atom}"',
        '',
    ]
    return lines


def generate(records: list[dict], out_dir: str, dry_run: bool) -> None:
    # Single output file for ~300 conflicts
    all_lines: list[str] = []
    for rec in records:
        all_lines.extend(emit_conflict_block(rec))

    n_total = len(records)
    eprint(f"\n  Conflicts: {n_total:,}")
    eprint(f"  Output:    {out_dir}/ucdp_conflicts.ak")

    if dry_run:
        print("# --- DRY RUN: first 20 output lines ---")
        count = 0
        for line in all_lines:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    if not records:
        eprint('[ucdp_conflicts_import] No conflicts to write.')
        return

    os.makedirs(out_dir, exist_ok=True)
    fpath = os.path.join(out_dir, "ucdp_conflicts.ak")
    with open(fpath, 'w', encoding='utf-8') as fh:
        fh.write(FILE_HEADER.format(entry_range=f"1–{n_total}"))
        for line in all_lines:
            fh.write(line + '\n')
    eprint(f"  Written: {fpath}  ({n_total} entries)")
    eprint(f"\n  Done → {out_dir}/")
    eprint("\nNext: git add app/ontology/war/ucdp_conflicts.ak && git commit")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--conflicts-file', help='Pre-downloaded UCDP conflicts JSON')
    ap.add_argument('--out',            default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--min-year',       type=int, default=1990,
                    help='Only include conflicts active since this year (default: 1990)')
    ap.add_argument('--intensity',      type=int, default=1,
                    help='Minimum intensity level: 1=minor conflict, 2=war (default: 1)')
    ap.add_argument('--dry-run',        action='store_true',
                    help='Print first 20 lines to stdout, write no files')
    args = ap.parse_args()

    if args.conflicts_file:
        eprint(f'[ucdp_conflicts_import] Loading {args.conflicts_file} …')
        with open(args.conflicts_file, encoding='utf-8') as f:
            raw = json.load(f)
        # Accept either a bare list or a UCDP paged response object
        if isinstance(raw, dict):
            raw = raw.get('Result', raw.get('result', []))
        eprint(f'  {len(raw):,} records in JSON file')
    else:
        try:
            raw = fetch_ucdp_conflicts()
        except Exception as e:
            eprint(f'\nError: {e}')
            eprint("""
Manual download:
  Visit https://ucdpapi.pcr.uu.se/api/conflicts/23.1?pagesize=100
  Save as JSON
  Run: python app/scripts/ucdp_conflicts_import.py --conflicts-file /path/to/conflicts.json

  For the full dataset:
  Visit https://ucdp.uu.se/downloads/ and download the UCDP/PRIO Armed Conflict Dataset
""")
            sys.exit(1)

    if not raw:
        eprint('No results returned. Try --conflicts-file with a pre-downloaded file.')
        sys.exit(0)

    eprint('[ucdp_conflicts_import] Parsing and filtering conflicts …')
    records = parse_conflicts(raw, min_year=args.min_year, min_intensity=args.intensity)

    if not records:
        eprint('No conflicts matched filters. Try --min-year or --intensity options.')
        sys.exit(0)

    generate(records, args.out, args.dry_run)


if __name__ == '__main__':
    main()
