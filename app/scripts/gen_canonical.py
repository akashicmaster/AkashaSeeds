#!/usr/bin/env python3
"""
gen_canonical.py — apply the Product · Component · Method · Producer law to the ontology packs at BUILD time.

The law (docs/for-llm/product-component-ontology.md) is data: `app/ontology/kitchen_index/canon.json` (`domains`,
`hub_exclude`, and the translation rows `product_ns` / `material_rels` / `producer_rels`). This script reads every
pack's authored `.ak`, applies it, and writes each pack's `canonical.ak` — the canonical links and sets that
pack's own atoms owe — so a cell that loads the packs holds the canonical shape with nothing derived at load.
(The platform used to derive it at every ingestion, a pass that named the kitchen's vocabulary from the heart.)

What it writes, per pack `P` (a statement goes to the pack that DEFINES its subject):
  · every entry of a domain:   ln <alias> <domain> sys:is_a  +  set.add <domain>:all  (+ the roll-up and method-marker sets)
  · every method (`recipe:*`):  its product `dish:<slug>` is MINTED when no pack defines it (method ⊆ product), then
                                sys:is_a meal, meal:all, meal:with_recipe, and  ln recipe:<slug> dish:<slug> sys:method_of
  · every material link         ln <product> <component> sys:made_from   beside the pack's own `thesaurus:related`
                                / `cocktail:base` / `cocktail:uses` line (the pack keeps writing its own relation)
  · every producer link         ln <product> <producer> sys:made_by      beside `whiskey:made_by` etc.
and, once, in `app/ontology/base1/canonical.ak`, the domain-level roles (`meal sys:is_a role:product`, `cocktail sys:is_a
drink`, …) that `canon_upper.ak` does not author by hand.

Idempotent and deterministic: running it twice writes the same bytes. `--check` writes nothing and exits 1 if any file
is stale (the build gate). `--stats` prints the size each canonical set will have.

Usage:  python app/scripts/gen_canonical.py [--check] [--stats]
"""
import argparse
import collections
import glob
import json
import os
import shlex
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
APP = os.path.abspath(os.environ.get("AKASHA_APP_DIR") or os.path.join(ROOT, "app"))
ONT = os.path.join(APP, "ontology")
OUT_NAME = "canonical.ak"
HEADER = ("# GENERATED by app/scripts/gen_canonical.py from app/ontology/kitchen_index/canon.json — DO NOT EDIT BY HAND.\n"
          "# The Product · Component · Method · Producer shape this pack's own atoms owe, written at build time.\n"
          "# Regenerate with:  python app/scripts/gen_canonical.py\n\n")

IS_A, MADE_FROM, METHOD_OF, MADE_BY = "sys:is_a", "sys:made_from", "sys:method_of", "sys:made_by"


def _q(s):
    return '"%s"' % str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def load_law():
    law = {"domains": {}, "hub_exclude": set(), "product_ns": [], "material": {}, "producer": {}}
    for path in sorted(glob.glob(os.path.join(ONT, "*", "canon.json"))):
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
        for name, cfg in (doc.get("domains") or {}).items():
            law["domains"][name] = {k: ([tuple(x) for x in v] if k == "member_ns" else v) for k, v in cfg.items()}
        law["hub_exclude"].update(doc.get("hub_exclude") or [])
        for ns in doc.get("product_ns") or []:
            if isinstance(ns, str) and not ns.startswith("_") and ns not in law["product_ns"]:
                law["product_ns"].append(ns)
        for key, out in (("material_rels", law["material"]), ("producer_rels", law["producer"])):
            for rel, spec in (doc.get(key) or {}).items():
                if rel.startswith("_") or not isinstance(spec, dict):
                    continue
                out[rel] = tuple(str(t) for t in (spec.get("targets") or ["*"]))
    return law


def pack_order():
    reg = json.load(open(os.path.join(ONT, "REGISTRY.json"), encoding="utf-8"))
    names = [p["name"] for p in reg.get("packages", [])]
    for d in sorted(os.listdir(ONT)):               # a pack dir the registry does not list still counts
        if os.path.isfile(os.path.join(ONT, d, "PACK.json")) and d not in names:
            names.append(d)
    return names


def parse(line):
    line = line.strip()
    if not line or line.startswith("#"):
        return None
    try:
        parts = shlex.split(line)
    except ValueError:
        parts = [p.strip('"\'') for p in line.split()]
    return parts or None


def scan(packs):
    """aliases: alias → pack that defines it (first in registry order);  desc: alias → description;  links:
    [(pack, src, dst, rel)] in file order."""
    aliases, desc, links = {}, {}, []
    for pack in packs:
        for path in sorted(glob.glob(os.path.join(ONT, pack, "*.ak"))):
            if os.path.basename(path) == OUT_NAME:
                continue
            with open(path, encoding="utf-8", errors="ignore") as f:
                for raw in f:
                    parts = parse(raw)
                    if not parts:
                        continue
                    cmd = parts[0].lower()
                    if cmd == "def" and len(parts) >= 2:
                        aliases.setdefault(parts[1], pack)
                        if len(parts) >= 3:
                            desc.setdefault(parts[1], parts[2])
                    elif cmd == "al" and len(parts) >= 3:
                        aliases.setdefault(parts[2], pack)
                    elif cmd == "ln" and len(parts) >= 4:
                        links.append((pack, parts[1], parts[2], parts[3]))
    return aliases, desc, links


def members(law, cfg, aliases):
    out = {}
    for prefix, depth in cfg.get("member_ns", ()):
        pre = prefix + ":"
        for a, pk in aliases.items():
            if a.startswith(pre) and a.count(":") == depth and a not in law["hub_exclude"]:
                out.setdefault(a, pk)
    return out


def name_head(text, fallback):
    c = (text or "").strip()
    for sep in (" — ", " (", ". "):
        if sep in c:
            c = c.split(sep, 1)[0].strip()
            break
    return (c.strip()[:80]) or fallback


def build(law, packs):
    aliases, desc, links = scan(packs)
    out = collections.OrderedDict((p, []) for p in packs)        # pack → [statement lines]
    sets = collections.defaultdict(set)                           # set name → member aliases (for --stats)
    domain_lines = []

    def emit(pack, line):
        out[pack].append(line)

    for dom, cfg in law["domains"].items():
        domain_lines.append("ln %s %s %s" % (dom, cfg["role"], IS_A))
        if cfg.get("parent"):
            domain_lines.append("ln %s %s %s" % (dom, cfg["parent"], IS_A))
        for a, pk in sorted(members(law, cfg, aliases).items()):
            emit(pk, "ln %s %s %s" % (a, dom, IS_A))
            for s in (cfg["all_set"], cfg.get("rollup_set"), cfg.get("method_marker")):
                if s:
                    emit(pk, 'set.add name=%s id=%s' % (_q(s), _q(a)))
                    sets[s].add(a)
    # methods: bind each to a product, MINT the product when no pack defines it
    for dom, cfg in law["domains"].items():
        if cfg["role"] != "role:method":
            continue
        pdom = cfg["method_of"]
        pcfg = law["domains"][pdom]
        pns = cfg["product_ns"]
        known = set(members(law, pcfg, aliases))
        for malias, pk in sorted(members(law, cfg, aliases).items()):
            slug = malias.split(":", 1)[1]
            palias = "%s:%s" % (pns, slug)
            if palias not in known:
                emit(pk, "def %s %s" % (_q(palias), _q(name_head(desc.get(malias), slug.replace("_", " ")))))
                known.add(palias)
                emit(pk, "ln %s %s %s" % (palias, pdom, IS_A))
                emit(pk, 'set.add name=%s id=%s' % (_q(pcfg["all_set"]), _q(palias)))
                sets[pcfg["all_set"]].add(palias)
            emit(pk, 'set.add name=%s id=%s' % (_q(cfg["subset_set"]), _q(palias)))
            sets[cfg["subset_set"]].add(palias)
            emit(pk, "ln %s %s %s" % (malias, palias, METHOD_OF))
    # material / producer links, beside the link the pack authored
    seen = set()
    for pack, src, dst, rel in links:
        if rel in (MADE_FROM, MADE_BY):
            continue
        tg = law["material"].get(rel)
        if tg and any(src.startswith(ns + ":") for ns in law["product_ns"]):
            if "*" in tg or any(dst.startswith(t + ":") for t in tg):
                if (src, dst, MADE_FROM) not in seen:
                    seen.add((src, dst, MADE_FROM))
                    emit(pack, "ln %s %s %s" % (src, dst, MADE_FROM))
        ptg = law["producer"].get(rel)
        if ptg and ("*" in ptg or any(dst.startswith(t + ":") for t in ptg)):
            if (src, dst, MADE_BY) not in seen:
                seen.add((src, dst, MADE_BY))
                emit(pack, "ln %s %s %s" % (src, dst, MADE_BY))
    files = {}
    for pack, lines in out.items():
        if lines:
            files[os.path.join(ONT, pack, OUT_NAME)] = HEADER + "\n".join(sorted(set(lines), key=lines.index)) + "\n"
    # domain-level roles: one file in the pack that carries the hand-authored canonical atoms
    files[os.path.join(ONT, "base1", OUT_NAME)] = files.get(os.path.join(ONT, "base1", OUT_NAME), HEADER) + \
        ("\n# ── domain-level roles (the super-concepts are defined by hand in canon_upper.ak) ──\n"
         + "\n".join(sorted(set(domain_lines), key=domain_lines.index)) + "\n")
    return files, sets, len(links)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stats", action="store_true")
    a = ap.parse_args()
    law = load_law()
    packs = pack_order()
    files, sets, nlinks = build(law, packs)
    if a.stats:
        print(json.dumps({s: len(m) for s, m in sorted(sets.items())}, indent=1, sort_keys=True))
    stale = []
    existing = set(glob.glob(os.path.join(ONT, "*", OUT_NAME)))
    for path, text in files.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(path)
            if not a.check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    gone = sorted(existing - set(files))
    for path in gone:
        stale.append(path)
        if not a.check:
            os.remove(path)
    print("canonical.ak: %d file(s), %d stale%s" % (len(files), len(stale), " (check)" if a.check else " (written)"))
    if a.check and stale:
        for s in stale[:10]:
            print("  stale:", os.path.relpath(s, ROOT))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
