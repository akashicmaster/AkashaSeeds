#!/usr/bin/env python3
"""Emit the durable Ayurveda GENEALOGY catalog from app/scripts/_ayurveda_corpus.py.

Writes:
  • app/ontology/base3/genealogy_ayurveda.ak          — the Caraka & Suśruta multi-lens stratification catalogs,
    the Atharvaveda→classical→Vāgbhaṭa source-stemma (@derives_from), and cross-links into the
    existing ontology (ancient:vedic, tradition:ayurveda, textcrit:*).
  • app/ontology/base3/genealogy_ayurveda_matrix.jsonl — the illustrative matrix (io.ingest model=gen).

⚠ Atoms are content-addressed: the Caraka and Suśruta share section names (Sūtrasthāna …), so every
work-scoped atom's content is disambiguated with ' · <work title>' to keep them distinct.
"""
import os, sys, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import app.scripts._ayurveda_corpus as AY

def esc(s): return (s or "").replace('"', "'").replace("\n", " ").strip()

out = []; w = out.append
w("# Genealogy — the Ayurveda corpus (Caraka & Suśruta stratification + the source-stemma).")
w("# Namespace gen:. Companion: app/concepts/gen.py (the SUPERSET model; sty is its subset). Generated by scripts/gen_genealogy_ayurveda_ak.py.")
w("# Matrix streamed at runtime: io.ingest model=gen into=<work> path=app/ontology/base3/genealogy_ayurveda_matrix.jsonl")
w("# Work-scoped atoms carry ' · <work>' in their content (content-addressing disambiguation).\n")

# ── the measurement lenses (feature spaces) — collected from the corpus, so every lens a feature
#    references (textual/stylometry, chronology, geography, concept, attestation, botany, tradition)
#    is DEFINED, never a bare proto-word. ──
_LENSES = []
for _spec in AY.STRATIFIED:
    for _f in _spec.get("features", []):
        _ln = _f[4] if len(_f) > 4 else "stylometry"
        if _ln not in _LENSES:
            _LENSES.append(_ln)
w("# ── measurement lenses (feature spaces) ──")
for _L in _LENSES:
    w(f'def "gen:lens:{_L}" "{_L.title()} lens — one feature space over the loci."')
    w(f'set.add name="gen:lenses" id="gen:lens:{_L}"')
w("")

def emit_work(spec):
    wid = spec["id"]; WK = f"gen:work:{wid}"; wt = spec["title"].split("—")[0].strip()
    w(f'# ══ {wt} ══')
    w(f'def "{WK}" "{esc(spec["title"])}"')
    w(f'set.add name="gen:works" id="{WK}"')
    for src in spec.get("derives", []):
        w(f'ln {WK} gen:work:{src} @derives_from')
    for t in spec.get("cross", []):
        w(f'ln {WK} {t} thesaurus:related')
    for wt_id, wt_title, wt_lang in spec.get("witnesses", []):
        k = f"gen:witness:{wt_id}"
        w(f'def "{k}" "{esc(wt_title)}"')
        w(f'set.add name="{WK}:witnesses" id="{k}"')
        w(f'ln {k} {WK} @witness_of')
    for lid, lt, ld in spec.get("layers", []):
        k = f"gen:layer:{lid}"
        w(f'def "{k}" "{esc(lt)} — {esc(ld)}"')
        w(f'set.add name="{WK}:layers" id="{k}"')
        w(f'ln {k} {WK} @in_work')
    prev = None
    for lid, lt, layer, attested in spec["loci"]:
        k = f"gen:locus:{lid}"
        w(f'def "{k}" "{esc(lt)} · {esc(wt)}"')                 # · <work> → unique content
        w(f'set.add name="{WK}:loci" id="{k}"')
        w(f'ln {k} {WK} @in_work')
        w(f'ln {k} gen:layer:{layer} @in_layer')
        for a in [x.strip() for x in attested.split(",") if x.strip()]:
            w(f'ln {k} gen:witness:{a} @attested_in')
        if prev:
            w(f'ln gen:locus:{prev} {k} @next_locus')
        prev = lid
    for fid, ft, fd, higher, lens in spec.get("features", []):
        k = f"gen:feature:{fid}"
        w(f'def "{k}" "{esc(ft)} · {esc(wt)} — {esc(fd)}"')      # · <work> → unique content
        w(f'set.add name="gen:features" id="{k}"')
        w(f'ln {k} gen:lens:{lens} @via_lens')
    for sid, after, sd in spec.get("seams", []):
        k = f"gen:seam:{sid}"
        w(f'def "{k}" "{esc(sd)}"')
        w(f'set.add name="{WK}:seams" id="{k}"')
        w(f'ln {k} gen:locus:{after} @seam_after')
        w(f'ln {k} {WK} @in_work')
    for hid, ht, hd, seams, layers in spec.get("hyps", []):
        k = f"gen:hyp:{hid}"
        w(f'def "{k}" "{esc(ht)} — {esc(hd)}"')
        w(f'set.add name="{WK}:hyps" id="{k}"')
        w(f'ln {k} {WK} @in_work')
        for s in [x.strip() for x in seams.split(",") if x.strip()]:
            w(f'ln {k} gen:seam:{s} @posits_seam')
        for l in [x.strip() for x in layers.split(",") if x.strip()]:
            w(f'ln {k} gen:layer:{l} @groups_layer')
    w("")

# ── source-stream + synthesis genealogy nodes ──
w('# ── the source-stemma (genealogy nodes) ──')
for nid, title, note, kind, derives in AY.SOURCE_NODES:
    WK = f"gen:work:{nid}"
    w(f'def "{WK}" "{esc(title)} — {esc(note)}"')
    w(f'set.add name="gen:works" id="{WK}"')
    for src in derives:
        w(f'ln {WK} gen:work:{src} @derives_from')
    for t in AY.NODE_CROSS.get(nid, []):
        w(f'ln {WK} {t} thesaurus:related')
w("")

for spec in AY.STRATIFIED:
    emit_work(spec)

# ── sources ──
w('# ── the published sources ──')
for sid, title, author, year, supports, contests, locator in AY.SOURCES:
    k = f"gen:source:{sid}"
    cite = " · ".join([x for x in (author, year) if x])
    body = title + (f" — {cite}" if cite else "") + (f". {locator}" if locator else "")
    w(f'def "{k}" "{esc(body)}"')
    w(f'set.add name="gen:sources" id="{k}"')
    for h in [x.strip() for x in supports.split(",") if x.strip()]:
        w(f'ln {k} gen:hyp:{h} @supports_hyp')
    for h in [x.strip() for x in contests.split(",") if x.strip()]:
        w(f'ln {k} gen:hyp:{h} @contests_hyp')
w("")

ak = os.path.join(ROOT, "app/ontology/base3/genealogy_ayurveda.ak")
open(ak, "w", encoding="utf-8").write("\n".join(out) + "\n")

mx = os.path.join(ROOT, "app/ontology/base3/genealogy_ayurveda_matrix.jsonl")
cells = 0
with open(mx, "w", encoding="utf-8") as fh:
    for spec in AY.STRATIFIED:
        wtn = spec["witnesses"][0][0]
        for lid, *_ in spec["loci"]:
            for fid, *_ in spec["features"]:
                fh.write(json.dumps({"locus": lid, "feature": fid, "value": spec["matrix"][lid][fid], "witness": wtn}) + "\n")
                cells += 1

defs = sum(1 for l in out if l.startswith('def "'))
lns = sum(1 for l in out if l.startswith("ln "))
print("wrote %s (defs=%d, ln=%d)" % (ak, defs, lns))
print("wrote %s (%d cells)" % (mx, cells))

# ── the non-textual layer: @discusses links from each text-stratum (gen:locus, defined in base3)
#    to the real ayurveda:* atoms it treats (materia medica / formulae / doctrine, defined in the
#    world pack). Emitted into app/ontology/world/ so BOTH endpoints are present at load time (base3 is
#    tier A → loaded before world tier B; the ayurveda atoms live in this same pack). This keeps
#    base3 free of cross-pack dangling refs in the seeds tier, where world is not loaded. ──
def _ay_atoms_present():
    # every ayurveda:* atom the world pack registers — whether by explicit def/al or implicitly as
    # a link endpoint (the loader auto-registers endpoints as proto-words, so they resolve too).
    import re
    present = set()
    for fn in os.listdir(os.path.join(ROOT, "app/ontology/world")):
        if not fn.endswith(".ak"):
            continue
        text = open(os.path.join(ROOT, "app/ontology/world", fn), encoding="utf-8").read()
        present.update(re.findall(r"ayurveda:[A-Za-z0-9_:]+", text))
    return present

present = _ay_atoms_present()
dl = []; dw = dl.append
dw("# Stylometry × Ayurveda — the non-textual layer (materia medica · formulae · doctrine).")
dw("# @discusses: a text-stratum (gen:locus, base3) treats a real ayurveda:* subject (world pack).")
dw("# Generated by app/scripts/gen_genealogy_ayurveda_ak.py — lives in world/ so both endpoints load.\n")
dcount = 0; skipped = []
for spec in AY.STRATIFIED:
    ctx = spec.get("context") or {}
    if not ctx:
        continue
    dw(f'# ── {esc(spec["title"].split("—")[0].strip())} ──')
    for lid, *_ in spec["loci"]:
        atoms = ctx.get(lid)
        if not atoms:
            continue
        for atom in atoms:
            if atom not in present:
                skipped.append(atom); continue
            dw(f'ln gen:locus:{lid} {atom} @discusses')
            dcount += 1
    dw("")

dpath = os.path.join(ROOT, "app/ontology/world/ayurveda_genealogy_links.ak")
open(dpath, "w", encoding="utf-8").write("\n".join(dl) + "\n")
print("wrote %s (%d @discusses links)" % (dpath, dcount))
if skipped:
    print("  ⚠ skipped %d links to absent atoms: %s" % (len(skipped), ", ".join(sorted(set(skipped)))))
