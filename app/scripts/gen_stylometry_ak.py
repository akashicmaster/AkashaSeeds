#!/usr/bin/env python3
"""Emit the durable stylometry catalog from the lab's constants (single source of truth).

Reads the Milindapañha catalog defined in app/scripts/milinda_lab.py and writes:
  • app/ontology/base3/stylometry.ak          — the durable sty: catalog (loaded at boot)
  • app/ontology/base3/stylometry_matrix.jsonl — the illustrative matrix for `io.ingest model=sty`

Re-run after editing the catalog in milinda_lab.py; then run scripts/gen_lexicon.py and
python test/verify_lexicon.py --all.
"""
import os, sys, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("AKASHA_SKIP_AUTOINSTALL", "1")
import app.scripts.milinda_lab as L   # catalog constants only (main() is guarded)

WORK = L.WORK
WK = f"sty:work:{WORK}"
def esc(s): return (s or "").replace('"', "'").replace("\n", " ").strip()

out = []
w = out.append
w("# Stylometry — the Milindapañha stratification catalog (durable form of the /labo/stylometry lab).")
w("# Namespace sty:. Companion code: lib/akasha/concepts/sty.py. Generated by scripts/gen_stylometry_ak.py.")
w("# The measurement MATRIX is NOT here — it is streamed at runtime with")
w("#   io.ingest model=sty into=milindapanha path=app/ontology/base3/stylometry_matrix.jsonl")
w("# This catalog links out to the existing textanal:/textcrit: vocabulary via thesaurus:related.\n")

# ── the work ──
w(f'def "{WK}" "Milindapañha — the Questions of King Milinda (Pāli; king Milinda = Menander I, r. c.165–130 BCE)."')
w(f'set.add name="sty:works" id="{WK}"')
for t in ("textanal:stylometry", "textanal:burrows_delta", "textanal:corpus",
          "textcrit:recension", "textcrit:witness", "textcrit:interpolation"):
    w(f'ln {WK} {t} thesaurus:related')
w("")

# ── witnesses ──
w("# ── witnesses (recensions) ──")
for wid, title, lang in L.WITNESSES:
    k = f"sty:witness:{wid}"
    w(f'def "{k}" "{esc(title)}"')
    w(f'set.add name="{WK}:witnesses" id="{k}"')
    w(f'ln {k} {WK} @witness_of')
w("")

# ── layers ──
w("# ── composition strata ──")
for lid, title, desc in L.LAYERS:
    k = f"sty:layer:{lid}"
    w(f'def "{k}" "{esc(title)} — {esc(desc)}"')
    w(f'set.add name="{WK}:layers" id="{k}"')
    w(f'ln {k} {WK} @in_work')
w("")

# ── loci (ordered) ──
w("# ── loci (books, in reading order) ──")
prev = None
for lid, title, layer, attested in L.LOCI:
    k = f"sty:locus:{lid}"
    w(f'def "{k}" "{esc(title)}"')
    w(f'set.add name="{WK}:loci" id="{k}"')
    w(f'ln {k} {WK} @in_work')
    w(f'ln {k} sty:layer:{layer} @in_layer')
    for wtn in [x.strip() for x in attested.split(",") if x.strip()]:
        w(f'ln {k} sty:witness:{wtn} @attested_in')
    if prev:
        w(f'ln sty:locus:{prev} {k} @next_locus')
    prev = lid
w("")

# ── features ──
w("# ── stylometric features ──")
for fid, title, desc, higher in L.FEATURES:
    k = f"sty:feature:{fid}"
    w(f'def "{k}" "{esc(title)} — {esc(desc)}"')
    w(f'set.add name="sty:features" id="{k}"')
w("ln sty:feature:mattr textanal:type_token_ratio thesaurus:related")
w("ln sty:feature:hapax_ratio textanal:hapax_legomenon thesaurus:related")
w("")

# ── seams ──
w("# ── posited composition seams ──")
for sid, after, desc in L.SEAMS:
    k = f"sty:seam:{sid}"
    w(f'def "{k}" "{esc(desc)}"')
    w(f'set.add name="{WK}:seams" id="{k}"')
    w(f'ln {k} sty:locus:{after} @seam_after')
    w(f'ln {k} {WK} @in_work')
w("")

# ── hypotheses ──
w("# ── competing stratification hypotheses ──")
for hid, title, desc, seams, layers in L.HYPS:
    k = f"sty:hyp:{hid}"
    w(f'def "{k}" "{esc(title)} — {esc(desc)}"')
    w(f'set.add name="{WK}:hyps" id="{k}"')
    w(f'ln {k} {WK} @in_work')
    for s in [x.strip() for x in seams.split(",") if x.strip()]:
        w(f'ln {k} sty:seam:{s} @posits_seam')
    for l in [x.strip() for x in layers.split(",") if x.strip()]:
        w(f'ln {k} sty:layer:{l} @groups_layer')
w("")

# ── sources ──
w("# ── the published sources ──")
for sid, title, author, year, supports, contests, locator in L.SOURCES:
    k = f"sty:source:{sid}"
    cite = " · ".join([x for x in (author, year) if x])
    body = f"{title}" + (f" — {cite}" if cite else "") + (f". {locator}" if locator else "")
    w(f'def "{k}" "{esc(body)}"')
    w(f'set.add name="sty:sources" id="{k}"')
    for h in [x.strip() for x in supports.split(",") if x.strip()]:
        w(f'ln {k} sty:hyp:{h} @supports_hyp')
    for h in [x.strip() for x in contests.split(",") if x.strip()]:
        w(f'ln {k} sty:hyp:{h} @contests_hyp')
w("")

ak_path = os.path.join(ROOT, "app/ontology/base3/stylometry.ak")
open(ak_path, "w", encoding="utf-8").write("\n".join(out) + "\n")

# ── the illustrative matrix (io.ingest model=sty target) ──
mx_path = os.path.join(ROOT, "app/ontology/base3/stylometry_matrix.jsonl")
with open(mx_path, "w", encoding="utf-8") as fh:
    for lid, _t, _l, _a in L.LOCI:
        for fid, _ft, _fd, _h in L.FEATURES:
            fh.write(json.dumps({"locus": lid, "feature": fid,
                                 "value": L.MATRIX[lid][fid], "witness": "pali"}) + "\n")

defs = sum(1 for line in out if line.startswith('def "'))
lns = sum(1 for line in out if line.startswith("ln "))
print("wrote %s  (defs=%d, ln=%d)" % (ak_path, defs, lns))
print("wrote %s  (%d cells)" % (mx_path, len(L.LOCI) * len(L.FEATURES)))
