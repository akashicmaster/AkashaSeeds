def person_desc(info: dict, nconst: str) -> str:
    name = info['name']
    birth = info['birthYear']
    death = info['deathYear']
    url = f"https://www.imdb.com/name/{nconst}/"
    if birth != NULL and birth:
        if death != NULL and death:
            span = f" ({birth}–{death})"
        else:
            span = f" (b. {birth})"
    else:
        span = ''
    desc = f"{name}{span}, film director. {url}"
    return truncate(desc, 280)


def title_desc(rec: dict, director_name: str) -> str:
    url = f"https://www.imdb.com/title/{rec['tconst']}/"
    parts = [f"{rec['title']} ({rec['year']})"]
    if rec['genres']:
        parts.append(rec['genres'])
    if director_name:
        parts.append(f"dir. {director_name}")
    parts.append(url)
    desc = '; '.join(parts[:-1]) + '. ' + parts[-1]
    return truncate(desc, 280)


def emit_title_block(rec: dict, director_atom: str, director_name: str) -> list[str]:
    """Return list of .ak lines for one title."""
    atom = f"film:work:{rec['key']}"
    alias = f"film:imdb:{rec['tconst']}"
    desc = title_desc(rec, director_name)
    lines = [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
        f'ln {atom} film:work sys:part_of',
        f'set.add name="ontology.films" id="{atom}"',
    ]
    if director_atom:
        lines.append(f'ln {atom} {director_atom} film:directed_by')
    lines.append('')
    return lines


def emit_director_block(nconst: str, info: dict) -> list[str]:
    """Return list of .ak lines for one director."""
    nn = norm_name(info['name'])
    atom = f"film:person:{nn}"
    alias = f"film:imdb:person:{nconst}"
    desc = person_desc(info, nconst)
    lines = [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
        f'set.add name="ontology.film_directors" id="{atom}"',
        '',
    ]
    return lines


