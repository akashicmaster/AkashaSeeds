def load_ratings(path: str) -> dict[str, tuple[float, int]]:
    """Return {tconst: (averageRating, numVotes)}. ~10 MB in RAM."""
    eprint(f"[imdb_import] Loading ratings from {os.path.basename(path)} …")
    ratings: dict[str, tuple[float, int]] = {}
    with gzip.open(path, 'rt', encoding='utf-8') as f:
        reader = csv.DictReader(f, delimiter='\t', quoting=csv.QUOTE_NONE)
        for row in reader:
            tc = row.get('tconst', '').strip()
            avg_raw = row.get('averageRating', NULL).strip()
            votes_raw = row.get('numVotes', NULL).strip()
            if not tc or avg_raw == NULL or votes_raw == NULL:
                continue
            try:
                ratings[tc] = (float(avg_raw), int(votes_raw))
            except ValueError:
                continue
    eprint(f"  {len(ratings):,} rated titles")
    return ratings


def load_crew(path: str, keep_tconsts: set[str] | None = None) -> dict[str, list[str]]:
    """Return {tconst: [director_nconst, ...]}. Filters to keep_tconsts if provided."""
    eprint(f"[imdb_import] Loading crew from {os.path.basename(path)} …")
    crew: dict[str, list[str]] = {}
    with gzip.open(path, 'rt', encoding='utf-8') as f:
        reader = csv.DictReader(f, delimiter='\t', quoting=csv.QUOTE_NONE)
        for row in reader:
            tc = row.get('tconst', '').strip()
            if not tc:
                continue
            if keep_tconsts is not None and tc not in keep_tconsts:
                continue
            directors_raw = row.get('directors', NULL).strip()
            if directors_raw == NULL or not directors_raw:
                continue
            nconsts = [n.strip() for n in directors_raw.split(',') if n.strip() and n.strip() != NULL]
            if nconsts:
                crew[tc] = nconsts
    eprint(f"  {len(crew):,} titles with director info")
    return crew


def load_names(path: str, keep_nconsts: set[str]) -> dict[str, dict]:
    """Return {nconst: {name, birthYear, deathYear}} filtered to keep_nconsts."""
    eprint(f"[imdb_import] Loading names from {os.path.basename(path)} …")
    names: dict[str, dict] = {}
    with gzip.open(path, 'rt', encoding='utf-8') as f:
        reader = csv.DictReader(f, delimiter='\t', quoting=csv.QUOTE_NONE)
        for row in reader:
            nc = row.get('nconst', '').strip()
            if nc not in keep_nconsts:
                continue
            names[nc] = {
                'name':      row.get('primaryName', '').strip(),
                'birthYear': row.get('birthYear', NULL).strip(),
                'deathYear': row.get('deathYear', NULL).strip(),
            }
    eprint(f"  {len(names):,} director name records loaded")
    return names


def stream_titles(
    path: str,
    ratings: dict[str, tuple[float, int]],
    min_rating: float,
    min_votes: int,
    allowed_types: frozenset[str],
    max_year: int | None,
) -> list[dict]:
    """Stream title.basics.tsv.gz; return filtered list sorted by startYear desc."""
    eprint(f"[imdb_import] Streaming titles from {os.path.basename(path)} …")
    # Dedup by norm_title+year, keep highest-voted
    seen: dict[str, dict] = {}   # key: norm_title_year → record
    total_read = 0
    with gzip.open(path, 'rt', encoding='utf-8') as f:
        reader = csv.DictReader(f, delimiter='\t', quoting=csv.QUOTE_NONE)
        for row in reader:
            total_read += 1
            tt = row.get('titleType', '').strip()
            if tt not in allowed_types:
                continue
            if row.get('isAdult', '1').strip() == '1':
                continue
            yr = row.get('startYear', NULL).strip()
            if yr == NULL or not yr.isdigit():
                continue
            if max_year is not None and int(yr) > max_year:
                continue
            tc = row.get('tconst', '').strip()
            if not tc or tc not in ratings:
                continue
            avg, votes = ratings[tc]
            if avg < min_rating or votes < min_votes:
                continue
            title = row.get('primaryTitle', '').strip()
            if not title:
                continue
            genres_raw = row.get('genres', NULL).strip()
            genres = '' if genres_raw == NULL else genres_raw.replace(',', '; ')
            nt = norm_title(title)
            key = f"{nt}_{yr}"
            rec = {
                'tconst': tc,
                'title':  title,
                'year':   yr,
                'type':   tt,
                'genres': genres,
                'rating': avg,
                'votes':  votes,
                'norm':   nt,
                'key':    key,
            }
            if key not in seen or votes > seen[key]['votes']:
                seen[key] = rec
    results = list(seen.values())
    # Sort: newest first
    results.sort(key=lambda r: (-int(r['year']), r['title'].lower()))
    eprint(f"  Read {total_read:,} rows → {len(results):,} titles after filtering")
    return results


