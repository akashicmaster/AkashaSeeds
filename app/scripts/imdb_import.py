"""
imdb_import.py — IMDb public datasets → app/ontology/film/films_NN.ak + tv_series_NN.ak + directors_NN.ak

Imports notable films, TV series, and the directors who made them from IMDb public datasets.
Full plots and cast lists are NOT stored — only titles, years, genres, director name,
rating metadata, and a URL pointing back to imdb.com.

Atom IDs:
    film:work:{norm_title}_{year}    e.g. film:work:the_godfather_1972
    film:person:{norm_name}          e.g. film:person:francis_ford_coppola
Aliases:
    film:imdb:{tconst}               → imdb.com/title/{tconst}
    film:imdb:person:{nconst}        → imdb.com/name/{nconst}
Links:
    film:work:{...} → film:work             sys:part_of
    film:work:{...} → film:person:{...}     film:directed_by

Filters applied (title.basics joined with title.ratings):
    - titleType in: movie, tvSeries, tvMiniSeries  (default; override with --types)
    - averageRating >= --min-rating  (default: 7.0)
    - numVotes >= --min-votes  (default: 10000)
    - isAdult == '0'
    - startYear present (not \\N)
    - Optional: startYear <= --max-year

Attribution:
    IMDb public datasets — https://datasets.imdbws.com/
    For personal and non-commercial use only — https://developer.imdb.com/non-commercial-datasets/

Usage:
    # Auto-download all files and convert:
    python app/scripts/imdb_import.py

    # Use pre-downloaded files:
    python app/scripts/imdb_import.py \\
        --titles-file title.basics.tsv.gz \\
        --ratings-file title.ratings.tsv.gz \\
        --crew-file title.crew.tsv.gz \\
        --names-file name.basics.tsv.gz

    # Classics only (up to 1970), high bar:
    python app/scripts/imdb_import.py --max-year 1970 --min-rating 7.5 --min-votes 25000

    # Dry run — preview first 20 atoms, no files written:
    python app/scripts/imdb_import.py --dry-run

Options:
    --titles-file FILE    Pre-downloaded title.basics.tsv.gz
    --ratings-file FILE   Pre-downloaded title.ratings.tsv.gz
    --crew-file FILE      Pre-downloaded title.crew.tsv.gz
    --names-file FILE     Pre-downloaded name.basics.tsv.gz
    --out DIR             Output directory (default: app/ontology/film/)
    --chunk-size N        Atoms per .ak file (default: 1000)
    --min-rating FLOAT    Minimum IMDb average rating (default: 7.0)
    --min-votes INT       Minimum vote count (default: 10000)
    --types LIST          Comma-separated title types (default: movie,tvSeries,tvMiniSeries)
    --max-year INT        Only include titles with startYear <= N (default: no limit)
    --dry-run             Print first 20 atoms to stdout, write no files

Source files (all at https://datasets.imdbws.com/):
    title.basics.tsv.gz   — titles, types, years, genres
    title.ratings.tsv.gz  — average rating and vote count
    title.crew.tsv.gz     — director/writer nconst lists per title
    name.basics.tsv.gz    — person name, birth, death, profession
"""

import argparse
import csv
import gzip
import os
import re
import sys
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "film")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "imdb_cache")

BASE_URL       = "https://datasets.imdbws.com/"
TITLES_FILE    = "title.basics.tsv.gz"
RATINGS_FILE   = "title.ratings.tsv.gz"
CREW_FILE      = "title.crew.tsv.gz"
NAMES_FILE     = "name.basics.tsv.gz"

DEFAULT_TYPES  = frozenset({"movie", "tvSeries", "tvMiniSeries"})

FILMS_HEADER = """\
# {filename}
# IMDb public datasets — https://datasets.imdbws.com/
# For personal and non-commercial use only — https://developer.imdb.com/non-commercial-datasets/
# Generated by app/scripts/imdb_import.py
# Entries: {entry_range}
#
"""

DIRECTORS_HEADER = """\
# {filename}
# IMDb public datasets — https://datasets.imdbws.com/
# For personal and non-commercial use only — https://developer.imdb.com/non-commercial-datasets/
# Generated by app/scripts/imdb_import.py
# Directors: {entry_range}
#
"""

NULL = r'\N'


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def norm_title(title: str, max_chars: int = 50) -> str:
    s = title.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def norm_name(name: str, max_chars: int = 60) -> str:
    s = name.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip('.,;') + '…'


def _download(url: str, dest: str, label: str) -> None:
    eprint(f"Downloading {label} …")

    def _prog(b, bs, ts):
        if ts > 0:
            pct = min(100, b * bs * 100 // ts)
            print(f"\r  {pct}%", end='', flush=True, file=sys.stderr)

    urllib.request.urlretrieve(url, dest, _prog)
    eprint()


def ensure_file(arg: str | None, filename: str, label: str) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, filename)
    if os.path.exists(dest):
        eprint(f"Using cached: {dest}")
        return dest
    url = BASE_URL + filename
    try:
        _download(url, dest, f"{filename} ({label})")
    except Exception as e:
        eprint(f"\nDownload failed: {e}")
        _print_manual_download()
        sys.exit(1)
    return dest


def _print_manual_download() -> None:
    eprint("""
Manual download:
  Visit https://datasets.imdbws.com/
  Download: title.basics.tsv.gz, title.ratings.tsv.gz, title.crew.tsv.gz, name.basics.tsv.gz
  Then run:
    python app/scripts/imdb_import.py \\
      --titles-file title.basics.tsv.gz \\
      --ratings-file title.ratings.tsv.gz \\
      --crew-file title.crew.tsv.gz \\
      --names-file name.basics.tsv.gz
""")


