# Main generation
# ---------------------------------------------------------------------------

def generate(
    titles: list[dict],
    crew: dict[str, list[str]],
    names: dict[str, dict],
    out_dir: str,
    chunk_size: int,
    dry_run: bool,
) -> None:
    # Build nconst → norm_name → atom id map; deduplicate directors
    director_atom: dict[str, str] = {}   # nconst → atom id
    director_info: dict[str, dict] = {}  # nconst → info dict
    for nconst, info in names.items():
        nn = norm_name(info['name'])
        director_atom[nconst] = f"film:person:{nn}"
        director_info[nconst] = info

    # Separate films and tv
    films    = [r for r in titles if r['type'] == 'movie']
    tv       = [r for r in titles if r['type'] in ('tvSeries', 'tvMiniSeries')]

    # Build director → title director_name for inline reference
    def get_dir_name(tconst: str) -> tuple[str, str]:
        """Return (atom, display_name) for first director of a title."""
        nconsts = crew.get(tconst, [])
        for nc in nconsts:
            if nc in director_atom:
                info = director_info[nc]
                return director_atom[nc], info['name']
        return '', ''

    # Collect all lines per category
    film_lines: list[str] = []
    for rec in films:
        da, dn = get_dir_name(rec['tconst'])
        film_lines.extend(emit_title_block(rec, da, dn))

    tv_lines: list[str] = []
    for rec in tv:
        da, dn = get_dir_name(rec['tconst'])
        tv_lines.extend(emit_title_block(rec, da, dn))

    dir_lines: list[str] = []
    # Only emit directors who appear as first director of at least one qualifying title
    used_nconsts: set[str] = set()
    for rec in titles:
        nconsts = crew.get(rec['tconst'], [])
        if nconsts:
            used_nconsts.add(nconsts[0])
    used_nconsts = used_nconsts.intersection(director_atom.keys())
    for nc in sorted(used_nconsts, key=lambda n: names[n]['name'].lower()):
        dir_lines.extend(emit_director_block(nc, names[nc]))

    eprint(f"\n  Films:     {len(films):,}")
    eprint(f"  TV:        {len(tv):,}")
    eprint(f"  Directors: {len(used_nconsts):,}")
    eprint(f"  Output:    {out_dir}/")

    if dry_run:
        all_preview = film_lines + tv_lines + dir_lines
        print("# --- DRY RUN: first 20 output lines ---")
        count = 0
        for line in all_preview:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    os.makedirs(out_dir, exist_ok=True)

    def write_chunks(lines: list[str], base: str, header_tpl: str) -> int:
        """Write lines to chunked files; return number of files written."""
        # Split by atom blocks (blank-line separated)
        blocks: list[list[str]] = []
        current: list[str] = []
        for line in lines:
            current.append(line)
            if line == '':
                blocks.append(current)
                current = []
        if current:
            blocks.append(current)

        n_chunks = (len(blocks) + chunk_size - 1) // chunk_size
        for i in range(n_chunks):
            chunk_blocks = blocks[i * chunk_size:(i + 1) * chunk_size]
            fname = f"{base}_{i + 1:02d}.ak"
            fpath = os.path.join(out_dir, fname)
            start = i * chunk_size + 1
            end   = start + len(chunk_blocks) - 1
            with open(fpath, 'w', encoding='utf-8') as fh:
                fh.write(header_tpl.format(filename=fname, entry_range=f"{start}–{end}"))
                for block in chunk_blocks:
                    fh.write('\n'.join(block) + '\n')
            eprint(f"  {fname}  {len(chunk_blocks):5d} entries", flush=True)
        return n_chunks

    eprint("[imdb_import] Writing films …")
    write_chunks(film_lines, "films", FILMS_HEADER)
    eprint("[imdb_import] Writing TV series …")
    write_chunks(tv_lines, "tv_series", FILMS_HEADER)
    eprint("[imdb_import] Writing directors …")
    write_chunks(dir_lines, "directors", DIRECTORS_HEADER)

    eprint(f"\n  Done → {out_dir}/")
    eprint("\nNext: git add app/ontology/film/ && git commit")


