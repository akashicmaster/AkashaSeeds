# Entry point
# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--titles-file',  help='Pre-downloaded title.basics.tsv.gz')
    ap.add_argument('--ratings-file', help='Pre-downloaded title.ratings.tsv.gz')
    ap.add_argument('--crew-file',    help='Pre-downloaded title.crew.tsv.gz')
    ap.add_argument('--names-file',   help='Pre-downloaded name.basics.tsv.gz')
    ap.add_argument('--out',          default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size',   type=int, default=1000,
                    help='Atoms per .ak file (default: 1000)')
    ap.add_argument('--min-rating',   type=float, default=7.0,
                    help='Minimum IMDb average rating (default: 7.0)')
    ap.add_argument('--min-votes',    type=int, default=10_000,
                    help='Minimum vote count (default: 10000)')
    ap.add_argument('--types',        default='movie,tvSeries,tvMiniSeries',
                    help='Comma-separated title types (default: movie,tvSeries,tvMiniSeries)')
    ap.add_argument('--max-year',     type=int, default=None,
                    help='Only include titles with startYear <= N (default: no limit)')
    ap.add_argument('--dry-run',      action='store_true',
                    help='Print first 20 atoms to stdout, write no files')
    args = ap.parse_args()

    allowed_types = frozenset(t.strip() for t in args.types.split(',') if t.strip())

    eprint('[imdb_import] Locating source files …')
    ratings_path = ensure_file(args.ratings_file, RATINGS_FILE, '~10 MB')
    crew_path    = ensure_file(args.crew_file,    CREW_FILE,    '~15 MB')
    titles_path  = ensure_file(args.titles_file,  TITLES_FILE,  '~200 MB uncompressed')
    names_path   = ensure_file(args.names_file,   NAMES_FILE,   '~250 MB uncompressed')

    ratings = load_ratings(ratings_path)
    titles  = stream_titles(
        titles_path, ratings,
        args.min_rating, args.min_votes,
        allowed_types, args.max_year,
    )
    if not titles:
        eprint('No titles matched the filters. Try lowering --min-rating or --min-votes.')
        sys.exit(0)

    # Load crew only for titles that passed the filter
    keep_tconsts = {r['tconst'] for r in titles}
    crew = load_crew(crew_path, keep_tconsts)

    # Collect director nconsts we actually need
    needed_nconsts: set[str] = set()
    for tc in keep_tconsts:
        for nc in crew.get(tc, []):
            needed_nconsts.add(nc)

    names = load_names(names_path, needed_nconsts)

    generate(titles, crew, names, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
