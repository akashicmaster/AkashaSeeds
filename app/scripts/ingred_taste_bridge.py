"""
ingred_taste_bridge.py — flavor scores → taste/colour concept links

Ingredients carry numeric flavour scores as links, e.g.
    ln ingred:fruit:apple  score:0.85         rec:sweetness
    ln ingred:fruit:apple  score:0.25         rec:acidity
    ln ingred:fruit:apple  score:color:red    rec:color

Those are *scores*, not links to the perceptual concepts, so the head of an
association chain (chocolate → sweet → pleasure → happy) is missing. This scans
every rec:* score in ontology/ and, where a score clears its threshold, emits a
concrete link from the ingredient to the matching perceptual atom
(dna:taste:* / dna:color:*) — which the sense/emotion bridges then carry on to
emo:*. Re-run whenever more ingredients get scored; it regenerates the file.

Output: ontology/base/ingred_taste_bridges.ak   (links only, no new atoms)

Usage:
    python app/scripts/ingred_taste_bridge.py            # write the .ak
    python app/scripts/ingred_taste_bridge.py --dry-run  # print stats only
    python app/scripts/ingred_taste_bridge.py --threshold 0.6
"""
import argparse, glob, os, re

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(PROJECT_ROOT, "ontology", "base", "ingred_taste_bridges.ak")

# rec:<axis>  →  perceptual taste atom (score ≥ threshold links)
TASTE_AXIS = {
    "sweetness":  "dna:taste:sweet",
    "acidity":    "dna:taste:sour",
    "bitterness": "dna:taste:bitter",
    "saltiness":  "dna:taste:salty",
    "umami":      "dna:taste:umami",
    "spiciness":  "dna:taste:hot",
    "heat":       "dna:taste:hot",
}


def _defined_atoms(root):
    have = set()
    for fp in glob.glob(os.path.join(root, "ontology", "**", "*.ak"), recursive=True):
        for a in re.findall(r'^def\s+"([^"]+)"', open(fp, errors="ignore").read(), re.M):
            have.add(a)
    return have


def scan(root):
    taste = {}   # (ingred, axis) -> value
    color = {}   # (ingred) -> [colours]
    for fp in glob.glob(os.path.join(root, "ontology", "**", "*.ak"), recursive=True):
        txt = open(fp, errors="ignore").read()
        for ing, val, axis in re.findall(r'^ln\s+(ingred:\S+)\s+score:([0-9.]+)\s+rec:([a-z_]+)', txt, re.M):
            if axis in TASTE_AXIS:
                taste[(ing, axis)] = float(val)
        for ing, c in re.findall(r'^ln\s+(ingred:\S+)\s+score:color:([a-z_]+)\s+rec:color', txt, re.M):
            color.setdefault(ing, [])
            if c not in color[ing]:
                color[ing].append(c)
    return taste, color


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--threshold", type=float, default=0.6)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    have = _defined_atoms(PROJECT_ROOT)
    taste, color = scan(PROJECT_ROOT)

    lines = [
        "# Akasha ontology — ingredient → taste/colour perceptual links",
        "# Generated by app/scripts/ingred_taste_bridge.py from the rec:* flavour scores.",
        f"# A score >= {args.threshold} links the ingredient to its perceptual atom",
        "# (dna:taste:* / dna:color:*), which the sense/emotion bridges carry on to",
        "# emo:* — so chains like  apple -> sweet -> joy  traverse from the ingredient.",
        "# Links only, no new atoms. Re-run to extend as more ingredients get scored.",
        "",
    ]
    seen = set()
    n_taste = n_color = 0
    for (ing, axis), val in sorted(taste.items()):
        if val < args.threshold:
            continue
        atom = TASTE_AXIS[axis]
        key = (ing, atom)
        if key in seen or atom not in have:
            continue
        seen.add(key)
        lines.append(f"ln {ing} {atom} thesaurus:related")
        n_taste += 1
    lines.append("")
    for ing, cs in sorted(color.items()):
        for c in cs:
            atom = f"dna:color:{c}" if f"dna:color:{c}" in have else (f"color:{c}" if f"color:{c}" in have else None)
            if not atom:
                continue
            key = (ing, atom)
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"ln {ing} {atom} thesaurus:related")
            n_color += 1

    print(f"scored ingredients: {len(set(i for i, _ in taste) | set(color))}")
    print(f"taste links (>= {args.threshold}): {n_taste} | colour links: {n_color}")
    if args.dry_run:
        print("(dry run — no file written)")
        return
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"→ {OUT}")


if __name__ == "__main__":
    main()
