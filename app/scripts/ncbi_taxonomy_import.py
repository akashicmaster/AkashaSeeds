"""
ncbi_taxonomy_import.py — NCBI Taxonomy → app/ontology/biology/taxon_NN.ak

Converts the NCBI Taxonomy database to Akasha .ak atoms for the optional
'biology' ontology pack.

Scope is filtered by rank and taxonomic group to produce a manageable set:
    Vertebrates  (Chordata)       — all ranks including genus + species
    Plants       (Viridiplantae)  — kingdom through genus
    Fungi        (Fungi)          — kingdom through family
    Invertebrates (Metazoa excl. Chordata) — kingdom through order
    Bacteria                      — kingdom through class (no genera/species)
    Viruses                       — excluded

Atom IDs:    bio:{rank}:{normalized_scientific_name}
             e.g. bio:species:homo_sapiens, bio:family:felidae
Aliases:     bio:ncbi:{taxid}      (canonical NCBI Tax ID)
Links:       sys:part_of → parent taxon (e.g. bio:genus:homo → bio:family:hominidae)

Attribution:
    NCBI Taxonomy — https://www.ncbi.nlm.nih.gov/taxonomy
    National Center for Biotechnology Information
    Public domain

Usage:
    python app/scripts/ncbi_taxonomy_import.py

    python app/scripts/ncbi_taxonomy_import.py --taxdump /path/to/taxdump.tar.gz

    python app/scripts/ncbi_taxonomy_import.py --dry-run

Options:
    --taxdump FILE    Pre-downloaded taxdump.tar.gz
    --out DIR         Output directory (default: app/ontology/biology/)
    --chunk-size N    Atoms per .ak file (default: 2000)
    --dry-run         Print stats only, write no files

Source:
    https://ftp.ncbi.nlm.nih.gov/pub/taxonomy/taxdump.tar.gz  (~55 MB)
"""

import argparse
import io
import os
import re
import sys
import tarfile
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "biology")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "ncbi_taxonomy_cache")

TAXDUMP_URL = "https://ftp.ncbi.nlm.nih.gov/pub/taxonomy/taxdump.tar.gz"

# Well-known NCBI taxids for major groups
TAXID_ROOT         = 1
TAXID_BACTERIA     = 2
TAXID_ARCHAEA      = 2157
TAXID_EUKARYOTA    = 2759
TAXID_VIRUSES      = 10239
TAXID_FUNGI        = 4751
TAXID_METAZOA      = 33208   # animals
TAXID_CHORDATA     = 7711
TAXID_VIRIDIPLANTAE = 33090  # green plants
TAXID_INSECTA      = 50557
TAXID_ARACHNIDA    = 6854
TAXID_NEMATODA     = 6231

# Ranks to include
ALL_RANKS = frozenset({
    'superkingdom', 'kingdom', 'subkingdom', 'phylum', 'subphylum',
    'superclass', 'class', 'subclass', 'superorder', 'order', 'suborder',
    'superfamily', 'family', 'subfamily', 'tribe', 'genus', 'species',
    'species group', 'species subgroup', 'subspecies',
})

# Per-group maximum rank depth (ranks above this are excluded per group)
GROUP_MAX_RANK: dict[str, str] = {
    'vertebrates':   'species',
    'plants':        'genus',
    'fungi':         'family',
    'invertebrates': 'order',
    'bacteria':      'class',
    'archaea':       'class',
}

RANK_DEPTH: dict[str, int] = {
    'superkingdom': 1, 'kingdom': 2, 'subkingdom': 3,
    'phylum': 4, 'subphylum': 5,
    'superclass': 6, 'class': 7, 'subclass': 8,
    'superorder': 9, 'order': 10, 'suborder': 11,
    'superfamily': 12, 'family': 13, 'subfamily': 14, 'tribe': 15,
    'genus': 16,
    'species group': 17, 'species subgroup': 17,
    'species': 18, 'subspecies': 19,
}

FILE_HEADER = """\
# {filename}
# NCBI Taxonomy — https://www.ncbi.nlm.nih.gov/taxonomy — Public domain
# Generated by app/scripts/ncbi_taxonomy_import.py
# Taxa: {taxon_range}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def normalize(name: str) -> str:
    s = name.lower()
    s = re.sub(r"[\s\-'/]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:80]


def open_member(tf: tarfile.TarFile, name: str):
    """Return a text-mode file object for a tarfile member."""
    member = tf.getmember(name)
    f = tf.extractfile(member)
    return io.TextIOWrapper(f, encoding='utf-8', errors='replace')


def parse_names(tf: tarfile.TarFile) -> dict[int, dict]:
    """
    Parse names.dmp → {taxid: {'sci': str, 'common': str}}
    """
    names: dict[int, dict] = {}
    with open_member(tf, 'names.dmp') as f:
        for line in f:
            parts = [p.strip() for p in line.split('\t|\t')]
            if len(parts) < 4:
                continue
            try:
                tid = int(parts[0])
            except ValueError:
                continue
            name_txt   = parts[1].rstrip('\t|').strip()
            name_class = parts[3].rstrip('\t|').strip()
            if tid not in names:
                names[tid] = {'sci': '', 'common': ''}
            if name_class == 'scientific name':
                names[tid]['sci'] = name_txt
            elif name_class in ('common name', 'genbank common name') and not names[tid]['common']:
                names[tid]['common'] = name_txt
    return names


def parse_nodes(tf: tarfile.TarFile) -> dict[int, dict]:
    """
    Parse nodes.dmp → {taxid: {'parent': int, 'rank': str, 'div': int}}
    """
    nodes: dict[int, dict] = {}
    with open_member(tf, 'nodes.dmp') as f:
        for line in f:
            parts = [p.strip() for p in line.split('\t|\t')]
            if len(parts) < 5:
                continue
            try:
                tid    = int(parts[0])
                parent = int(parts[1])
                rank   = parts[2].rstrip('\t|').strip()
                div    = int(parts[4].rstrip('\t|'))
            except (ValueError, IndexError):
                continue
            nodes[tid] = {'parent': parent, 'rank': rank, 'div': div}
    return nodes


def build_subtree(nodes: dict, root: int) -> set[int]:
    """Return set of all taxids in the subtree rooted at root."""
    children: dict[int, list[int]] = {}
    for tid, n in nodes.items():
        p = n['parent']
        if p != tid:
            children.setdefault(p, []).append(tid)
    result: set[int] = set()
    queue = [root]
    while queue:
        tid = queue.pop()
        result.add(tid)
        queue.extend(children.get(tid, []))
    return result


def group_of(tid: int, subtrees: dict[str, set]) -> str | None:
    """Return the highest-priority group name for this taxid."""
    for group in ('vertebrates', 'plants', 'fungi', 'invertebrates', 'bacteria', 'archaea'):
        if tid in subtrees.get(group, set()):
            return group
    return None


def build_filtered_taxa(nodes: dict, names: dict) -> list[dict]:
    """
    Build and filter the taxonomy. Returns list of taxon dicts
    sorted topologically (ancestors before descendants).
    """
    print("  Building subtrees …", flush=True)

    # Compute group subtrees
    chordata_set  = build_subtree(nodes, TAXID_CHORDATA)
    inverts_set   = build_subtree(nodes, TAXID_METAZOA) - chordata_set
    plants_set    = build_subtree(nodes, TAXID_VIRIDIPLANTAE)
    fungi_set     = build_subtree(nodes, TAXID_FUNGI)
    bacteria_set  = build_subtree(nodes, TAXID_BACTERIA)
    archaea_set   = build_subtree(nodes, TAXID_ARCHAEA)

    subtrees = {
        'vertebrates':   chordata_set,
        'plants':        plants_set,
        'fungi':         fungi_set,
        'invertebrates': inverts_set,
        'bacteria':      bacteria_set,
        'archaea':       archaea_set,
    }

    print("  Filtering by rank … ", flush=True)
    kept: dict[int, dict] = {}

    for tid, n in nodes.items():
        rank = n['rank']
        if rank not in ALL_RANKS:
            continue
        group = group_of(tid, subtrees)
        if group is None:
            continue
        max_rank = GROUP_MAX_RANK[group]
        if RANK_DEPTH.get(rank, 99) > RANK_DEPTH.get(max_rank, 0):
            continue
        sci    = names.get(tid, {}).get('sci', '')
        common = names.get(tid, {}).get('common', '')
        if not sci:
            continue
        kept[tid] = {
            'tid':    tid,
            'parent': n['parent'],
            'rank':   rank,
            'sci':    sci,
            'common': common,
            'group':  group,
        }

    # Topological sort (BFS from root, then keep order)
    print(f"  Sorting {len(kept)} taxa … ", flush=True)
    children: dict[int, list[int]] = {}
    for tid, t in kept.items():
        p = t['parent']
        if p != tid and p in kept:
            children.setdefault(p, []).append(tid)

    ordered: list[dict] = []
    visited: set[int] = set()
    # Start from roots (parent not in kept)
    roots = [tid for tid, t in kept.items() if t['parent'] not in kept or t['parent'] == tid]
    queue = sorted(roots)
    while queue:
        tid = queue.pop(0)
        if tid in visited:
            continue
        visited.add(tid)
        ordered.append(kept[tid])
        queue = sorted(children.get(tid, [])) + queue

    return ordered


def atom_id(t: dict) -> str:
    rank = t['rank'].replace(' ', '_')
    norm = normalize(t['sci'])
    return f"bio:{rank}:{norm}"


def emit_taxon(fh, t: dict, id_map: dict[int, str]) -> None:
    aid = atom_id(t)
    alias = f"bio:ncbi:{t['tid']}"
    sci    = t['sci']
    common = t['common']
    rank   = t['rank']

    desc = sci
    if common:
        desc += f" ({common})"
    desc += f" — {rank}"

    fh.write(f'def "{aid}" "{escape_ak(desc)}"\n')
    fh.write(f'al {aid} {alias}\n')

    # Parent link
    parent_tid = t['parent']
    if parent_tid in id_map and parent_tid != t['tid']:
        fh.write(f'ln {aid} {id_map[parent_tid]} sys:part_of\n')

    fh.write('\n')


def generate(taxa: list[dict], out_dir: str, chunk_size: int, dry_run: bool) -> None:
    total     = len(taxa)
    num_files = (total + chunk_size - 1) // chunk_size

    by_group: dict[str, int] = {}
    by_rank:  dict[str, int] = {}
    for t in taxa:
        by_group[t['group']] = by_group.get(t['group'], 0) + 1
        by_rank[t['rank']]   = by_rank.get(t['rank'], 0) + 1

    print(f"\n  Taxa: {total}")
    for g, n in sorted(by_group.items()):
        print(f"    {g}: {n:6d}")
    top_ranks = sorted(by_rank.items(), key=lambda x: -x[1])[:8]
    print(f"  Top ranks: " + ', '.join(f"{r}({n})" for r, n in top_ranks))
    print(f"  Files: {num_files} × {chunk_size} → taxon_{{NN}}.ak")

    if dry_run:
        return

    os.makedirs(out_dir, exist_ok=True)

    # Build id_map for parent lookups
    id_map = {t['tid']: atom_id(t) for t in taxa}

    for i in range(num_files):
        chunk = taxa[i * chunk_size:(i + 1) * chunk_size]
        fname = f"taxon_{i + 1:02d}.ak"
        fpath = os.path.join(out_dir, fname)
        start = i * chunk_size + 1
        end   = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, taxon_range=f"{start}–{end}"))
            for t in chunk:
                emit_taxon(fh, t, id_map)
        print(f"  {fname}  {len(chunk):5d} taxa", flush=True)

    print(f"\n  Total: {total} taxa in {num_files} files → {out_dir}/")
    print("\nNext:")
    print("  git add app/ontology/biology/ && git commit")
    print("  onto.pack.enable biology")


def _download(url: str, dest: str, label: str) -> None:
    print(f"Downloading {label} …")
    print("(~55 MB)")

    def _prog(b, bs, ts):
        if ts > 0:
            print(f"\r  {min(100, b * bs * 100 // ts)}%", end='', flush=True)

    urllib.request.urlretrieve(url, dest, _prog)
    print()


def ensure_taxdump(arg: str | None) -> str:
    if arg:
        return arg
    os.makedirs(CACHE_DIR, exist_ok=True)
    dest = os.path.join(CACHE_DIR, 'taxdump.tar.gz')
    if os.path.exists(dest):
        print(f"Using cached: {dest}")
        return dest
    _download(TAXDUMP_URL, dest, "NCBI taxdump.tar.gz")
    return dest


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--taxdump',    help='Pre-downloaded taxdump.tar.gz')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=2000,
                    help='Taxa per .ak file (default: 2000)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print stats only, write no files')
    args = ap.parse_args()

    print('[ncbi_taxonomy_import] Locating taxdump …')
    try:
        dump_path = ensure_taxdump(args.taxdump)
    except Exception as e:
        print(f'\nError: {e}')
        print(f'\nManual download: {TAXDUMP_URL}')
        print('Re-run with: --taxdump /path/to/taxdump.tar.gz')
        sys.exit(1)

    print(f'[ncbi_taxonomy_import] Parsing names.dmp …')
    with tarfile.open(dump_path, 'r:gz') as tf:
        names = parse_names(tf)
        print(f'  {len(names):,} name records')
        print('[ncbi_taxonomy_import] Parsing nodes.dmp …')
        nodes = parse_nodes(tf)
        print(f'  {len(nodes):,} nodes')

    print('[ncbi_taxonomy_import] Filtering …')
    taxa = build_filtered_taxa(nodes, names)

    generate(taxa, args.out, args.chunk_size, args.dry_run)


if __name__ == '__main__':
    main()
