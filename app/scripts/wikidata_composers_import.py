"""
wikidata_composers_import.py — Wikidata SPARQL → app/ontology/music/composers_NN.ak

Queries Wikidata for pre-20th century classical music composers and converts
results to Akasha .ak atoms for app/ontology/music/.

Filter: composers who died before 1920 or were born before 1870.
~1,000–5,000 records expected depending on Wikidata coverage.

Atom IDs:    music:composer:{norm_name}     e.g. music:composer:beethoven
Aliases:     music:composer:wd:{qid}        e.g. music:composer:wd:Q1340

Attribution:
    Wikidata — https://www.wikidata.org/
    CC0 1.0 Universal — https://creativecommons.org/publicdomain/zero/1.0/
    IMSLP — https://imslp.org/ (linked via imslp.org/wiki/ URLs where available)

Usage:
    # Query Wikidata SPARQL endpoint automatically:
    python app/scripts/wikidata_composers_import.py

    # Use pre-downloaded SPARQL result JSON:
    python app/scripts/wikidata_composers_import.py --json /path/to/composers.json

    # Dry run (print first 20 lines, no files written):
    python app/scripts/wikidata_composers_import.py --dry-run

    # Limit number of composers processed:
    python app/scripts/wikidata_composers_import.py --limit 200

Options:
    --json FILE       Pre-downloaded SPARQL result JSON
    --out DIR         Output directory (default: app/ontology/music/)
    --chunk-size N    Atoms per .ak file (default: 500)
    --limit N         Max composers to process (default: all)
    --dry-run         Print first 20 lines, write no files

Source:
    https://query.wikidata.org/sparql
    User-Agent: AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)
"""

import argparse
import json
import os
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "music")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "wikidata_composers_cache")

SPARQL_ENDPOINT = "https://query.wikidata.org/sparql"
WIKIDATA_BASE   = "https://www.wikidata.org/wiki/"
IMSLP_BASE      = "https://imslp.org/wiki/"

USER_AGENT = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

SPARQL_QUERY = """
SELECT DISTINCT ?composer ?composerLabel ?birthYear ?deathYear ?nationalityLabel ?imslpTitle WHERE {
  ?composer wdt:P31 wd:Q5 .
  ?composer wdt:P106/wdt:P279* wd:Q36834 .
  OPTIONAL { ?composer wdt:P569 ?birth . BIND(YEAR(?birth) AS ?birthYear) }
  OPTIONAL { ?composer wdt:P570 ?death . BIND(YEAR(?death) AS ?deathYear) }
  OPTIONAL { ?composer wdt:P27 ?nationality }
  OPTIONAL { ?composer wdt:P839 ?imslpTitle }
  FILTER (!BOUND(?deathYear) || ?deathYear < 1920)
  FILTER (!BOUND(?birthYear) || ?birthYear < 1870)
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" . }
}
ORDER BY ?deathYear ?composerLabel
LIMIT 5000
""".strip()

FILE_HEADER = """\
# {filename}
# Wikidata — https://www.wikidata.org/ — CC0 1.0
# Classical composers (died < 1920 or born < 1870)
# Generated by app/scripts/wikidata_composers_import.py
# Composers: {comp_range}
#
"""


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n - 1].rsplit(' ', 1)[0].rstrip(' ,;') + '…'


def normalize_name(name: str) -> str:
    """Convert composer name to atom ID component (lowercase, ASCII, underscored)."""
    # Strip accents
    s = unicodedata.normalize('NFKD', name)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = s.lower()
    s = re.sub(r"[\s\-,.'()\/]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:60]


def extract_qid(uri: str) -> str:
    """Extract Q-number from a Wikidata entity URI like http://www.wikidata.org/entity/Q1340."""
    m = re.search(r'[/:]([Qq]\d+)$', uri)
    return m.group(1) if m else uri.strip()


def parse_sparql_results(data: dict) -> list[dict]:
    """
    Parse a SPARQL results+JSON response into a list of composer dicts.
    Keys: name, birth, death, nationality, imslp_title, qid, uri.
    Deduplicates by QID (IMSLP title: keep first non-empty).
    """
    try:
        bindings = data['results']['bindings']
    except (KeyError, TypeError):
        return []

    seen: dict[str, dict] = {}   # qid → composer dict

    for row in bindings:
        uri   = row.get('composer', {}).get('value', '').strip()
        qid   = extract_qid(uri)
        if not qid:
            continue

        name  = row.get('composerLabel', {}).get('value', '').strip()
        birth = row.get('birthYear',     {}).get('value', '').strip()
        death = row.get('deathYear',     {}).get('value', '').strip()
        nat   = row.get('nationalityLabel', {}).get('value', '').strip()
        imslp = row.get('imslpTitle',    {}).get('value', '').strip()

        # Skip auto-generated labels (Wikidata fallback = QID itself)
        if name == qid or not name:
            continue

        if qid in seen:
            # Merge: keep first name/dates; prefer first non-empty IMSLP title
            if imslp and not seen[qid]['imslp_title']:
                seen[qid]['imslp_title'] = imslp
            if nat and not seen[qid]['nationality']:
                seen[qid]['nationality'] = nat
        else:
            seen[qid] = {
                'name':        name,
                'birth':       birth,
                'death':       death,
                'nationality': nat,
                'imslp_title': imslp,
                'qid':         qid,
                'uri':         uri,
            }

    return list(seen.values())


def ensure_data(json_arg: str | None) -> list[dict]:
    """Return parsed composer list from cache, --json arg, or live SPARQL query."""
    if json_arg:
        print(f'[wikidata_composers_import] Loading --json {json_arg} …', file=sys.stderr)
        with open(json_arg, encoding='utf-8') as f:
            data = json.load(f)
        return parse_sparql_results(data)

    os.makedirs(CACHE_DIR, exist_ok=True)
    cache_path = os.path.join(CACHE_DIR, 'composers.json')

    if os.path.exists(cache_path):
        print(f'[wikidata_composers_import] Using cached: {cache_path}', file=sys.stderr)
        with open(cache_path, encoding='utf-8') as f:
            data = json.load(f)
        return parse_sparql_results(data)

    print('[wikidata_composers_import] Querying Wikidata SPARQL …', file=sys.stderr)
    print(f'  Endpoint: {SPARQL_ENDPOINT}', file=sys.stderr)

    params  = urllib.parse.urlencode({'query': SPARQL_QUERY, 'format': 'json'})
    url     = f"{SPARQL_ENDPOINT}?{params}"
    req     = urllib.request.Request(
        url,
        headers={
            'User-Agent': USER_AGENT,
            'Accept':     'application/sparql-results+json',
        },
    )
    with urllib.request.urlopen(req, timeout=120) as resp:
        raw = resp.read()

    data = json.loads(raw.decode('utf-8'))
    with open(cache_path, 'w', encoding='utf-8') as f:
        json.dump(data, f)
    print(f'  Cached to {cache_path}', file=sys.stderr)

    return parse_sparql_results(data)


def build_description(c: dict) -> str:
    """Build ≤280-char description string for a composer atom."""
    name   = c['name']
    birth  = c['birth']
    death  = c['death']
    nat    = c['nationality']
    imslp  = c['imslp_title']
    qid    = c['qid']

    # Date range
    if birth and death:
        dates = f"({birth}–{death})"
    elif birth:
        dates = f"(b. {birth})"
    elif death:
        dates = f"(d. {death})"
    else:
        dates = ''

    # Source URL: prefer IMSLP, fallback Wikidata
    if imslp:
        url = IMSLP_BASE + urllib.parse.quote(imslp, safe='')
    else:
        url = WIKIDATA_BASE + qid

    parts: list[str] = [name]
    if dates:
        parts[-1] = f"{name} {dates}"
    if nat:
        parts.append(nat)
    parts.append('classical composer')
    parts.append(url)

    desc = '; '.join(parts)
    return truncate(desc, 280)


def emit_composer(fh, c: dict) -> None:
    """Write one composer atom to fh."""
    norm_name = normalize_name(c['name'])
    atom      = f"music:composer:{norm_name}"
    qid       = c['qid']
    alias     = f"music:composer:wd:{qid}"
    desc      = build_description(c)

    fh.write(f'def "{atom}" "{escape_ak(desc)}"\n')
    fh.write(f'al {atom} {alias}\n')
    fh.write('\n')


def generate(composers: list[dict], out_dir: str, chunk_size: int,
             limit: int | None, dry_run: bool) -> None:
    if limit is not None:
        composers = composers[:limit]

    total     = len(composers)
    num_files = (total + chunk_size - 1) // chunk_size if total else 0

    with_imslp = sum(1 for c in composers if c['imslp_title'])
    with_dates = sum(1 for c in composers if c['birth'] or c['death'])

    print(f'\n  Composers: {total}', file=sys.stderr)
    print(f'  With IMSLP link: {with_imslp}', file=sys.stderr)
    print(f'  With dates:      {with_dates}', file=sys.stderr)
    print(f'  Files: {num_files} × {chunk_size} → composers_{{NN}}.ak', file=sys.stderr)

    if dry_run:
        print('\n--- dry-run: first 20 output lines ---', file=sys.stderr)
        import io as _io
        buf = _io.StringIO()
        for c in composers[:5]:
            emit_composer(buf, c)
        lines = buf.getvalue().splitlines()
        for line in lines[:20]:
            print(line)
        return

    if total == 0:
        print('[wikidata_composers_import] No composers to write.', file=sys.stderr)
        return

    os.makedirs(out_dir, exist_ok=True)
    for i in range(num_files):
        chunk  = composers[i * chunk_size:(i + 1) * chunk_size]
        fname  = f"composers_{i + 1:02d}.ak"
        fpath  = os.path.join(out_dir, fname)
        start  = i * chunk_size + 1
        end    = start + len(chunk) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, comp_range=f"{start}–{end}"))
            for c in chunk:
                emit_composer(fh, c)
        print(f'  {fname}  {len(chunk):5d} composers', file=sys.stderr, flush=True)

    print(f'\n  Total: {total} composers in {num_files} files → {out_dir}/', file=sys.stderr)
    print('\nNext: git add app/ontology/music/composers_*.ak && git commit', file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json',       help='Pre-downloaded SPARQL result JSON')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--limit',      type=int, default=None,
                    help='Max composers to process (default: all)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print first 20 lines, write no files')
    args = ap.parse_args()

    print('[wikidata_composers_import] Locating composer data …', file=sys.stderr)
    try:
        composers = ensure_data(args.json)
    except urllib.error.URLError as e:
        print(f'\nError: SPARQL endpoint unreachable — {e}', file=sys.stderr)
        print('\nManual download:', file=sys.stderr)
        print('  Visit https://query.wikidata.org/', file=sys.stderr)
        print('  Paste the SPARQL query from the script\'s SPARQL_QUERY constant', file=sys.stderr)
        print('  Download result as JSON', file=sys.stderr)
        print('  Pass with: --json /path/to/composers.json', file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f'\nError: {e}', file=sys.stderr)
        print('\nManual download:', file=sys.stderr)
        print('  Visit https://query.wikidata.org/', file=sys.stderr)
        print('  Paste the SPARQL query from the script\'s SPARQL_QUERY constant', file=sys.stderr)
        print('  Download result as JSON', file=sys.stderr)
        print('  Pass with: --json /path/to/composers.json', file=sys.stderr)
        sys.exit(1)

    print(f'[wikidata_composers_import] Parsed {len(composers)} composers', file=sys.stderr)

    generate(composers, args.out, args.chunk_size, args.limit, args.dry_run)


if __name__ == '__main__':
    main()
