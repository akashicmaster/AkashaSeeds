"""
wikidata_cases_import.py — Wikidata SPARQL → app/ontology/law/cases_NN.ak

Queries Wikidata for notable court cases and landmark legal decisions and
converts results to Akasha .ak atoms for app/ontology/law/.

Filter: court cases with at least 3 Wikidata sitelinks (notable Wikipedia presence).
~1,000–5,000 records expected depending on Wikidata coverage.

Atom IDs:    law:case:{norm_name}       e.g. law:case:marbury_v_madison_1803
Aliases:     law:case:wd:{qid}          e.g. law:case:wd:Q26737

Attribution:
    Wikidata — https://www.wikidata.org/
    CC0 1.0 Universal — https://creativecommons.org/publicdomain/zero/1.0/

Usage:
    # Query Wikidata SPARQL endpoint automatically:
    python app/scripts/wikidata_cases_import.py

    # Use pre-downloaded SPARQL result JSON:
    python app/scripts/wikidata_cases_import.py --json /path/to/cases.json

    # Dry run (print first 20 lines, no files written):
    python app/scripts/wikidata_cases_import.py --dry-run

    # Override output directory:
    python app/scripts/wikidata_cases_import.py --out app/ontology/law/

Options:
    --json FILE       Pre-downloaded SPARQL result JSON
    --out DIR         Output directory (default: app/ontology/law/)
    --chunk-size N    Atoms per .ak file (default: 500)
    --limit N         Max cases to process (default: all)
    --dry-run         Print first 20 lines, write no files

Source:
    https://query.wikidata.org/sparql
    User-Agent: AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)
"""

import argparse
import json
import os
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request

SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUT  = os.path.join(PROJECT_ROOT, "app", "ontology", "law")
CACHE_DIR    = os.path.join(PROJECT_ROOT, "out", "wikidata_cases_cache")

SPARQL_ENDPOINT = "https://query.wikidata.org/sparql"
WIKIDATA_BASE   = "https://www.wikidata.org/wiki/"

USER_AGENT = "AkashaOntologyBuilder/1.0 (contact: ontology@akasha.local)"

# Primary query: cases with notable Wikipedia presence (>=3 sitelinks)
SPARQL_QUERY = """
SELECT DISTINCT ?case ?caseLabel ?courtLabel ?year ?jurisdictionLabel ?countryLabel WHERE {
  ?case wdt:P31/wdt:P279* wd:Q2669966 .
  ?case wikibase:sitelinks ?sitelinks .
  FILTER(?sitelinks >= 3)
  OPTIONAL {
    ?case wdt:P585|wdt:P577 ?date .
    BIND(YEAR(?date) AS ?year)
  }
  OPTIONAL { ?case wdt:P1001 ?jurisdiction }
  OPTIONAL { ?case wdt:P838 ?court }
  OPTIONAL { ?case wdt:P17 ?country }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
}
ORDER BY ?year ?caseLabel
LIMIT 5000
""".strip()

# Fallback query: simpler, no sitelinks filter
SPARQL_FALLBACK_QUERY = """
SELECT DISTINCT ?case ?caseLabel ?courtLabel ?year ?jurisdictionLabel ?countryLabel WHERE {
  ?case wdt:P31/wdt:P279* wd:Q2669966 .
  OPTIONAL {
    ?case wdt:P585|wdt:P577 ?date .
    BIND(YEAR(?date) AS ?year)
  }
  OPTIONAL { ?case wdt:P1001 ?jurisdiction }
  OPTIONAL { ?case wdt:P838 ?court }
  OPTIONAL { ?case wdt:P17 ?country }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en" }
  FILTER(LANG(?caseLabel) = "en")
}
ORDER BY ?year ?caseLabel
LIMIT 5000
""".strip()

FILE_HEADER = """\
# {filename}
# Wikidata — https://www.wikidata.org/ — CC0 1.0
# Landmark court cases and legal decisions
# Generated by app/scripts/wikidata_cases_import.py
# Entries: {entry_range}
#
"""

NAMESPACE_ANCHOR = """\
# Namespace anchor — landmark court cases and legal decisions
def "law:case" "Namespace anchor for landmark court decisions and legal cases"

"""


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def escape_ak(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def truncate(s: str, n: int = 280) -> str:
    if len(s) <= n:
        return s
    return s[:n - 1].rsplit(' ', 1)[0].rstrip(' ,;') + '…'


def normalize_name(name: str, max_chars: int = 70) -> str:
    """Convert case name to atom ID component (lowercase, ASCII, underscored)."""
    s = unicodedata.normalize('NFKD', name)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = s.lower()
    s = re.sub(r"[\s\-,.'()\[\]!?:;/\\&]+", '_', s)
    s = re.sub(r'[^a-z0-9_]', '', s)
    s = re.sub(r'_+', '_', s).strip('_')
    return s[:max_chars]


def extract_qid(uri: str) -> str:
    """Extract Q-number from a Wikidata entity URI like http://www.wikidata.org/entity/Q26737."""
    m = re.search(r'[/:]([Qq]\d+)$', uri)
    return m.group(1) if m else uri.strip()


def val(row: dict, field: str) -> str | None:
    """Safely extract string value from a SPARQL result binding row."""
    entry = row.get(field)
    if not entry:
        return None
    v = entry.get('value', '').strip()
    return v if v else None


def sparql_get(query: str, timeout: int = 120) -> dict:
    """Execute a SPARQL GET request; return parsed JSON. Retry once on timeout."""
    params = urllib.parse.urlencode({'query': query, 'format': 'json'})
    url    = f"{SPARQL_ENDPOINT}?{params}"
    req    = urllib.request.Request(
        url,
        headers={
            'User-Agent': USER_AGENT,
            'Accept':     'application/sparql-results+json',
        },
    )
    for attempt in range(2):
        try:
            eprint(f"  SPARQL request (attempt {attempt + 1}) …")
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                return json.loads(resp.read().decode('utf-8'))
        except Exception as e:
            if attempt == 0:
                eprint(f"  Error: {e} — retrying in 5 s …")
                time.sleep(5)
            else:
                raise
    raise RuntimeError("SPARQL query failed after 2 attempts")


def parse_bindings(bindings: list[dict]) -> list[dict]:
    """
    Collapse multi-row results (same case with multiple courts/jurisdictions)
    into one record per QID. Keep earliest year; collect court and jurisdiction.
    """
    by_qid: dict[str, dict] = {}

    for row in bindings:
        uri  = val(row, 'case')
        if not uri:
            continue
        qid  = extract_qid(uri)
        if not qid:
            continue

        label        = val(row, 'caseLabel') or ''
        court        = val(row, 'courtLabel') or ''
        jurisdiction = val(row, 'jurisdictionLabel') or ''
        country      = val(row, 'countryLabel') or ''
        year_str     = val(row, 'year') or ''

        # Skip auto-generated labels (Wikidata fallback = QID itself)
        if not label or label == qid:
            continue

        if qid in by_qid:
            rec = by_qid[qid]
            # Keep earliest year
            if year_str:
                try:
                    y = int(year_str)
                    if rec['year'] is None or y < rec['year']:
                        rec['year'] = y
                except ValueError:
                    pass
            if court and not rec['court']:
                rec['court'] = court
            if jurisdiction and not rec['jurisdiction']:
                rec['jurisdiction'] = jurisdiction
            if country and not rec['country']:
                rec['country'] = country
        else:
            year_int = None
            if year_str:
                try:
                    year_int = int(year_str)
                except ValueError:
                    pass
            by_qid[qid] = {
                'qid':          qid,
                'label':        label,
                'year':         year_int,
                'court':        court,
                'jurisdiction': jurisdiction,
                'country':      country,
            }

    eprint(f"  {len(by_qid):,} unique cases after collapsing multi-row results")

    records = list(by_qid.values())
    records.sort(key=lambda r: (r['year'] if r['year'] is not None else 9999,
                                r['label'].lower()))

    # Build unique atom keys: norm_name[_{year}] to resolve collisions
    seen_keys: dict[str, int] = {}
    for rec in records:
        base = normalize_name(rec['label'])
        yr   = str(rec['year']) if rec['year'] is not None else ''
        key  = f"{base}_{yr}" if yr else base
        if key in seen_keys:
            seen_keys[key] += 1
            key = f"{key}_{seen_keys[key]}"
        else:
            seen_keys[key] = 1
        rec['atom_key'] = key

    return records


def build_description(rec: dict) -> str:
    """Build ≤280-char description string; omit missing fields."""
    label        = rec['label']
    year         = rec['year']
    court        = rec['court']
    jurisdiction = rec['jurisdiction']
    country      = rec['country']
    qid          = rec['qid']
    url          = WIKIDATA_BASE + qid

    # Title with optional year
    title = f"{label} ({year})" if year is not None else label

    parts = [title]
    if court:
        parts.append(court)
    if jurisdiction:
        parts.append(jurisdiction)
    elif country:
        parts.append(country)
    parts.append(url)

    desc = '; '.join(parts[:-1])
    if desc:
        desc = desc + '. ' + url
    else:
        desc = url

    # Rebuild properly — join all except url with semicolons, then append url
    body_parts = [title]
    if court:
        body_parts.append(court)
    if jurisdiction:
        body_parts.append(jurisdiction)
    elif country:
        body_parts.append(country)
    body = '; '.join(body_parts)
    desc = f"{body}. {url}"

    return truncate(desc, 280)


def emit_case_block(rec: dict) -> list[str]:
    """Return list of .ak lines for one court case."""
    atom  = f"law:case:{rec['atom_key']}"
    alias = f"law:case:wd:{rec['qid']}"
    desc  = build_description(rec)
    return [
        f'def "{atom}" "{escape_ak(desc)}"',
        f'al {atom} {alias}',
        f'ln {atom} law:case sys:part_of',
        f'set.add name="ontology.law_cases" id="{atom}"',
        '',
    ]


def ensure_data(json_arg: str | None) -> list[dict]:
    """Return parsed case list from --json arg, cache, or live SPARQL query."""
    if json_arg:
        eprint(f'[wikidata_cases_import] Loading --json {json_arg} …')
        with open(json_arg, encoding='utf-8') as f:
            data = json.load(f)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f'  {len(bindings):,} rows in JSON file')
        return parse_bindings(bindings)

    os.makedirs(CACHE_DIR, exist_ok=True)
    cache_path = os.path.join(CACHE_DIR, 'cases.json')

    if os.path.exists(cache_path):
        eprint(f'[wikidata_cases_import] Using cached: {cache_path}')
        with open(cache_path, encoding='utf-8') as f:
            data = json.load(f)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f'  {len(bindings):,} rows in cache')
        return parse_bindings(bindings)

    eprint('[wikidata_cases_import] Querying Wikidata SPARQL …')
    eprint(f'  Endpoint: {SPARQL_ENDPOINT}')

    try:
        data = sparql_get(SPARQL_QUERY)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f'  Primary query returned {len(bindings):,} rows')
    except Exception as e:
        eprint(f'  Primary query failed: {e}')
        eprint('  Falling back to simpler query (no sitelinks filter) …')
        data     = sparql_get(SPARQL_FALLBACK_QUERY)
        bindings = data.get('results', {}).get('bindings', [])
        eprint(f'  Fallback query returned {len(bindings):,} rows')

    with open(cache_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    eprint(f'  Cached to {cache_path}')

    return parse_bindings(bindings)


def generate(records: list[dict], out_dir: str, chunk_size: int,
             limit: int | None, dry_run: bool) -> None:
    if limit is not None:
        records = records[:limit]

    total   = len(records)
    n_files = (total + chunk_size - 1) // chunk_size if total else 0

    with_year  = sum(1 for r in records if r['year'] is not None)
    with_court = sum(1 for r in records if r['court'])

    eprint(f'\n  Cases:      {total:,}')
    eprint(f'  With year:  {with_year:,}')
    eprint(f'  With court: {with_court:,}')
    eprint(f'  Files:      {n_files} × {chunk_size} → cases_{{NN}}.ak')

    # Build all output lines
    all_lines: list[str] = []
    for rec in records:
        all_lines.extend(emit_case_block(rec))

    if dry_run:
        print('# --- DRY RUN: first 20 output lines ---')
        count = 0
        # Include namespace anchor in preview
        for line in NAMESPACE_ANCHOR.splitlines():
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        for line in all_lines:
            if count >= 20:
                break
            print(line)
            if line.strip():
                count += 1
        return

    if total == 0:
        eprint('[wikidata_cases_import] No cases to write.')
        return

    os.makedirs(out_dir, exist_ok=True)

    # Split into per-record blocks (each terminated by a blank line)
    blocks: list[list[str]] = []
    current: list[str] = []
    for line in all_lines:
        current.append(line)
        if line == '':
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    n_chunks = (len(blocks) + chunk_size - 1) // chunk_size
    for i in range(n_chunks):
        chunk_blocks = blocks[i * chunk_size:(i + 1) * chunk_size]
        fname  = f"cases_{i + 1:02d}.ak"
        fpath  = os.path.join(out_dir, fname)
        start  = i * chunk_size + 1
        end    = start + len(chunk_blocks) - 1
        with open(fpath, 'w', encoding='utf-8') as fh:
            fh.write(FILE_HEADER.format(filename=fname, entry_range=f"{start}–{end}"))
            # Namespace anchor in first file only
            if i == 0:
                fh.write(NAMESPACE_ANCHOR)
            for block in chunk_blocks:
                fh.write('\n'.join(block) + '\n')
        eprint(f'  {fname}  {len(chunk_blocks):5d} entries', flush=True)

    eprint(f'\n  Total: {total:,} cases in {n_chunks} files → {out_dir}/')
    eprint('\nNext: git add app/ontology/law/cases_*.ak && git commit')


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument('--json',       help='Pre-downloaded SPARQL result JSON')
    ap.add_argument('--out',        default=DEFAULT_OUT,
                    help=f'Output directory (default: {DEFAULT_OUT})')
    ap.add_argument('--chunk-size', type=int, default=500,
                    help='Atoms per .ak file (default: 500)')
    ap.add_argument('--limit',      type=int, default=None,
                    help='Max cases to process (default: all)')
    ap.add_argument('--dry-run',    action='store_true',
                    help='Print first 20 lines, write no files')
    args = ap.parse_args()

    eprint('[wikidata_cases_import] Locating case data …')
    try:
        records = ensure_data(args.json)
    except urllib.error.URLError as e:
        eprint(f'\nError: SPARQL endpoint unreachable — {e}')
        eprint('\nManual download:')
        eprint('  Visit https://query.wikidata.org/')
        eprint("  Paste the SPARQL_QUERY constant from this script")
        eprint('  Download result as JSON')
        eprint('  Pass with: --json /path/to/cases.json')
        sys.exit(1)
    except Exception as e:
        eprint(f'\nError: {e}')
        eprint('\nManual download:')
        eprint('  Visit https://query.wikidata.org/')
        eprint("  Paste the SPARQL_QUERY constant from this script")
        eprint('  Download result as JSON')
        eprint('  Pass with: --json /path/to/cases.json')
        sys.exit(1)

    eprint(f'[wikidata_cases_import] Parsed {len(records):,} cases')

    generate(records, args.out, args.chunk_size, args.limit, args.dry_run)


if __name__ == '__main__':
    main()
