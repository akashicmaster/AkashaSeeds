"""The generated tables, split by owner (the purge order, ruling of 4 October, later: item 3).

Two tables are GENERATED from the manifests: the access table (method → IAM action,
`scripts/gen_kernel_methods.py`) and the CLI table (command → method, `scripts/gen_cli_table.py`).
Each generator writes two kinds of file:

- the PLATFORM's table, from the platform's manifests only, into the platform tree
  (`lib/akasha/kernel_methods.py`, `api/cli_table.py`) — listed in `PLATFORM_TREE.json`, so an
  application op never changes a platform file;
- the APPLICATION's table, from one application manifest only, written beside that manifest
  (`<package>/MANIFEST.access.json`, `<package>/MANIFEST.cli.json`) — application-owned, and
  regenerated by the application with the platform's generator, unmodified.

At import, the platform module merges in every application table through this loader. A name in
both is the error of item 1 — `TableConflict`, naming the name and both files — so the boot stops
instead of one side silently winning. With no application present (a platform-alone tree) the
platform's table is the whole table.

Dependency-free beyond the manifest path list: the CSL validator and the thin CLI load the tables
without the kernel."""
import json
import os
from typing import Any, Dict, List

ACCESS_TABLE = "MANIFEST.access.json"
CLI_TABLE = "MANIFEST.cli.json"
_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))


class TableConflict(ValueError):
    """A name both the platform's table and an application's table declare."""


def application_tables(name: str, root: str = "") -> List[str]:
    """The application tables called `name`, one beside each application (non-platform) manifest."""
    from .manifest import default_manifest_paths
    base = root or _ROOT
    out = []
    for path in default_manifest_paths(os.path.join(base, "lib", "akasha")):
        try:
            with open(path, encoding="utf-8") as fh:
                owner = json.load(fh).get("owner")
        except (OSError, ValueError):
            continue
        table = os.path.join(os.path.dirname(path), name)
        if owner != "platform" and os.path.isfile(table):
            out.append(table)
    return out


def merged(platform: Dict[str, Any], name: str, key: str, root: str = "") -> Dict[str, Any]:
    """`platform` plus the `key` section of every application table called `name`. A key present
    on both sides (or in two application tables) raises `TableConflict`, naming it."""
    out = dict(platform)
    seen = {k: "the platform's table" for k in platform}
    for path in application_tables(name, root):
        with open(path, encoding="utf-8") as fh:
            section = (json.load(fh).get(key) or {})
        rel = os.path.relpath(path, root or _ROOT)
        for k, v in section.items():
            if k in seen:
                raise TableConflict("%r is declared in %s and in %s — a name is declared once"
                                    % (k, seen[k], rel))
            seen[k] = rel
            out[k] = v
    return out
