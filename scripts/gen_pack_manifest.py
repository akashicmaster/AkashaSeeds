#!/usr/bin/env python3
# Generate docs/ontology/pack-manifest.md — the ontology package inventory with
# per-pack .ak file and step counts (step = one executable .ak statement:
# def / ln / al / set.add). Re-run to refresh after editing packs.
#
# The packs are every root's REGISTRY (the platform's ontology/, then the application's) — read through
# the loader, so the inventory is what a boot loads. Nothing here names a pack: what a series autoloads
# beyond the registry's autoload flags comes from the application's series declaration.
import json, os, glob, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.chdir(ROOT)
from lib.akasha.ontology.loader import registry_packages
from lib.akasha.api import reserved as _reserved

CMD_DEF = ("def", "define")
def stats(pdir):
    files = sorted(glob.glob(os.path.join(pdir, "*.ak")))
    d = l = a = s = 0
    for f in files:
        for raw in open(f, encoding="utf-8", errors="replace"):
            t = raw.strip()
            if not t or t.startswith("#"):
                continue
            c = t.split(None, 1)[0].lower()
            if c in CMD_DEF:   d += 1
            elif c == "ln":    l += 1
            elif c in ("al", "alias"): a += 1
            elif c == "set.add": s += 1
    return len(files), d, l, a, s, d + l + a + s

def label(pdir):
    # Prefer the English `description`; the `label` field is often localized.
    p = os.path.join(pdir, "PACK.json")
    if os.path.isfile(p):
        try:
            m = json.load(open(p))
            return m.get("description", "") or m.get("label", "")
        except Exception:
            return ""
    return ""

rows = []
for pk in registry_packages():
    if pk.get("user"):
        continue                                  # a cell operator's own pack is not shipped
    n, pdir = pk["name"], pk["_dir"]
    fl, d, l, a, s, st = stats(pdir)
    rows.append((n, bool(pk.get("autoload", False)), fl, d, l, a, s, st, label(pdir),
                 str(pk.get("tier") or "")))

# What a series autoloads beyond the autoload flags (`autoload_packs` in the series declaration).
SERIES_EXTRA = {}
try:
    _sd = json.load(open(_reserved.root("series"), encoding="utf-8"))
    _sd = _sd.get("series", _sd)
    for _name, _s in (_sd.items() if isinstance(_sd, dict) else []):
        if isinstance(_s, dict) and _s.get("autoload_packs"):
            SERIES_EXTRA[_name] = list(_s["autoload_packs"])
except (OSError, ValueError):
    pass

auto = [r for r in rows if r[1]]
opt  = [r for r in rows if not r[1]]
def subtotal(rs, i): return sum(r[i] for r in rs)

def fmt(n): return f"{n:,}" if n else "—"

# Tier C (deep reference layers) is not bundled on the seeds line; every other pack is bundled on
# both. Startup then differs: seeds loads the autoload packs (+ its series' extra autoload packs) and
# leaves the rest opt-in; the thesaurus tier's load_all loads every pack.
def seeds_unbundled(r): return r[9] == "C"
def seeds_mark(r):
    if seeds_unbundled(r): return "–"
    return "●" if r[1] else "○"
def thes_mark(r):
    return "●"

def rowline(r):
    n, au, fl, d, l, a, s, st, lab, _tier = r
    return (f"| {n} | {seeds_mark(r)} | {thes_mark(r)} | {fl or '—'} | "
            f"{fmt(d)} | {fmt(l)} | {fmt(a)} | {fmt(s)} | **{fmt(st)}** | {lab[:38]} |")

# ── estimate load time (empirically ~40 steps/s on the reference VM) ──
RATE = 40
tier_c        = [r for r in rows if seeds_unbundled(r)]
seeds_startup = subtotal([r for r in auto if not seeds_unbundled(r)], 7)
seeds_full    = subtotal([r for r in rows if not seeds_unbundled(r)], 7)
thes_full     = subtotal(rows, 7)
grand         = thes_full
def mins(steps): return round(steps / RATE / 60)

L = []
L.append("# Ontology Package Manifest")
L.append("")
L.append("> Auto-generated by `scripts/gen_pack_manifest.py` — re-run to refresh after editing packs.")
L.append("")
L.append("A **step** is one executable `.ak` statement — `def` (define an atom), `ln` (typed")
L.append("link), `al` (alias), or `set.add` (add to a collection). Comments and blank lines")
L.append("are excluded. Steps map one-to-one onto the JCL job steps the loader executes, so")
L.append("the step count is a direct measure of how much work a pack costs to load.")
L.append("")
L.append("**Load behaviour differs by edition** — the two columns show what happens at startup:")
L.append("")
L.append("- **Seeds** — `●` loads at startup (an autoload pack) · `○` bundled but OFF, enable with")
L.append("  `onto.pack.enable name=<pack>` · `–` not shipped on the seeds line (a tier-C deep")
L.append("  reference layer). A series may autoload more packs than the `●` ones — see *Notes*.")
L.append("- **Thesaurus** — `●` every pack loads automatically at startup (the `load_all` flag,")
L.append("  in REGISTRY order); there is no opt-in step.")
L.append("")
L.append("## Packages (load order: the platform's `ontology/`, then `app/ontology/`)")
L.append("")
L.append("| pack | Seeds | Thes. | files | def | ln | al | set | steps | content |")
L.append("|---|:--:|:--:|--:|--:|--:|--:|--:|--:|---|")
for r in rows:
    L.append(rowline(r))
L.append("")
L.append("## Totals")
L.append("")
L.append("| group | files | steps |")
L.append("|---|--:|--:|")
L.append(f"| Seeds startup (autoload packs, no tier C) | {subtotal([r for r in auto if not seeds_unbundled(r)],2)} | **{fmt(seeds_startup)}** |")
L.append(f"| opt-in packs (Seeds: on demand) | {subtotal([r for r in opt if not seeds_unbundled(r)],2)} | **{fmt(subtotal([r for r in opt if not seeds_unbundled(r)],7))}** |")
L.append(f"| tier C (thesaurus tier only) | {subtotal(tier_c,2)} | **{fmt(subtotal(tier_c,7))}** |")
L.append(f"| **Thesaurus full load (every pack)** | **{subtotal(rows,2)}** | **{fmt(thes_full)}** |")
L.append("")
L.append("## Approximate load time")
L.append("")
L.append(f"At the reference rate of ~{RATE} steps/second (single-thread serial write path,")
L.append("measured on the soak-test VM). A small host is slower — a first seeds load of about an hour")
L.append("has been measured on one; `onto.status` shows the progress:")
L.append("")
L.append("| edition · scenario | steps | ~time |")
L.append("|---|--:|--:|")
L.append(f"| **Seeds** startup (autoload packs only) | {fmt(seeds_startup)} | ~{mins(seeds_startup)} min |")
L.append(f"| **Seeds** + all opt-in packs enabled | {fmt(seeds_full)} | ~{mins(seeds_full)} min |")
L.append(f"| **Thesaurus** startup = full load (every pack, incl. tier C) | {fmt(thes_full)} | ~{mins(thes_full)} min |")
L.append("")
L.append("## Notes")
L.append("")
L.append("- **Autoload packs:** " + ", ".join(f"`{r[0]}`" for r in auto) + ".")
for _sn, _extra in sorted(SERIES_EXTRA.items()):
    L.append(f"- **The `{_sn}` series also autoloads** " + ", ".join(f"`{x}`" for x in _extra)
             + " (its `autoload_packs`).")
_empty = [r[0] for r in rows if not r[2]]
if _empty:
    L.append("- **Zero-file packs** (" + ", ".join(_empty) + ") are registered but carry no `.ak`")
    L.append("  data, so they cost 0 steps even under `load_all`.")
L.append("- **Your own packs** (`ontology/user/<name>/`, a `PACK.json` and its `.ak` files) are not")
L.append("  listed here: they are the cell's, never shipped. They load after these, at the next start.")
L.append("- Loading is idempotent and content-addressed: enabling an overlapping pack never")
L.append("  creates duplicates.")
L.append("")
open("docs/ontology/pack-manifest.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote docs/ontology/pack-manifest.md")
print(f"  {len(rows)} packs, {subtotal(rows,2)} files, grand total {grand:,} steps")
