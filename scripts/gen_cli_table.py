#!/usr/bin/env python3
"""Generate `api/cli_table.py` — the CLI command → JSON-RPC method table — from the package
manifests (group 4, 4.6).

The router's command table used to be ~440 hand-written entries in `api/router.py`, so the CLI
named every application method the platform had ever served, and a command's spelling lived apart
from the op it reached. It is now DERIVED, the way `kernel_methods.py` is: a command is declared
once, as the `cli` attribute of the op it dispatches, in the manifest of the package that owns it.

    "ops": {"kernel.memory.write": {"fn": "…", "stage": "pre", "access": "record",
                                    "cli": {"w": {"args": ["text"],
                                                  "desc": "Write an atom into memory"}}}}

`cli` maps each command spelling to its positional `args` and its help `desc`; the method is the
op itself, so a command can never point at an op that does not exist. An op may carry several
spellings (`dive` / `look` / `d`).

Concept Models the registry discovers derive their own specs from `CONCEPT_METHODS` at runtime.
The application's commands are declared on its ops the same way (the owed data file closed at 0
on 10-02 and was deleted).

SPLIT BY OWNER (rulings of 4 October). The PLATFORM's commands are written from the platform's
manifests only (`owner: platform`, every manifest outside the application root) to
`api/cli_table.py`, which is in `PLATFORM_TREE.json`, so the platform's CLI never depends on an
application declaring a platform command and an application op never changes a platform file. Each
APPLICATION manifest's commands are written from that manifest only, beside it, as
`MANIFEST.cli.json` — application-owned, regenerated by the application with this generator,
unmodified. A name declared on both sides (an op, a command spelling, or a help group with a
different label) is a generation error — a help group whose label repeats the platform's word for
word is omitted from the application table and reported as redundant; at import `api/cli_table.py` merges the application tables through
`lib.akasha.api.tables`, where a name in both is a boot error. With no application present the
table still holds every platform command (`platform_alone_eval` checks it).

    python scripts/gen_cli_table.py            # regenerate, report the diff
    python scripts/gen_cli_table.py --check    # exit 1 if the file is stale (no write)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "api", "cli_table.py")
APP_TABLE = "MANIFEST.cli.json"             # = lib.akasha.api.tables.CLI_TABLE


def manifests():
    """[(package, relpath, owner)] — every manifest the aggregator reads, the platform's first."""
    sys.path.insert(0, ROOT)
    from lib.akasha.api import manifest as M
    rows = []
    for path in M.default_manifest_paths(os.path.join(ROOT, "lib", "akasha")):
        man = json.load(open(path, encoding="utf-8"))
        rows.append((str(man.get("package") or "?"), os.path.relpath(path, ROOT),
                     str(man.get("owner") or "user")))
    return [r for r in rows if r[2] == "platform"] + [r for r in rows if r[2] != "platform"]

HEADER = '''"""
CLI command → JSON-RPC method table — the PLATFORM's commands, plus the application's at import.

GENERATED FILE — do not edit. Regenerate with:

    python scripts/gen_cli_table.py

The source is the `cli` attribute of each op in each PLATFORM manifest: a command is declared beside
the op it dispatches, by the package that owns the op (group 4, 4.6). The application's commands are
in its own generated table (`MANIFEST.cli.json` beside its manifest), merged in below by
`lib.akasha.api.tables`; a name in both is a boot error. Read by `api/router.py`, which adds the
Concept Models' registry-derived specs at runtime.

Imports only the table loader — the thin CLI client loads it without the kernel.
"""

PLATFORM_CLI_SPECS = {
'''

FOOTER = '''
# The application's tables, merged in (a name in both raises TableConflict — a boot error by name).
from lib.akasha.api.tables import merged as _merged, CLI_TABLE as _CLI_TABLE   # noqa: E402

CLI_SPECS = _merged(PLATFORM_CLI_SPECS, _CLI_TABLE, "specs")
CLI_GROUPS = _merged(PLATFORM_CLI_GROUPS, _CLI_TABLE, "groups")
'''

APP_HEADER = ("GENERATED by scripts/gen_cli_table.py from the MANIFEST.json beside it — do not edit; "
              "regenerate with the platform's generator, unmodified. command → method for this "
              "manifest's ops, and its help groups; the platform merges it into its CLI table at import.")


REDUNDANT_GROUPS = []          # (application manifest, group) repeating the platform's label word for word


def collect():
    """(platform rows per manifest, the platform's flat table, the platform's help groups,
    {app manifest relpath: (rows, groups)}). A name declared twice — an op, a command spelling or
    a help group, on either side — is a generation error."""
    per, flat, groups, apps = [], {}, {}, {}
    op_owner, cmd_owner, group_owner = {}, {}, {}
    redundant = REDUNDANT_GROUPS
    del redundant[:]
    for pkg, rel, owner in manifests():
        rows, mgroups = [], {}
        man = json.load(open(os.path.join(ROOT, rel), encoding="utf-8"))
        for g, label in (man.get("cli_groups") or {}).items():
            if g in group_owner and group_owner[g] != rel:
                if owner != "platform" and groups.get(g) == str(label):
                    redundant.append((rel, g))       # the platform's own label, repeated: omitted
                    continue
                raise SystemExit("help group %r is labelled twice: %s and %s — a name is declared once"
                                 % (g, group_owner[g], rel))
            group_owner[g] = rel
            mgroups[g] = str(label)
        for method, spec in (man.get("ops") or {}).items():
            if method in op_owner and op_owner[method] != rel:
                raise SystemExit("op %r is declared twice: %s and %s — a name is declared once"
                                 % (method, op_owner[method], rel))
            op_owner[method] = rel
            cli = spec.get("cli") if isinstance(spec, dict) else None
            if not cli:
                continue
            if not isinstance(cli, dict):
                raise SystemExit("%s ops.%s: `cli` must map each command to {args, desc}" % (rel, method))
            for cmd, c in cli.items():
                c = c or {}
                if cmd in cmd_owner:
                    raise SystemExit("command %r is declared twice: %s (%s) and %s (%s)"
                                     % (cmd, cmd_owner[cmd][1], cmd_owner[cmd][0], method, rel))
                cmd_owner[cmd] = (rel, method)
                row = {"method": method}
                if "args" in c:
                    row["args"] = list(c.get("args") or [])
                if "desc" in c:
                    row["desc"] = str(c.get("desc") or "")
                if c.get("group"):
                    row["group"] = str(c["group"])
                rows.append((cmd, row))
        if owner == "platform":
            per.append((pkg, rel, rows))
            flat.update(rows)
            groups.update(mgroups)
        else:
            apps[rel] = (rows, mgroups)
    return per, flat, groups, apps


def render(per, groups):
    out = [HEADER]
    for pkg, rel, rows in per:
        if not rows:
            continue
        out.append("    # ── %s (%s) — %d commands ──\n" % (pkg, rel, len(rows)))
        for cmd, row in rows:
            out.append("    %s: %s,\n" % (json.dumps(cmd, ensure_ascii=False),
                                          json.dumps(row, ensure_ascii=False)))
        out.append("\n")
    if out[-1] == "\n":
        out.pop()
    out.append("}\n\n")
    out.append("# help group → its one-line label, for groups no Concept Model class labels itself\n")
    out.append("PLATFORM_CLI_GROUPS = {\n")
    for g in sorted(groups):
        out.append("    %s: %s,\n" % (json.dumps(g), json.dumps(groups[g], ensure_ascii=False)))
    out.append("}\n")
    out.append(FOOTER)
    return "".join(out)


def app_path(rel):
    return os.path.join(ROOT, os.path.dirname(rel), APP_TABLE)


def render_app(rows, groups):
    """The application table for one manifest, or None when it declares no command and no group."""
    if not rows and not groups:
        return None
    return json.dumps({"_": APP_HEADER, "specs": {c: r for c, r in rows},
                       "groups": dict(sorted(groups.items()))}, indent=1, ensure_ascii=False) + "\n"


def main():
    check = "--check" in sys.argv
    per, flat, groups, apps = collect()
    text = render(per, groups)
    old = open(TARGET, encoding="utf-8").read() if os.path.isfile(TARGET) else ""
    prev = set()
    if old:
        import re as _re
        prev = set(_re.findall(r'^    ("[^"]+"): \{', old.split("\n}\n", 1)[0], _re.M))
        prev = {json.loads(p) for p in prev}
    added = sorted(k for k in flat if k not in prev)
    removed = sorted(k for k in prev if k not in flat)
    print("platform manifests declare %d CLI commands (%d manifests); application: %s"
          % (len(flat), len(per), ", ".join("%s=%d" % (r, len(v[0])) for r, v in sorted(apps.items()))
                                    or "-"))
    print("  platform table — added: %d   removed: %d" % (len(added), len(removed)))
    if REDUNDANT_GROUPS:
        print("  redundant: %s repeat the platform's help-group label word for word — omitted from "
              "the application table; delete them" % ", ".join("%s cli_groups.%s" % rg
                                                              for rg in REDUNDANT_GROUPS))
    for label, d in (("added", added), ("removed", removed)):
        if d:
            print("  %s: %s" % (label, ", ".join(d[:20]) + (" …" if len(d) > 20 else "")))
    app_files = {app_path(rel): render_app(*v) for rel, v in apps.items()}
    if check:
        stale = [os.path.relpath(TARGET, ROOT)] if text != old else []
        for path, want in sorted(app_files.items()):
            have = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            if have != want:
                stale.append(os.path.relpath(path, ROOT))
        if stale:
            print("STALE — run: python scripts/gen_cli_table.py (%s)" % ", ".join(stale))
            sys.exit(1)
        print("up to date")
        return
    if text != old:
        with open(TARGET, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(TARGET, ROOT))
    for path, want in sorted(app_files.items()):
        have = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if want is None and have is not None:
            os.remove(path)
            print("removed %s (its manifest declares no command)" % os.path.relpath(path, ROOT))
        elif want is not None and have != want:
            with open(path, "w", encoding="utf-8") as f:
                f.write(want)
            print("wrote %s" % os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
