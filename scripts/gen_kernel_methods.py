#!/usr/bin/env python3
"""Generate `lib/akasha/kernel_methods.py` — the kernel method → IAM action table — from the
package manifests (backend layout order 2026-09-20 §2).

The access table used to be hand-edited, so a new method's gate was a second place to remember
and the table drifted from what actually dispatches. It is now DERIVED: every method's action is
declared once, in the `ops` block of the manifest of the package that owns it.

    "ops": {"bench.info": {"fn": "lib.akasha.workbench.bench:op_info",
                           "stage": "post", "access": "read"}}

An entry with an `access` but no `fn` is an ACCESS-ONLY declaration: the method is dispatched by
a router (the Concept Model registry) while its package still declares the gate. An entry whose
`access` is null has no capability mapping at all — a pre-auth op gated by its dispatch stage
(`auth.*`, `sys.ping`, `kernel.genesis_rite`), or a spelling that is not reachable over RPC.

SPLIT BY OWNER (ruling of 4 October, later: items 2 and 3). The PLATFORM's table is written from
the platform's manifests only (`owner: platform`, every manifest outside the application root)
to `lib/akasha/kernel_methods.py`, which is in `PLATFORM_TREE.json`. Each APPLICATION manifest's
table is written from that manifest only, beside it, as `MANIFEST.access.json` — application-owned,
regenerated by the application with this generator, unmodified. A method declared on both sides is a
generation error; at import the platform module merges the application tables through
`lib.akasha.api.tables`, where a name in both is a boot error.

The emitted module imports only `typing` and that loader, so `lib/akasha/csl/validator.py` can load
it without pulling in the kernel.

    python scripts/gen_kernel_methods.py            # regenerate, report the diff
    python scripts/gen_kernel_methods.py --check    # exit 1 if the file is stale (no write)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "lib", "akasha", "kernel_methods.py")
APP_TABLE = "MANIFEST.access.json"          # = lib.akasha.api.tables.ACCESS_TABLE


def manifests():
    """[(package, relpath, owner)] — every manifest the aggregator reads, the platform's first."""
    sys.path.insert(0, ROOT)
    from lib.akasha.api import manifest as M
    rows = []
    for path in M.default_manifest_paths(os.path.join(ROOT, "lib", "akasha")):
        man = json.load(open(path, encoding="utf-8"))
        rows.append((str(man.get("package") or "?"), os.path.relpath(path, ROOT),
                     str(man.get("owner") or "user")))
    return [r for r in rows if r[2] == "platform"] + [r for r in rows if r[2] != "platform"]

HEADER = '''"""
Kernel method → IAM action mapping — the PLATFORM's table, plus the application's at import.

GENERATED FILE — do not edit. Regenerate with:

    python scripts/gen_kernel_methods.py

The source is the `ops` block of each PLATFORM manifest: every method declares its action
(`access`) beside the function that serves it, so a method's gate lives in one place. A method
whose `access` is null has no capability mapping — it is a pre-auth op gated by its dispatch
stage, or a spelling that is not reachable over RPC — and is therefore absent from this table.
The application's methods are in its own generated table (`MANIFEST.access.json` beside its
manifest), merged in below by `lib.akasha.api.tables`; a method in both is a boot error.

Read by:
  lib/akasha/kernel.py        — the capability gate in the authenticated dispatch
  lib/akasha/csl/validator.py — static CSL method validation (loads this module alone)
  api/portals/cell_ipc.py     — the split gateway's read/write routing

Imports only `typing` and the table loader, so the validator can load it without pulling in the
kernel import chain.
"""
from typing import Dict

PLATFORM_METHOD_TO_ACTION: Dict[str, str] = {
'''

FOOTER = '''
# The application's tables, merged in (a method in both raises TableConflict — a boot error by name).
from lib.akasha.api.tables import merged as _merged, ACCESS_TABLE as _ACCESS_TABLE   # noqa: E402

METHOD_TO_ACTION: Dict[str, str] = _merged(PLATFORM_METHOD_TO_ACTION, _ACCESS_TABLE, "access")
'''

APP_HEADER = ("GENERATED by scripts/gen_kernel_methods.py from the MANIFEST.json beside it — do not "
              "edit; regenerate with the platform's generator, unmodified. method → IAM action for "
              "this manifest's ops; the platform merges it into its access table at import.")


def collect():
    """(platform rows per manifest, the platform's flat mapping, {app manifest relpath: mapping}).
    A method declared on both sides — or by two application manifests — is a generation error."""
    per, flat, apps, owner_of = [], {}, {}, {}
    for pkg, rel, owner in manifests():
        rows = []
        ops = (json.load(open(os.path.join(ROOT, rel), encoding="utf-8")).get("ops") or {})
        for name, spec in ops.items():
            spec = {"fn": spec} if isinstance(spec, str) else spec
            if name in owner_of and owner_of[name] != rel:
                raise SystemExit("method %r is declared twice: %s and %s — a name is declared once"
                                 % (name, owner_of[name], rel))
            owner_of[name] = rel
            action = spec.get("access")
            if not action:
                continue                      # no capability mapping — stage-gated or unreachable
            if owner == "platform":
                if name in flat and flat[name] != action:
                    raise SystemExit("conflicting access for %r: %r vs %r" % (name, flat[name], action))
                if name not in flat:
                    rows.append((name, action))
                flat[name] = action
            else:
                apps.setdefault(rel, {})[name] = action
        if owner == "platform":
            per.append((pkg, rel, rows))
        else:
            apps.setdefault(rel, apps.get(rel, {}))
    return per, flat, apps


def render(per):
    out = [HEADER]
    for pkg, rel, rows in per:
        if not rows:
            continue
        out.append("    # ── %s (%s) — %d methods ──\n" % (pkg, rel, len(rows)))
        width = max(len(n) for n, _ in rows) + 3
        for name, action in rows:
            out.append('    %-*s %s,\n' % (width, '"%s":' % name, '"%s"' % action))
        out.append("\n")
    if out[-1] == "\n":
        out.pop()
    out.append("}\n")
    out.append(FOOTER)
    return "".join(out)


def app_path(rel):
    return os.path.join(ROOT, os.path.dirname(rel), APP_TABLE)


def render_app(mapping):
    """The application table for one manifest, or None when it maps no method (no file)."""
    if not mapping:
        return None
    return json.dumps({"_": APP_HEADER, "access": dict(sorted(mapping.items()))},
                      indent=1, ensure_ascii=False) + "\n"


def main():
    check = "--check" in sys.argv
    per, flat, apps = collect()
    text = render(per)
    old = open(TARGET, encoding="utf-8").read() if os.path.isfile(TARGET) else ""

    # Compare MEANING, not bytes: the platform table the old file defines vs the one the manifests
    # declare.
    prev = {}
    if old:
        import re as _re
        prev = dict(_re.findall(r'^\s+"([^"]+)":\s+"([^"]+)",$', old.split("\n}\n", 1)[0], _re.M))
    added = {k: flat[k] for k in flat if k not in prev}
    removed = {k: prev[k] for k in prev if k not in flat}
    changed = {k: (prev[k], flat[k]) for k in flat if k in prev and prev[k] != flat[k]}
    print("platform manifests declare %d methods with an action (%d manifests); application: %s"
          % (len(flat), len(per), ", ".join("%s=%d" % (r, len(m)) for r, m in sorted(apps.items())) or "-"))
    print("  added: %d   removed: %d   changed: %d" % (len(added), len(removed), len(changed)))
    for label, d in (("added", added), ("removed", removed), ("changed", changed)):
        if d:
            print("  %s: %s%s" % (label, sorted(d)[:12], " …" if len(d) > 12 else ""))

    app_files = {app_path(rel): render_app(m) for rel, m in apps.items()}
    if check:
        stale = [os.path.relpath(TARGET, ROOT)] if text != old else []
        for path, want in sorted(app_files.items()):
            have = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            if have != want:
                stale.append(os.path.relpath(path, ROOT))
        print(("STALE — regenerate: %s" % ", ".join(stale)) if stale else "up to date")
        sys.exit(1 if stale else 0)
    if text != old:
        open(TARGET, "w", encoding="utf-8").write(text)
        print("wrote %s (%d lines)" % (TARGET, text.count("\n")))
    for path, want in sorted(app_files.items()):
        have = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if want is None and have is not None:
            os.remove(path)
            print("removed %s (its manifest maps no method)" % os.path.relpath(path, ROOT))
        elif want is not None and have != want:
            open(path, "w", encoding="utf-8").write(want)
            print("wrote %s (%d methods)" % (os.path.relpath(path, ROOT), want.count('": "') - 1))


if __name__ == "__main__":
    main()
