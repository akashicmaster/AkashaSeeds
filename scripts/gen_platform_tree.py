#!/usr/bin/env python3
"""
PLATFORM_TREE.json — every platform file with its hash, and the tree hash (platform-spec v1,
"Platform release"). The platform is EVERYTHING outside the application root (`app/`): every file
the repository tracks there, except build output (`akasha_seeds_*.py`), the handoff notes
(`docs/handoff/` — correspondence, not the platform) and this file itself. A
platform release carries it; an application verifies against it and fails on any difference, so an
application change can never edit the platform by accident.

    python scripts/gen_platform_tree.py           write PLATFORM_TREE.json
    python scripts/gen_platform_tree.py --check   exit 1 if it is stale (manifest_eval runs this)
"""
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "PLATFORM_TREE.json")


# Handoff notes are correspondence to the librarian, not the platform: a note written after a release
# must not change the released tree.
NOTES = "docs/handoff/"


def platform_files():
    sys.path.insert(0, ROOT)
    from lib.akasha.api import reserved as R
    files = subprocess.run(["git", "-C", ROOT, "ls-files", "-co", "--exclude-standard"],
                           capture_output=True, text=True).stdout.split()
    out = []
    for f in files:
        if f == "PLATFORM_TREE.json" or f.startswith(NOTES) or "__pycache__" in f or f.endswith(".pyc") \
                or (f.startswith("akasha_seeds_") and f.endswith(".py")) \
                or not os.path.isfile(os.path.join(ROOT, f)) or R.is_app_path(f):
            continue
        out.append(f)
    return sorted(out)


def build():
    files = {}
    for f in platform_files():
        with open(os.path.join(ROOT, f), "rb") as fh:
            files[f] = hashlib.sha256(fh.read()).hexdigest()
    tree = hashlib.sha256("".join("%s\0%s\n" % kv for kv in sorted(files.items())).encode()).hexdigest()
    return {"_": "Every platform file (everything outside the application root) and its sha256, and "
                 "the tree hash (platform-spec v1, 'Platform release'). "
                 "Generated by scripts/gen_platform_tree.py; never edit by hand.",
            "tree_hash": tree, "count": len(files), "files": files}


def main():
    doc = build()
    text = json.dumps(doc, indent=1, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        try:
            cur = open(OUT, encoding="utf-8").read()
        except OSError:
            cur = ""
        if cur != text:
            try:
                old = json.loads(cur).get("files") or {}
            except ValueError:
                old = {}
            new = doc["files"]
            diff = sorted(set(old) ^ set(new)) + sorted(f for f in new if f in old and old[f] != new[f])
            print("STALE — run: python scripts/gen_platform_tree.py  (%d differ, e.g. %s)"
                  % (len(diff), ", ".join(diff[:5])))
            sys.exit(1)
        print("up to date (tree %s, %d files)" % (doc["tree_hash"][:12], doc["count"]))
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote PLATFORM_TREE.json (tree %s, %d files)" % (doc["tree_hash"][:12], doc["count"]))


if __name__ == "__main__":
    main()
